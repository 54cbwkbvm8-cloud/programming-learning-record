while True:  # 无限循环，直到登录成功才退出
    name = input("请输入你的用户名")  # 提示用户输入用户名

    if name == "":  # 如果用户名为空
        print("用户名为空 请重新输入密码")  # 提示用户名不能为空
        continue  # 结束本次循环，回到开头重新输入

    password = input("请输入你的密码")  # 提示用户输入密码

    if name == "zach" and password == "123456":  # 判断用户名和密码是否都正确
        print("登录成功")  # 都正确时打印登录成功
        break  # 跳出循环，程序结束

    print("请检查用户名或者密码是否正确")  # 否则提示重新检查用户名或密码
