public class Student {
    int id;
    String name;
    double score;

    public Student() {
    }

    public Student(int id, String name, double score) {
        this.id = id;
        this.name = name;
        this.score = score;
    }

    public void printInfo() {
        System.out.println("学号：" + id + " 姓名：" + name + " 成绩：" + score);
    }
}
