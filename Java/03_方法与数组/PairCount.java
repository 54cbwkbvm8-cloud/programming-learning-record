import java.util.Scanner;

public class PairCount {
    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        int n = sc.nextInt();
        int target = sc.nextInt();
        int[] a = new int[n];
        for (int i = 0; i < n; i++) {
            a[i] = sc.nextInt();
        }
        long count = 0;
        for (int i = 0; i < n; i++) {
            for (int j = i + 1; j < n; j++) {
                if (((long) a[i] + a[j]) == target) {
                    count++;
                }
            }
        }
        System.out.println(count);
        sc.close();
    }
}
