import java.util.Scanner;

public class P03_CountLetters {
    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        String s = "";
        if (sc.hasNextLine()) {
            s = sc.nextLine();
        }
        int total = 0;
        int[] count = new int[26];
        for (int i = 0; i < s.length(); i++) {
            char ch = s.charAt(i);
            if (ch >= 'a' && ch <= 'z') {
                total++;
                count[ch - 'a']++;
            } else if (ch >= 'A' && ch <= 'Z') {
                total++;
                count[ch - 'A']++;
            }
        }
        System.out.println(total);
        for (int k = 0; k < 26; k++) {
            if (count[k] > 0) {
                System.out.println((char) ('a' + k) + ": " + count[k]);
            }
        }
        sc.close();
    }
}




