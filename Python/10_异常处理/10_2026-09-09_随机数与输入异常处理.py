"""
简介：导入 random 模块生成随机数并持续接收用户猜测。
功能：
- 随机生成 1 到 100 之间的目标数字。
- 反复提示用户输入猜测。
- 使用异常处理识别非数字输入。
用途：练习模块导入、随机数、循环和 ValueError 异常处理。
最后修改：2026-09-09
"""
# 文件用途：本文件围绕“随机数与输入异常处理”展开。
# 核心知识点：循环、分支判断、异常处理。
# 基本流程：根据代码中的输入或初始数据，按条件、循环和函数调用完成处理，再输出结果。
# 输入：从标准输入读取数据或由调用者传入参数。输出：通过控制台打印处理结果。
# 阅读提醒：异常分支是否覆盖所有错误情况，应结合具体输入和运行环境判断。
# 模块依赖：random。
print("简单小任务")  # 打印提示信息
import random  # 导入 random 模块，用于生成随机数
num = random.randint(1,100)  # 随机生成一个 1～100（含两端）之间的整数
print(num)  # 打印这个随机数，方便用户对照
while True:  # 无限循环，直到用户输对才退出
    try:  # 尝试执行可能出错的代码
        nums = int(input("请输入生成的随机阿拉伯数字到对话框中"))  # 接收输入并转成整数
        if nums == num:  # 如果输入的数字等于随机数
            print(f"你输入的是{nums},很好已经完成任务了")  # 用 f-string 提示已经完成
        else:  # 否则输入的数字不对
            print("请输入正确的随机数字哦")  # 提示输入正确的数字
    # 捕获前面 try 代码块中符合条件的异常；变量名（如有）用于接收异常对象。
    except ValueError:  # 若输入的不是整数（例如字母），捕获 ValueError
        print("输入错误，注意！！我要的是数字")  # 提示必须输入数字
