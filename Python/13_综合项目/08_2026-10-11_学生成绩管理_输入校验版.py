"""
简介：带完整输入校验的学生成绩管理系统，先确定人数再逐个录入。
功能：
- 校验学生人数必须是大于 0 的整数，不合法就要求重新输入。
- 逐个校验学生成绩必须是 0 到 100 之间的整数。
- 输出全部学生及等级、成绩最好的学生、成绩总和和平均分。
用途：练习输入校验、字典列表、max 配合 key 取最高分和字符串格式化。
最后修改：2026-10-11
"""
# 文件用途：本文件围绕“学生成绩管理 输入校验版”展开。
# 核心知识点：列表与字典、字符串、函数、循环、分支判断。
# 基本流程：根据代码中的输入或初始数据，按条件、循环和函数调用完成处理，再输出结果。
# 输入：从标准输入读取数据或由调用者传入参数。输出：通过控制台打印处理结果。
# 阅读提醒：检查列表/序列的下标范围、字符串处理结果及空数据情况。
# 创建空列表 `students`，后续把逐步处理得到的记录或结果追加到其中。
students = []
# 定义函数 `get_level`，用于根据分数或数据返回对应等级；参数包括 score，函数体负责具体处理，调用处应关注传入参数和返回值。
def get_level(score):
    # 判断条件 `score >= 90`；条件为真时执行 if 分支，否则按后续 elif/else 分支处理。
    if score >= 90:
        # 返回字符串 `A`，调用方可以把它保存到变量或继续用于判断。
        return 'A'
    # 判断条件 `score >= 80`；条件为真时执行 if 分支，否则按后续 elif/else 分支处理。
    elif score >= 80:
        # 返回字符串 `B`，调用方可以把它保存到变量或继续用于判断。
        return 'B'
    # 判断条件 `score >= 70`；条件为真时执行 if 分支，否则按后续 elif/else 分支处理。
    elif score >= 70:
        # 返回字符串 `C`，调用方可以把它保存到变量或继续用于判断。
        return 'C'
    # 判断条件 `score >= 60`；条件为真时执行 if 分支，否则按后续 elif/else 分支处理。
    elif score >= 60:
        # 返回字符串 `D`，调用方可以把它保存到变量或继续用于判断。
        return 'D'
    # 当前条件分支的前置条件均未成立时，执行这个 else 代码块。
    else:
        # 返回字符串 `E`，调用方可以把它保存到变量或继续用于判断。
        return 'E'
# 把括号中的内容输出到控制台；字符串中的 `{}`、`%s` 或 `%d` 等格式占位符应与传入的数据类型匹配。
print("="*10,"学生成绩管理系统", "="*10)
# 进入持续循环；必须通过循环体中的 `break`、`return` 或异常等方式结束，通常用于反复读取并校验输入。
while True:
    # 调用 `input()` 显示提示并读取用户输入，把返回的字符串保存到 `count`；需要数值运算时再显式转换类型。
    count = input("请输入学生人数：")
    # 检查输入字符串 `count` 是否由数字字符组成，再决定是否进行数值转换；这并不能接受带小数点或正负号的数字写法。
    if count.isdigit() and int(count) > 0:
        # 把 `count` 转换为整数并存入 `count`；如果文本不是合法整数，会抛出 `ValueError`。
        count = int(count)
        # `break` 会立即结束当前循环，并继续执行循环之后的语句。
        break
    # 当前条件分支的前置条件均未成立时，执行这个 else 代码块。
    else:
        # 把括号中的内容输出到控制台；字符串中的 `{}`、`%s` 或 `%d` 等格式占位符应与传入的数据类型匹配。
        print("输入错误，请重新输入大于 0 的整数！")
# 遍历 `range(count)` 生成的整数序列，每轮把当前值赋给 `i`；`range` 的终点不包含在序列中，需留意循环边界。
for i in range(count):
    # 调用 `input()` 显示提示并读取用户输入，把返回的字符串保存到 `name`；需要数值运算时再显式转换类型。
    name = input("请输入第 %d 个学生的姓名：" % (i + 1))
    # 进入持续循环；必须通过循环体中的 `break`、`return` 或异常等方式结束，通常用于反复读取并校验输入。
    while True:
        # 调用 `input()` 显示提示并读取用户输入，把返回的字符串保存到 `score`；需要数值运算时再显式转换类型。
        score = input("请输入第 %d 个学生的成绩：" % (i + 1))
        # 检查输入字符串 `score` 是否由数字字符组成，再决定是否进行数值转换；这并不能接受带小数点或正负号的数字写法。
        if score.isdigit() and int(score) >= 0 and int(score) <= 100:
            # 把 `score` 转换为整数并存入 `score`；如果文本不是合法整数，会抛出 `ValueError`。
            score = int(score)
            # `break` 会立即结束当前循环，并继续执行循环之后的语句。
            break
        # 当前条件分支的前置条件均未成立时，执行这个 else 代码块。
        else:
            # 把括号中的内容输出到控制台；字符串中的 `{}`、`%s` 或 `%d` 等格式占位符应与传入的数据类型匹配。
            print("输入错误，请重新输入 0-100 之间的整数！")
    # 调用函数 `get_level()`，把它返回的结果保存到 `level`；函数具体做什么要看函数定义。
    level = get_level(score)
    # 把当前对象整理成字典 `student`，用键名关联姓名、成绩、等级等字段，便于后续按键读取。
    student = {"name": name, "score": score, "level": level}
    # 把一个元素追加到列表末尾；这是原地修改，列表变量仍指向同一个列表对象。
    students.append(student)

# 把括号中的内容输出到控制台；字符串中的 `{}`、`%s` 或 `%d` 等格式占位符应与传入的数据类型匹配。
print("\n==========所有学生成绩==========")
# 依次取出 `students` 列表中的每个学生记录，并暂时用 `student` 指向当前记录。
for student in students:
    # 把括号中的内容输出到控制台；字符串中的 `{}`、`%s` 或 `%d` 等格式占位符应与传入的数据类型匹配。
    print("姓名：%s，成绩：%d，等级：%s" % (student["name"], student["score"], student["level"]))
# 把括号中的内容输出到控制台；字符串中的 `{}`、`%s` 或 `%d` 等格式占位符应与传入的数据类型匹配。
print("----------------------------------")
# 判断条件 `not students`；条件为真时执行 if 分支，否则按后续 elif/else 分支处理。
if not students:
    # 把括号中的内容输出到控制台；字符串中的 `{}`、`%s` 或 `%d` 等格式占位符应与传入的数据类型匹配。
    print("暂无学生成绩！")
# 当前条件分支的前置条件均未成立时，执行这个 else 代码块。
else:
    # 使用 `max()` 找到 `students` 中按指定规则比较最大的元素，并保存到 `best_student`。
    best_student = max(students, key=lambda x: x["score"])
    # 把括号中的内容输出到控制台；字符串中的 `{}`、`%s` 或 `%d` 等格式占位符应与传入的数据类型匹配。
    print("\n==========成绩最好的学生==========")
    # 把括号中的内容输出到控制台；字符串中的 `{}`、`%s` 或 `%d` 等格式占位符应与传入的数据类型匹配。
    print("姓名：%s，成绩：%d，等级：%s" % (best_student["name"], best_student["score"], best_student["level"]))
    # 把累计变量 `total_score` 初始化为 0，后续通常会在循环中不断累加每一项。
    total_score = 0
    # 依次取出 `students` 列表中的每个学生记录，并暂时用 `student` 指向当前记录。
    for student in students:
        # 把 `student['score']` 累加到 `total_score`，相当于 `total_score = total_score + student['score']`；这是更新原变量，而不是创建新变量。
        total_score += student["score"]
    # 用总和除以元素数量计算平均值并存入 `average_score`；需确保除数不为 0。
    average_score = total_score / len(students)
    # 把括号中的内容输出到控制台；字符串中的 `{}`、`%s` 或 `%d` 等格式占位符应与传入的数据类型匹配。
    print("\n==========所有学生成绩总和==========")
    # 把括号中的内容输出到控制台；字符串中的 `{}`、`%s` 或 `%d` 等格式占位符应与传入的数据类型匹配。
    print("所有学生成绩总和：%d" % total_score)
    # 把括号中的内容输出到控制台；字符串中的 `{}`、`%s` 或 `%d` 等格式占位符应与传入的数据类型匹配。
    print("\n==========所有学生成绩平均值==========")
    # 把括号中的内容输出到控制台；字符串中的 `{}`、`%s` 或 `%d` 等格式占位符应与传入的数据类型匹配。
    print("所有学生成绩平均值：%.2f" % average_score)
