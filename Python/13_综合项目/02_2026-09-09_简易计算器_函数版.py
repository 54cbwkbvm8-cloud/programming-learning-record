def divide(a, b):
    # 判断条件 `b == 0`；条件为真时执行 if 分支，否则按后续 elif/else 分支处理。
    if b == 0:
        # 返回字符串 `不能除以 0`，调用方可以把它保存到变量或继续用于判断。
        return "不能除以 0"
    # 结束当前函数调用，并把 `a / b` 的结果交给调用方；调用方可以继续使用这个值。
    return a / b

