""" 用代码制作小游戏 """
# 文件用途：本文件围绕“猜数字游戏 早期版”展开。
# 核心知识点：循环、分支判断。
# 基本流程：根据代码中的输入或初始数据，按条件、循环和函数调用完成处理，再输出结果。
# 输入：从标准输入读取数据或由调用者传入参数。输出：通过控制台打印处理结果。
# 阅读提醒：注释用于解释当前代码的实际行为；若示例输入范围有限，扩展使用前应自行验证边界情况。
# 模块依赖：random。
# 导入后续代码需要使用的模块或名称；第三方模块还需在当前 Python 环境安装对应依赖。
import random

# 把表达式 `3` 的计算结果保存到 `counts`；右侧是数据来源，左侧是接收结果的变量。
counts = 3
# 把表达式 `random.randint(1, 10)` 的计算结果保存到 `answer`；右侧是数据来源，左侧是接收结果的变量。
answer = random.randint(1,10)

# 当条件 `counts > 0` 为真时重复执行循环体；需要确认循环体会更新相关状态，避免意外死循环。
while counts > 0:
    # 调用 `input()` 显示提示并读取用户输入，把返回的字符串保存到 `temp`；需要数值运算时再显式转换类型。
    temp = input("猜数字？：")
    # 把 `temp` 转换为整数并存入 `guess`；如果文本不是合法整数，会抛出 `ValueError`。
    guess = int(temp)

    # 判断条件 `guess == answer`；条件为真时执行 if 分支，否则按后续 elif/else 分支处理。
    if guess == answer:
        # 把括号中的内容输出到控制台；字符串中的 `{}`、`%s` 或 `%d` 等格式占位符应与传入的数据类型匹配。
        print("对了？？？")
        # 把括号中的内容输出到控制台；字符串中的 `{}`、`%s` 或 `%d` 等格式占位符应与传入的数据类型匹配。
        print("对了就对了呗！")
        # `break` 会立即结束当前循环，并继续执行循环之后的语句。
        break
    # 当前条件分支的前置条件均未成立时，执行这个 else 代码块。
    else:
        # 判断条件 `guess < answer`；条件为真时执行 if 分支，否则按后续 elif/else 分支处理。
        if guess < answer:
            # 把括号中的内容输出到控制台；字符串中的 `{}`、`%s` 或 `%d` 等格式占位符应与传入的数据类型匹配。
            print("傻子，太小了")
        # 当前条件分支的前置条件均未成立时，执行这个 else 代码块。
        else:
            # 把括号中的内容输出到控制台；字符串中的 `{}`、`%s` 或 `%d` 等格式占位符应与传入的数据类型匹配。
            print("太大了")
    # 计算 `counts - 1` 并将结果保存到 `counts`；按运算符和运算顺序逐步计算，可以验证结果是否正确。
    counts = counts - 1    

# 把括号中的内容输出到控制台；字符串中的 `{}`、`%s` 或 `%d` 等格式占位符应与传入的数据类型匹配。
print("不跟你玩了，傻孩子自己玩去吧")   
 
    
 
