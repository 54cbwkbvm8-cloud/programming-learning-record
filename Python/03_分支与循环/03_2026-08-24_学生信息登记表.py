"""
简介：录入学生信息并与预设身份信息进行匹配验证。
功能：
- 接收姓名、专业、学校和年龄。
- 核对四项信息是否同时匹配。
- 输出完整登记信息及身份判断结果。
用途：练习输入、字符串比较、逻辑与运算和格式化输出。
最后修改：2026-09-09
"""
# 文件用途：本文件围绕“学生信息登记表”展开。
# 核心知识点：字符串、循环、分支判断。
# 基本流程：根据代码中的输入或初始数据，按条件、循环和函数调用完成处理，再输出结果。
# 输入：从标准输入读取数据或由调用者传入参数。输出：通过控制台打印处理结果。
# 阅读提醒：检查列表/序列的下标范围、字符串处理结果及空数据情况。
name = input("姓名")  # 提示用户输入姓名
zy = input("专业")  # 提示用户输入专业
school = input("学校")  # 提示用户输入学校
age = input("年龄")  # 提示用户输入年龄
print("--------------------\n学生信息\n--------------------")  # 打印分隔线、标题、分隔线，\n 表示换行
if name == "张三" and age == "19" and school == "示例大学" and zy == "示例专业":  # 判断四项信息是否都等于预设值
    print("姓名:张三\n年龄:19岁\n学校:示例大学\n专业:示例专业\n身份判断:成功")  # 全部匹配时打印完整信息和“成功”
else:  # 否则说明信息不匹配
    print("姓名:",name)  # 打印输入的姓名
    print("专业:",zy)  # 打印输入的专业
    print("学校:",school)  # 打印输入的学校
    print("年龄:",age)  # 打印输入的年龄
    print("身份判断:失败")  # 打印身份判断结果“失败”
