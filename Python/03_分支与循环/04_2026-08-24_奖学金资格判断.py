# 把用户输入转成"是否挂科"的判断
has_failed = failed in ("是", "有", "y", "Y", "yes", "YES")

# 三个条件同时满足才算符合
if avg >= 85 and english >= 70 and not has_failed:
    # 把括号中的内容输出到控制台；字符串中的 `{}`、`%s` 或 `%d` 等格式占位符应与传入的数据类型匹配。
    print(f"{name}，符合基本奖学金申请条件")
# 当前条件分支的前置条件均未成立时，执行这个 else 代码块。
else:
    # 把括号中的内容输出到控制台；字符串中的 `{}`、`%s` 或 `%d` 等格式占位符应与传入的数据类型匹配。
    print(f"{name}，暂不符合条件")
