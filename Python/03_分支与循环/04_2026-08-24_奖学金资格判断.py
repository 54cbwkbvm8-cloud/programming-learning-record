# 大学奖学金资格判断程序
# 用户输入姓名、平均成绩、英语成绩、是否挂科

name = input("请输入姓名：")
# 把表达式转换为浮点数并存入 `avg`；输入文本不符合数值格式时可能抛出 `ValueError`。
avg = float(input("请输入平均成绩："))
# 把表达式转换为浮点数并存入 `english`；输入文本不符合数值格式时可能抛出 `ValueError`。
english = float(input("请输入英语成绩："))
# 调用 `input()` 显示提示并读取用户输入，把返回的字符串保存到 `failed`；需要数值运算时再显式转换类型。
