# 进入持续循环；必须通过循环体中的 `break`、`return` 或异常等方式结束，通常用于反复读取并校验输入。
while True:
    # 调用 `input()` 显示提示并读取用户输入，把返回的字符串保存到 `name`；需要数值运算时再显式转换类型。
    name = input("请输入你的用户名")

    # 判断条件 `name == ''`；条件为真时执行 if 分支，否则按后续 elif/else 分支处理。
    if name == "":
        # 把括号中的内容输出到控制台；字符串中的 `{}`、`%s` 或 `%d` 等格式占位符应与传入的数据类型匹配。
        print("用户名为空 请重新输入密码")
        # `continue` 会跳过本轮循环剩余语句，直接进入下一轮循环判断。
        continue

    # 调用 `input()` 显示提示并读取用户输入，把返回的字符串保存到 `password`；需要数值运算时再显式转换类型。
    password = input("请输入你的密码")

    # 判断条件 `name == 'zach' and password == '123456'`；条件为真时执行 if 分支，否则按后续 elif/else 分支处理。
    if name == "zach" and password == "123456":
        # 把括号中的内容输出到控制台；字符串中的 `{}`、`%s` 或 `%d` 等格式占位符应与传入的数据类型匹配。
        print("登录成功")
        # `break` 会立即结束当前循环，并继续执行循环之后的语句。
        break

    # 把括号中的内容输出到控制台；字符串中的 `{}`、`%s` 或 `%d` 等格式占位符应与传入的数据类型匹配。
    print("请检查用户名或者密码是否正确")
