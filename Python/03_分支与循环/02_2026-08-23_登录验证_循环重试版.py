"""
简介：可重复尝试用户名和密码的登录验证程序。
功能：
- 持续要求输入非空用户名。
- 校验用户名和密码是否匹配指定账号。
- 登录成功后退出，失败则自动重新尝试。
用途：对比基础版练习 while、continue、break 和输入校验。
最后修改：2026-09-09
"""
while True:
    name = input("请输入你的用户名")

    if name == "":
        print("用户名为空 请重新输入密码")
        continue

    password = input("请输入你的密码")

    if name == "zach" and password == "123456":
        print("登录成功")
        break

    print("请检查用户名或者密码是否正确")
