"""
简介：可重复尝试用户名和密码的登录验证程序。
功能：
- 持续要求输入非空用户名。
- 校验用户名和密码是否匹配指定账号。
- 登录成功后退出，失败则自动重新尝试。
用途：对比基础版练习 while、continue、break 和输入校验。
最后修改：2026-09-09
"""
# 文件用途：本文件围绕“登录验证 循环重试版”展开。
# 核心知识点：循环、分支判断。
# 基本流程：根据代码中的输入或初始数据，按条件、循环和函数调用完成处理，再输出结果。
# 输入：从标准输入读取数据或由调用者传入参数。输出：通过控制台打印处理结果。
# 阅读提醒：注释用于解释当前代码的实际行为；若示例输入范围有限，扩展使用前应自行验证边界情况。
while True:  # 无限循环，直到登录成功才退出
    name = input("请输入你的用户名")  # 提示用户输入用户名

    if name == "":  # 如果用户名为空
        print("用户名为空 请重新输入密码")  # 提示用户名不能为空
        continue  # 结束本次循环，回到开头重新输入

    password = input("请输入你的密码")  # 提示用户输入密码

    if name == "zach" and password == "123456":  # 判断用户名和密码是否都正确
        print("登录成功")  # 都正确时打印登录成功
        break  # 跳出循环，程序结束

    print("请检查用户名或者密码是否正确")  # 否则提示重新检查用户名或密码
