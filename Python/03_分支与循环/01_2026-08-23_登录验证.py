name = input("请输入你的用户名""----注意：""用户名和密码不能为空")  # 输入用户名，提示文案由三段拼接而成
if name == "":  # 判断用户名是否为空字符串
    print("用户名不能为空")  # 用户名为空时打印提示
    name = input("请重新输入你的用户名")  # 让用户重新输入用户名
