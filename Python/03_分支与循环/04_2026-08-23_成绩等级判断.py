"""
简介：根据用户输入的分数输出对应等级。
功能：
- 接收 0 到 120 之间的成绩。
- 按分数区间输出不同等级。
- 对超出范围的输入给出提示。
用途：练习 input、整数转换和多分支 if/elif/else 判断。
最后修改：2026-09-09
"""
# 文件用途：本文件围绕“成绩等级判断”展开。
# 核心知识点：字符串、循环、分支判断。
# 基本流程：根据代码中的输入或初始数据，按条件、循环和函数调用完成处理，再输出结果。
# 输入：从标准输入读取数据或由调用者传入参数。输出：通过控制台打印处理结果。
# 阅读提醒：检查列表/序列的下标范围、字符串处理结果及空数据情况。
score = input("请输入你的分数")  # 提示用户输入分数，先以字符串形式保存
score = int(score)  # 把输入的字符串转成整数

if 0 <= score < 60:  # 分数在 0（含 0）到 60（不含 60）之间
    print("傻子，你的是鸭蛋")  # 输出鸭蛋等级提示
elif 60 <= score < 80:  # 分数在 60（含）到 80（不含）之间
    print("C")  # 输出等级 C
elif 80 <= score < 90:  # 分数在 80（含）到 90（不含）之间
    print("B")  # 输出等级 B
elif 90 <= score < 100:  # 分数在 90（含）到 100（不含）之间
    print("A")  # 输出等级 A
elif 100 <= score < 120:  # 分数在 100（含）到 120（不含）之间
    print("SSS")  # 输出等级 SSS
else:  # 以上条件都不满足
    print("请输入0～120")  # 提示用户输入 0～120 之间的分数
