"""
简介：用循环同时演示九九乘法表和七天学习打卡输出。
功能：
- 使用嵌套 while 循环输出九九乘法表。
- 使用七天循环模拟每日学习打卡。
- 通过 break 控制每天只输出一次打卡信息。
用途：练习嵌套循环、计数器以及循环控制。
最后修改：2026-09-09
"""
# 文件用途：本文件围绕“九九乘法表与学习打卡”展开。
# 核心知识点：循环、分支判断。
# 基本流程：根据代码中的输入或初始数据，按条件、循环和函数调用完成处理，再输出结果。
# 输入：本文件使用预设数据、初始化值或函数参数。输出：通过控制台打印结果。
# 阅读提醒：注释用于解释当前代码的实际行为；若示例输入范围有限，扩展使用前应自行验证边界情况。
i = 1  # 外层循环变量 i（乘法表的行号）从 1 开始
while i <= 9:  # i 最多到 9，即一共打印 9 行
    j = 1  # 内层循环变量 j（乘法表的列号）从 1 开始
    while j <= i:  # 只要 j 不超过当前行号 i 就继续
        print(j,"*",i,"=",j*i,end=" ")  # 打印乘法算式，end=" " 表示不换行只加空格
        j = j + 1  # 内层列号 j 递增
    print()  # 一行打印结束后换行
    i = i + 1  # 外层行号 i 递增，进入下一行
day = 1  # 打卡天数从第 1 天开始
hour = 1  # 当天学习小时数从 1 开始
while day <= 7:  # 循环控制连续打卡 7 天
    while hour <= 8:  # 一天内最多学到 8 小时
        print("我今天要学八小时")  # 打印这一天的打卡内容
        hour = hour + 1  # 小时数加 1
        if hour > 1:  # 判断当前小时是否已经超过 1
            break  # 满足时跳出内层循环，结束这一天
    day = day + 1  # 天数加 1，进入下一天
