"""
简介：随机生成 1 到 10 的目标数字并允许玩家猜三次。
功能：
- 使用 random.randint 生成随机答案。
- 提示猜测值比答案大还是小。
- 猜中或用完三次机会后结束。
用途：练习随机数、循环、条件判断和 break。
最后修改：2026-09-09
"""
import random

counts = 3
answer = random.randint(1,10)

while counts > 0:
    temp = input("猜数字？：")
    guess = int(temp)

    if guess == answer:
        print("对了？？？")
        print("对了就对了呗！")
        break
    else:
        if guess < answer:
            print("傻子，太小了")
        else:
            print("太大了")
    counts = counts - 1

print("不跟你玩了，傻孩子自己玩去吧")
