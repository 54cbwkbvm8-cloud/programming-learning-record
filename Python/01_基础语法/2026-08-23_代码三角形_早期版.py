# 第 3 题：打印三角形
#
# 关键知识：字符串可以乘数字，"* " * 3 会得到 "* * * "
#
# 思路：
#   - height 控制三角形的高度（几行）
#   - i 从 1 到 height，第几行就打印几个"* "

height = 5

# 遍历 `range(1, height + 1)` 生成的整数序列，每轮把当前值赋给 `i`；`range` 的终点不包含在序列中，需留意循环边界。
for i in range(1, height + 1):
    # 把括号中的内容输出到控制台；字符串中的 `{}`、`%s` 或 `%d` 等格式占位符应与传入的数据类型匹配。
    print("* " * i)
