# 第 2 题：打印 100 以内的偶数
#
# range(起点, 终点, 步长)：
#   - 起点是 0，包含
#   - 终点是 101，不包含（所以 100 会被打印出来）
#   - 步长是 2，从 0 开始每次加 2
#
# 如果想从 2 开始（不打印 0），把起点改成 2 即可

for n in range(0, 101, 2):
    # 把括号中的内容输出到控制台；字符串中的 `{}`、`%s` 或 `%d` 等格式占位符应与传入的数据类型匹配。
    print(n)
