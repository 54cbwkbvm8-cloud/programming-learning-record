# 文件用途：本文件围绕“星号三角形”展开。
# 核心知识点：字符串、循环。
# 基本流程：根据代码中的输入或初始数据，按条件、循环和函数调用完成处理，再输出结果。
# 输入：本文件使用预设数据、初始化值或函数参数。输出：通过控制台打印结果。
# 阅读提醒：检查列表/序列的下标范围、字符串处理结果及空数据情况。
# 第 3 题：打印三角形
#
# 关键知识：字符串可以乘数字，"* " * 3 会得到 "* * * "
#
# 思路：
#   - height 控制三角形的高度（几行）
#   - i 从 1 到 height，第几行就打印几个"* "

height = 5  # 定义三角形的高度为 5 行

for i in range(1, height + 1):  # 循环变量 i 从 1 到 height，代表当前是第几行
    print("* " * i)  # 打印 i 个 "* "，组成第 i 行的三角形内容
