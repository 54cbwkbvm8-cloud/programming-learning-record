# -*- coding: utf-8 -*-
"""
简介：输出 0 到 100 之间的全部偶数。
功能：
- 使用 range 设置起点、终点和步长。
- 逐个打印 0、2、4 到 100。
用途：理解 range 的边界规则以及 for 循环。
最后修改：2026-09-09
"""
# 文件用途：本文件围绕“输出偶数”展开。
# 核心知识点：循环。
# 基本流程：根据代码中的输入或初始数据，按条件、循环和函数调用完成处理，再输出结果。
# 输入：本文件使用预设数据、初始化值或函数参数。输出：通过控制台打印结果。
# 阅读提醒：注释用于解释当前代码的实际行为；若示例输入范围有限，扩展使用前应自行验证边界情况。
# 第 2 题：打印 100 以内的偶数
#
# range(起点, 终点, 步长)：
#   - 起点是 0，包含
#   - 终点是 101，不包含（所以 100 会被打印出来）
#   - 步长是 2，从 0 开始每次加 2
#
# 如果想从 2 开始（不打印 0），把起点改成 2 即可

for n in range(0, 101, 2):  # 从 0 开始，步长为 2，生成 0、2、4……100（101 不包含，所以能取到 100）
    print(n)  # 打印当前这个偶数
