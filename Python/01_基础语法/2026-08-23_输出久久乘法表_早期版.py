# 第 1 题：九九乘法表
#
# 思路：
#   - 外层循环 i 代表"行"，从 1 到 9
#   - 内层循环 j 代表"列"，从 1 到 i（所以每行列数不超过行数）
#   - end="  " 表示这一句打印完不换行，只加两个空格
#   - 内层循环结束后 print() 负责换行

for i in range(1, 10):
    # 遍历 `range(1, i + 1)` 生成的整数序列，每轮把当前值赋给 `j`；`range` 的终点不包含在序列中，需留意循环边界。
    for j in range(1, i + 1):
        # 把括号中的内容输出到控制台；字符串中的 `{}`、`%s` 或 `%d` 等格式占位符应与传入的数据类型匹配。
        print(f"{j} x {i} = {i * j}", end="  ")
    # 把括号中的内容输出到控制台；字符串中的 `{}`、`%s` 或 `%d` 等格式占位符应与传入的数据类型匹配。
    print()
