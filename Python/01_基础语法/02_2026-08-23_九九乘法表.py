# -*- coding: utf-8 -*-
"""
简介：使用双重循环输出标准的九九乘法表。
功能：
- 外层循环控制 1 到 9 行。
- 内层循环按当前行号输出对应列数。
- 使用格式化字符串展示完整乘法算式。
用途：练习嵌套循环、range 和 f-string。
最后修改：2026-09-09
"""
# 文件用途：本文件围绕“九九乘法表”展开。
# 核心知识点：字符串、循环。
# 基本流程：根据代码中的输入或初始数据，按条件、循环和函数调用完成处理，再输出结果。
# 输入：本文件使用预设数据、初始化值或函数参数。输出：通过控制台打印结果。
# 阅读提醒：检查列表/序列的下标范围、字符串处理结果及空数据情况。
# 第 1 题：九九乘法表
#
# 思路：
#   - 外层循环 i 代表"行"，从 1 到 9
#   - 内层循环 j 代表"列"，从 1 到 i（所以每行列数不超过行数）
#   - end="  " 表示这一句打印完不换行，只加两个空格
#   - 内层循环结束后 print() 负责换行

for i in range(1, 10):  # 外层循环，i 代表行号，范围是 1 到 9
    for j in range(1, i + 1):  # 内层循环，j 代表列号，从 1 到当前行号 i
        print(f"{j} x {i} = {i * j}", end="  ")  # 打印乘法算式，end="  " 表示本次打印不换行，只加两个空格
    print()  # 打印完一行乘法后换行
