# 定义函数 `two_sum`，用于计算总和或平均值；参数包括 nums、target，函数体负责具体处理，调用处应关注传入参数和返回值。
def two_sum(nums,target):
    # 遍历 `range(len(nums))` 生成的整数序列，每轮把当前值赋给 `i`；`range` 的终点不包含在序列中，需留意循环边界。
    for i in range(len(nums)):
        # 遍历 `range(i + 1, len(nums))` 生成的整数序列，每轮把当前值赋给 `j`；`range` 的终点不包含在序列中，需留意循环边界。
        for j in range(i+1,len(nums)):
            # 判断条件 `nums[i] + nums[j] == target`；条件为真时执行 if 分支，否则按后续 elif/else 分支处理。
            if nums[i]+nums[j]==target:
                # 返回一个新列表 `[i, j]`；列表中的值由当前计算得到，函数执行到这里就会立即结束。
                return [i,j]
# 检查本文件是否被直接运行；作为模块被其他文件导入时，这个分支不会执行。
if __name__=='__main__':
    # 创建列表 `nums` 并放入初始元素；列表有顺序且可修改，元素下标从 0 开始。
    nums = [2,7,11,15]
    # 保存需要达到的目标值 `9`；后续算法会比较计算结果与这个目标。
    target = 9
    # 把括号中的内容输出到控制台；字符串中的 `{}`、`%s` 或 `%d` 等格式占位符应与传入的数据类型匹配。
    print(two_sum(nums,target))
