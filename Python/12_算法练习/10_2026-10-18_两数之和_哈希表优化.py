def two_sum(nums, target):
    seen = {}

    for i in range(len(nums)):
        current = nums[i]
        need = target - current

        if need in seen:
            return [seen[need], i]

        seen[current] = i

    return None


if __name__ == '__main__':
    nums = [2, 7, 11, 15]
    target = 9
    print(two_sum(nums, target))
