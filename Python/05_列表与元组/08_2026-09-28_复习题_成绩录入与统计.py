# 文件用途：本文件围绕“复习题 成绩录入与统计”展开。
# 核心知识点：列表与字典、循环、分支判断。
# 基本流程：根据代码中的输入或初始数据，按条件、循环和函数调用完成处理，再输出结果。
# 输入：从标准输入读取数据或由调用者传入参数。输出：通过控制台打印处理结果。
# 阅读提醒：注释用于解释当前代码的实际行为；若示例输入范围有限，扩展使用前应自行验证边界情况。
students = []  # 创建一个空列表，用来保存所有学生的信息
scores = []  # 创建一个空列表，用来保存所有学生的成绩
while True:  # 创建一个无限循环，让我们可以连续输入多个学生
    name = input("请输入学生姓名：")  # 让用户输入学生姓名，并把姓名保存到name变量中
    score = float(input("请输入学生成绩："))  # 让用户输入成绩，并把输入的内容转换成数字保存到score变量中
    if score < 0 or score > 100:  # 判断成绩是否小于0或者大于100
        print("成绩必须在0到100之间，请重新输入！")  # 如果成绩不合法，就输出错误提示
        # `continue` 会跳过本轮循环剩余语句，直接进入下一轮循环判断。
        continue
    if score >= 90:  # 判断成绩是否大于等于90
        # 把表达式 `'A'` 的计算结果保存到 `level`；右侧是数据来源，左侧是接收结果的变量。
        level = 'A'
    elif score >= 80:  # 如果成绩没有达到90，再判断是否大于等于80
        # 把表达式 `'B'` 的计算结果保存到 `level`；右侧是数据来源，左侧是接收结果的变量。
        level = 'B'
    elif score >= 70:  # 如果成绩没有达到80，再判断是否大于等于70
        # 把表达式 `'C'` 的计算结果保存到 `level`；右侧是数据来源，左侧是接收结果的变量。
        level = 'C'
    elif score >= 60:  # 如果成绩没有达到70，再判断是否大于等于60
        # 把表达式 `'D'` 的计算结果保存到 `level`；右侧是数据来源，左侧是接收结果的变量。
        level = 'D'
    else:  # 如果成绩没有达到60
        # 把表达式 `'E'` 的计算结果保存到 `level`；右侧是数据来源，左侧是接收结果的变量。
        level = 'E'
    students.append([name, score, level])  # 把学生信息添加到students列表中
    # 把括号中的内容输出到控制台；字符串中的 `{}`、`%s` 或 `%d` 等格式占位符应与传入的数据类型匹配。
    print("学生姓名：", name, "学生成绩：", score, "学生等级：",level)
    # 调用 `input()` 显示提示并读取用户输入，把返回的字符串保存到 `answer`；需要数值运算时再显式转换类型。
    answer = input("是否继续输入学生信息？(y/n)")
    # 判断条件 `answer == 'n'`；条件为真时执行 if 分支，否则按后续 elif/else 分支处理。
    if answer == 'n':
        # `break` 会立即结束当前循环，并继续执行循环之后的语句。
        break
    # 判断条件 `answer == 'y'`；条件为真时执行 if 分支，否则按后续 elif/else 分支处理。
    elif answer == 'y':
        # `continue` 会跳过本轮循环剩余语句，直接进入下一轮循环判断。
        continue
    # 当前条件分支的前置条件均未成立时，执行这个 else 代码块。
    else:
        # 把括号中的内容输出到控制台；字符串中的 `{}`、`%s` 或 `%d` 等格式占位符应与传入的数据类型匹配。
        print("输入错误，请重新输入！")
        # `continue` 会跳过本轮循环剩余语句，直接进入下一轮循环判断。
        continue
# 把括号中的内容输出到控制台；字符串中的 `{}`、`%s` 或 `%d` 等格式占位符应与传入的数据类型匹配。
print("**********所有学生的成绩统计表**********")
# 创建空列表 `scores`；列表可以保存多个元素，之后可使用 `append()` 添加数据。
scores = []
for student in students:  # 遍历students列表中的每一个学生
    scores.append(student[1])  # 把当前学生的成绩添加到scores列表中

print("\n所有学生成绩：")  # 输出所有学生成绩的标题
# 依次取出 `students` 列表中的每个学生记录，并暂时用 `student` 指向当前记录。
for student in students:
    # 把括号中的内容输出到控制台；字符串中的 `{}`、`%s` 或 `%d` 等格式占位符应与传入的数据类型匹配。
    print("学生姓名：", student[0], "学生成绩：", student[1], "学生等级：", student[2])
# 判断条件 `len(students) > 0`；条件为真时执行 if 分支，否则按后续 elif/else 分支处理。
if len(students) > 0:
    # 使用 `max()` 找到 `students` 中按指定规则比较最大的元素，并保存到 `highest_score`。
    highest_score = max(students, key=lambda x: x[1])
    # 把括号中的内容输出到控制台；字符串中的 `{}`、`%s` 或 `%d` 等格式占位符应与传入的数据类型匹配。
    print("最高分学生姓名：", highest_score[0], "最高分学生成绩：", highest_score[1], "最高分学生等级：", highest_score[2])
    # 用总和除以元素数量计算平均值并存入 `average`；需确保除数不为 0。
    average = sum([student[1] for student in students]) / len(students)
    # 把括号中的内容输出到控制台；字符串中的 `{}`、`%s` 或 `%d` 等格式占位符应与传入的数据类型匹配。
    print("平均分：", average)
# 当前条件分支的前置条件均未成立时，执行这个 else 代码块。
else:
    # 把括号中的内容输出到控制台；字符串中的 `{}`、`%s` 或 `%d` 等格式占位符应与传入的数据类型匹配。
    print("没有学生信息")
# 把括号中的内容输出到控制台；字符串中的 `{}`、`%s` 或 `%d` 等格式占位符应与传入的数据类型匹配。
print("程序结束")
