students = []
scores = []
while True:
    name = input("请输入学生姓名：")
    score = float(input("请输入学生成绩："))
    if score < 0 or score > 100:
        print("成绩必须在0到100之间，请重新输入！")
        continue
    if score >= 90:
        level = 'A'
    elif score >= 80:
        level = 'B'
    elif score >= 70:
        level = 'C'
    elif score >= 60:
        level = 'D'
    else:
        level = 'E'
    students.append([name, score, level])
    print("学生姓名：", name, "学生成绩：", score, "学生等级：",level)
    answer = input("是否继续输入学生信息？(y/n)")
    if answer == 'n':
        break
    elif answer == 'y':
        continue
    else:
        print("输入错误，请重新输入！")
        continue
print("**********所有学生的成绩统计表**********")
scores = []
for student in students:
    scores.append(student[1])

print("\n所有学生成绩：")
for student in students:
    print("学生姓名：", student[0], "学生成绩：", student[1], "学生等级：", student[2])
if len(students) > 0:
    highest_score = max(students, key=lambda x: x[1])
    print("最高分学生姓名：", highest_score[0], "最高分学生成绩：", highest_score[1], "最高分学生等级：", highest_score[2])
    average = sum([student[1] for student in students]) / len(students)
    print("平均分：", average)
else:
    print("没有学生信息")
print("程序结束")
