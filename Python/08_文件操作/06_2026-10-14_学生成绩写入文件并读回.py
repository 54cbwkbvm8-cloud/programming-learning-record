# 文件用途：本文件围绕“学生成绩写入文件并读回”展开。
# 核心知识点：列表与字典、字符串、循环、文件读写。
# 基本流程：根据代码中的输入或初始数据，按条件、循环和函数调用完成处理，再输出结果。
# 输入：从标准输入读取数据或由调用者传入参数。输出：通过控制台打印处理结果。 文件操作：代码中包含文件读写相关逻辑，运行时需留意路径、权限和文件内容。
# 阅读提醒：检查列表/序列的下标范围、字符串处理结果及空数据情况。
# 创建空列表 `students`，后续把逐步处理得到的记录或结果追加到其中。
students = []
# 把括号中的内容输出到控制台；字符串中的 `{}`、`%s` 或 `%d` 等格式占位符应与传入的数据类型匹配。
print("========学生成绩管理系统========")
# 把括号中的内容输出到控制台；字符串中的 `{}`、`%s` 或 `%d` 等格式占位符应与传入的数据类型匹配。
print("接下来输入 3 名学生的姓名和成绩。")
# 遍历 `range(3)` 生成的整数序列，每轮把当前值赋给 `i`；`range` 的终点不包含在序列中，需留意循环边界。
for i in range(3):
    # 把括号中的内容输出到控制台；字符串中的 `{}`、`%s` 或 `%d` 等格式占位符应与传入的数据类型匹配。
    print(f"\n第{i + 1} 名学生")
    # 调用 `input()` 显示提示并读取用户输入，把返回的字符串保存到 `name`；需要数值运算时再显式转换类型。
    name = input(f"请输入第 {i+1} 名学生的姓名：")
    # 把表达式转换为浮点数并存入 `score`；输入文本不符合数值格式时可能抛出 `ValueError`。
    score = float(input(f"请输入 {name} 的成绩："))
    # 把一个元素追加到列表末尾；这是原地修改，列表变量仍指向同一个列表对象。
    students.append({"name": name, "score": score})
# 进入上下文管理器；例如 `with open(...)` 能在代码块结束后自动关闭文件，减少资源未释放的风险。
with open("students.txt", "w", encoding="utf-8") as f:
    # 依次取出 `students` 列表中的每个学生记录，并暂时用 `s` 指向当前记录。
    for s in students:
        # 调用 `f.write` 执行操作；如果它有返回值而这里没有接收，通常表示代码只需要它产生的副作用。
        f.write(f"{s['name']},{s['score']}\n")
# 把括号中的内容输出到控制台；字符串中的 `{}`、`%s` 或 `%d` 等格式占位符应与传入的数据类型匹配。
print("\n学生成绩已保存到 students.txt 文件中。")
# 把括号中的内容输出到控制台；字符串中的 `{}`、`%s` 或 `%d` 等格式占位符应与传入的数据类型匹配。
print("\n从 students.txt 文件中读取学生成绩：")
# 进入上下文管理器；例如 `with open(...)` 能在代码块结束后自动关闭文件，减少资源未释放的风险。
with open("students.txt", "r", encoding="utf-8") as f:
    # 遍历 `f`，每轮把当前元素赋给 `line`，再执行循环体；确认容器内容与循环次数是否符合预期。
    for line in f:
        # 把表达式 `line.strip().split(',')` 的计算结果保存到 `(name, score)`；右侧是数据来源，左侧是接收结果的变量。
        name, score = line.strip().split(",")
        # 把括号中的内容输出到控制台；字符串中的 `{}`、`%s` 或 `%d` 等格式占位符应与传入的数据类型匹配。
        print(f"{name} 的成绩是 {score}")
# 把括号中的内容输出到控制台；字符串中的 `{}`、`%s` 或 `%d` 等格式占位符应与传入的数据类型匹配。
print("\n程序结束。")
