# -*- coding: utf-8 -*-
"""
简介：使用循环打印由星号组成的直角三角形。
功能：
- 通过 height 变量控制三角形的行数。
- 使用 for 循环和字符串重复运算逐行输出。
用途：练习 range、循环变量和字符串乘法。
最后修改：2026-09-09
"""
# 第 3 题：打印三角形
#
# 关键知识：字符串可以乘数字，"* " * 3 会得到 "* * * "
#
# 思路：
#   - height 控制三角形的高度（几行）
#   - i 从 1 到 height，第几行就打印几个"* "

height = 5  # 定义三角形的高度为 5 行

for i in range(1, height + 1):  # 循环变量 i 从 1 到 height，代表当前是第几行
    print("* " * i)  # 打印 i 个 "* "，组成第 i 行的三角形内容
