// --------------------------------------------------------------------
// 第一部分：引入"工具箱"
// --------------------------------------------------------------------
// <stdio.h> 是"标准输入输出"工具箱：printf 负责输出，scanf 负责从键盘输入，都在里面。
#include <stdio.h>


// --------------------------------------------------------------------
// 第二部分：main 函数 —— 程序从这里开始
// --------------------------------------------------------------------
// 程序从 main 开始，从上往下一行一行执行。
int main(void) {

    // number 是整数变量，用来存输入的数。第一题和第二题共用它，第二题输入的新值会覆盖第一题的旧值。
    int number;

    // --------------------------------------------------------------------
    // 第一题：正数、负数还是 0
    // --------------------------------------------------------------------
    printf("【第一题】请输入一个整数：");

    // scanf 从键盘读数据：%d 表示读一个整数，&number 是 number 的地址，读到的数会放进这个地址。
    // 记忆：读 int、float 这类普通变量，变量名前面要加 &。
    scanf("%d", &number);

    // if ... else if ... else 是"多选一"：从上往下依次检查，遇到第一个成立的就执行它，后面的全部跳过。
    // 例：输入 -5，先看 > 0 不成立，再看 < 0 成立，输出"这是负数"，最后的 else 不再执行。
    if (number > 0) {
        printf("这是正数\n");
    } else if (number < 0) {
        printf("这是负数\n");

    // 走到 else，说明既不大于 0，也不小于 0，只剩 0 这一种可能，所以 else 后面不用再写条件。
    } else {
        printf("这是0\n");
    }

    // --------------------------------------------------------------------
    // 第二题：奇数还是偶数
    // --------------------------------------------------------------------
    // 提示文字开头的 \n 先换一行，让题与题之间空一行，输出更清楚。
    printf("\n【第二题】请输入一个整数：");
    scanf("%d", &number);

    // % 叫"取余"，a % b 是 a 除以 b 的余数。除以 2 余 0 的是偶数，否则是奇数。
    // 例：8 % 2 是 0，是偶数；7 % 2 是 1，是奇数。
    // == 是"判断是否相等"（两个等号），一个等号 = 是赋值，不能混。
    if (number % 2 == 0) {
        printf("这是偶数\n");
    } else {
        printf("这是奇数\n");
    }

    // --------------------------------------------------------------------
    // 第三题：三个数中的最大值
    // --------------------------------------------------------------------
    // 下面 4 个变量：a、b、c 存输入的三个整数，max 存最大值。
    int a;
    int b;
    int c;
    int max;

    // 提示里说明了两种输入方式：每输入一个数按一次回车，或者用空格把三个数隔开。
    printf("\n【第三题】请输入三个整数：(输入一个数字后按回车 或者 输入一个数字后用空格隔开)");

    // 一条 scanf 一次读三个整数：三个 %d 依次对应 &a、&b、&c。
    // scanf 会自动跳过空格和回车，所以数字之间用空格或回车隔开都可以。
    // 例：输入 3 9 6，a 是 3，b 是 9，c 是 6。
    scanf("%d %d %d", &a, &b, &c);

    // "打擂台"的思路：先假设第一个数 a 是最大的，把它放进 max。
    max = a;

    // 再让 b 去挑战：如果 b 比目前的最大值还大，就让 b 当新的最大值。
    if (b > max) {
        max = b;
    }

    // 再让 c 去挑战。三个数比完，max 里就是最大值。
    // 例：a=3，b=9，c=6：max 先是 3；b > 3 成立，max 变 9；c > 9 不成立；最大值是 9。
    // 这里是两个独立的 if（不是 else if），因为 b 和 c 都需要各比一次。
    if (c > max) {
        max = c;
    }
    printf("最大值是：%d\n", max);

    // --------------------------------------------------------------------
    // 第四题：分数等级
    // --------------------------------------------------------------------
    // score 存分数。
    int score;
    printf("\n【第四题】请输入一个分数：");
    scanf("%d", &score);

    // || 读作"或者"：两边只要有一边成立，整个条件就成立。
    // 先把不合法的分数挑出来：小于 0 或者大于 100 都是输入错误。
    if (score < 0 || score > 100) {
        printf("输入错误,请输入 0～100 的数字\n");

    // 这里只写下限就够了：能走到这一行，说明前面的条件都没成立（分数一定在 0 到 100 之间）。
    // 例：输入 85，不合法？否；>= 90？否；>= 80？是，输出"良好"，后面的不再检查。
    } else if (score >= 90) {
        printf("优秀\n");
    } else if (score >= 80) {
        printf("良好\n");
    } else if (score >= 70) {
        printf("中等\n");
    } else if (score >= 60) {
        printf("及格\n");

    // 走到这里，说明分数在 0 到 59 之间，输出"不及格"。
    } else {
        printf("不及格\n");
    }

    // --------------------------------------------------------------------
    // 第五题：闰年判断
    // --------------------------------------------------------------------
    // year 存年份。
    int year;
    printf("\n【第五题】请输入一个年份：");
    scanf("%d", &year);

    // 闰年的规则：能被 4 整除但不能被 100 整除，或者能被 400 整除。
    // 对应的写法：(year % 4 == 0 && year % 100 != 0) || year % 400 == 0
    //   && 读作"并且"，两边都成立才成立；|| 读作"或者"；!= 表示"不等于"；括号让里面的先算。
    // 例：2024 能被 4 整除，不能被 100 整除，是闰年；
    //     1900 能被 4 整除，但也能被 100 整除，又不能被 400 整除，不是闰年；
    //     2000 能被 400 整除，是闰年。
    if ((year % 4 == 0 && year % 100 != 0) || year % 400 == 0) {
        printf("%d年是闰年\n", year);

    // 这个 else 后面只有一条语句，所以省略了大括号。这样写合法，
    // 但以后如果要在 else 里再加语句，一定要补上大括号，否则新加的语句不属于 else，容易出错。
    } else

        // 这条输出的结尾没有 \n，所以程序结束时光标停在同一行。
        printf("%d年不是闰年", year);

    // return 0：结束 main，把 0 交给系统，表示"程序正常结束"。
    return 0;
}

