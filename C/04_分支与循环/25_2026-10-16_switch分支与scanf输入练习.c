// --------------------------------------------------------------------
// 第一部分：引入"工具箱"
// --------------------------------------------------------------------
// <stdio.h> 是"标准输入输出"工具箱：printf（输出）和 scanf（输入）都在里面。
#include <stdio.h>


// --------------------------------------------------------------------
// 第二部分：main 函数 —— 程序从这里开始
// --------------------------------------------------------------------
int main(void) {

    // number 存读到的整数。声明的同时赋初值 0，避免它里面是随机的旧数据。
    int number = 0;

    // ch 存读到的字符。'\0' 是"空字符"（编码为 0），这里用来表示"还没有字符"。
    // char 变量的值用单引号写，例如 'A'。
    char ch = '\0';

    // ⚠ 提醒：这句提示写的是"字符"，但下面的 scanf 用 %d 读的是整数，运行时应该输入 1、2、3 这样的整数。
    // 这是原代码的提示文字，这里不改，只提醒你。
    printf("请输入一个字符用于（switch分支演示）：");

    // scanf 有返回值：成功读到几个数据，就返回几。这里只读一个整数，成功时返回 1。
    // != 1 表示"没有读成功"。例如应该输入数字，你却输入了字母 a，scanf 读不到整数，就会返回 0。
    // 为什么要检查？读失败时 number 里还是旧值，不检查的话，程序会拿着错误的数据继续往下走。
    // 写法：scanf 直接放在 if 的条件里，先执行 scanf，再拿它的返回值去和 1 比较。
    if (scanf("%d", &number) != 1) {
        printf("输入错误，程序退出。\n");

        // return 1：提前结束 main，把 1 交给系统。按约定，0 表示正常结束，非 0（这里是 1）表示"出错了"。
        // return 一执行，整个程序就结束，后面的代码不会再运行。
        return 1;
    }
    printf("请输入一个字符（例如：A、B、C）：\n");

    // %c 表示读一个字符；%c 前面的空格让 scanf 先跳过空白（比如上一次输入留下的回车），再读真正的字符。
    // 同样检查返回值是否为 1。
    if (scanf(" %c", &ch) != 1) {
        printf("输入错误，程序退出。\n");
        return 1;
    }

    // 把读到的结果显示出来，方便确认输入是否正确。%d 是整数占位符。
    printf("读取到的整数是 %d\n", number);

    // %c 是字符的占位符。单引号 ' 写在双引号字符串里，可以直接原样显示。
    printf("读取到的字符是 '%c'\n", ch);
    printf("switch分支执行结果是：\n");

    // switch (表达式) { case 值: ... }：拿表达式的值，依次和每个 case 后面的值比较，相等就从这个 case 开始执行。
    // 适合"一个变量对应多个固定取值"的情况，比一长串 if ... else if 更清楚。
    // 注意：switch 里的表达式和 case 后面的值必须是整数类型（int、char 等），不能是小数或字符串。
    switch (number) {
    // case 1: 表示"如果 number 等于 1，就从这里开始执行"。冒号 : 不能漏。
    case 1:
        printf("进入 case 1\n");

        // break 的作用是"跳出 switch"。
        // 如果不写 break，程序会接着执行下一个 case 里的代码（不再判断条件），这叫"穿透"，通常是出错的原因。
        // 所以每个 case 末尾一般都要写 break（除非你就是想要穿透）。
        break;
    case 2:
        printf("进入 case 2\n");
        break;
    case 3:
        printf("进入 case 3\n");
        break;

    // default 表示"上面所有 case 都不匹配时"执行的分支，相当于 if 里的 else。
    // 例：输入 2 时进入 case 2；输入 9 没有匹配的 case，就进入 default。
    default:
        printf("没有匹配的 case，进入 default 分支\n");

        // default 放在最后，这个 break 不写也不影响结果。写上是个好习惯：以后再往下加 case 时不会出错。
        break;
    }

    // return 0：结束 main，把 0 交给系统，表示"程序正常结束"。
    return 0;
}

