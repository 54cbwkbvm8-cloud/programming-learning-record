#include <stdio.h>
// 定义函数 main；参数接收调用方传入的数据，函数体完成操作，返回语句（如有）把结果交还调用者。
int main(void) {
// 声明并初始化变量；`=` 是赋值运算符，用右侧表达式的值设置左侧变量，而不是比较两个值。
    int number = 0;
// 声明并初始化变量；`=` 是赋值运算符，用右侧表达式的值设置左侧变量，而不是比较两个值。
    char ch = '\0';
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("请输入一个字符用于（switch分支演示）：");
// 判断条件 `(scanf(字符串, &number) != 1)` 是否成立；条件为真时执行对应分支，否则跳过或转入其他分支。
    if (scanf("%d", &number) != 1) {
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
        printf("输入错误，程序退出。\n");
// 结束当前函数调用，并把表达式 `1` 的结果返回给调用者。
        return 1;
    }
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("请输入一个字符（例如：A、B、C）：\n");
// 判断条件 `(scanf(字符串, &ch) != 1)` 是否成立；条件为真时执行对应分支，否则跳过或转入其他分支。
    if (scanf(" %c", &ch) != 1) {
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
        printf("输入错误，程序退出。\n");
// 结束当前函数调用，并把表达式 `1` 的结果返回给调用者。
        return 1;
    }
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("读取到的整数是 %d\n", number);
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("读取到的字符是 '%c'\n", ch);
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("switch分支执行结果是：\n");
// 根据括号中表达式的值选择匹配的 case 分支；C 语言的 case 默认会继续向下执行，除非遇到 break 等控制转移。
    switch (number) {
// 这是 switch 中的一个匹配标签；表达式值与此常量相同时，从此处开始执行。
    case 1:
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
        printf("进入 case 1\n");
        break;
// 这是 switch 中的一个匹配标签；表达式值与此常量相同时，从此处开始执行。
    case 2:
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
        printf("进入 case 2\n");
        break;
// 这是 switch 中的一个匹配标签；表达式值与此常量相同时，从此处开始执行。
    case 3:
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
        printf("进入 case 3\n");
        break;
// 当 switch 中没有其他 case 匹配时，执行默认分支（如果存在）。
    default:
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
        printf("没有匹配的 case，进入 default 分支\n");
        break;
    }
// 结束当前函数调用，并把表达式 `0` 的结果返回给调用者。
    return 0;
}
