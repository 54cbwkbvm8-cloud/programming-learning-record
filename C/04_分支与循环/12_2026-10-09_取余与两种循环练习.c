// --------------------------------------------------------------------
// 第一部分：引入"工具箱"
// --------------------------------------------------------------------
// <stdio.h> 是"标准输入输出"工具箱：printf（输出）和 scanf（输入）都在里面。
#include <stdio.h>


// --------------------------------------------------------------------
// 第二部分：main 函数 —— 程序从这里开始
// --------------------------------------------------------------------
// 程序从 main 开始，从上往下一行一行执行。
int main(void) {

    // --------------------------------------------------------------------
    // 任务 1、2：分数的奇偶和是否及格
    // --------------------------------------------------------------------
    // score 存输入的分数（整数）。
    int score;
    printf("请输入你的分数:");

    // %d 读一个整数；&score 是 score 的地址，scanf 要把读到的数放进这个地址。
    scanf("%d", &score);

    // % 是取余：score 除以 2 余 0 就是偶数，否则是奇数。例：75 % 2 是 1，所以 75 是奇数。
    if (score % 2 == 0) {
        printf("你的分数是偶数\n");
    } else {
        printf("你的分数是奇数\n");
    }

    // >= 是"大于或等于"，60 分及以上算及格。
    if (score >= 60) {
        printf("你的成绩及格了\n");
    } else {
        printf("你的成绩不及格\n");
    }

    // --------------------------------------------------------------------
    // 任务 3：for 和 while 各输出一段数字
    // --------------------------------------------------------------------
    // i 是循环计数器，下面的 for 和 while 都要用到它。
    int i;
    printf("for循环演示，输出 1～10\n");

    // for (初始化; 条件; 每轮结束后做的事)：i 从 1 数到 10，每轮输出一个数，共 10 轮。
    // i++ 叫"自增"，等价于 i = i + 1。
    for (i = 1; i <= 10; i++) {
        printf("%d\n", i);
    }

    // for 结束时 i 已经变成 11，这里再明确赋一次值 11，让 while 的起点一目了然。
    i = 11;
    printf("while循环演示，输出 11～20\n");

    // while 和 for 能做同样的事，区别在于写法：
    //   for 把"初始化、条件、变化"写在一行；
    //   while 的初始化写在循环前（上面的 i = 11），变化写在循环体里（下面的 i++）。
    while (i <= 20) {
        printf("%d\n", i);

        // 让 i 加 1。缺了这一句，i 永远是 11，条件一直成立，循环就停不下来了。
        i++;
    }

    // --------------------------------------------------------------------
    // 任务 4：三个数中的最大值
    // --------------------------------------------------------------------
    printf(" 请你再输入三个数字\n");

    // 一行声明三个整数变量，用逗号隔开。
    int a, b, c;

    // 一条 scanf 一次读三个整数，数字之间用空格或回车隔开都可以。
    // 例：输入 4 9 7，a 是 4，b 是 9，c 是 7。
    scanf("%d %d %d", &a, &b, &c);

    // max 用来存最大值。
    int max;

    // 先在 a、b 里选出较大的那个，放进 max。
    if (a > b) {
        max = a;
    } else {
        max = b;
    }

    // 再拿 max 和 c 比，c 更大就换成 c。这样三个数只要比两次，就能得到最大值。
    // 例：a 是 4，b 是 9，c 是 7：先得到 max 是 9；9 < 7 不成立；最大值是 9。
    if (max < c) {
        max = c;
    }

    // %d 是整数占位符，会被 max 的值替换。
    printf("max=%d\n", max);

    // --------------------------------------------------------------------
    // 任务 5：计算 1 到 100 的和，对照 for 和 while
    // --------------------------------------------------------------------
    // sum 存累加的结果，必须从 0 开始。
    int sum = 0;

    // for 版本：i 从 1 数到 100。
    for (i = 1; i <= 100; i++) {
        // += 是"加上再赋值"：sum += i 等价于 sum = sum + i。
        sum += i;
    }

    // 结果是 5050。
    printf("1～100 的和是：%d\n", sum);

    // while 版本：用新的变量 sum2 存结果，i2 做计数器。
    int sum2 = 0;
    int i2;

    // 给计数器赋初值 1（while 的初始化要写在循环外面）。
    i2 = 1;
    while (i2 <= 100) {
        sum2 += i2;

        // 每轮让 i2 加 1，让循环最终能结束。
        i2++;
    }

    // 两种写法的结果都是 5050，说明在这类题目里，for 和 while 可以互换。
    printf("1～100 的和是：%d\n", sum2);
    return 0;
}

