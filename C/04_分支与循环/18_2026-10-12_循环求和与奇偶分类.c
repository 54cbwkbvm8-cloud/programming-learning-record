// --------------------------------------------------------------------
// 第一部分：引入"工具箱"
// --------------------------------------------------------------------
// <stdio.h> 是"标准输入输出"工具箱，printf（输出）在里面。
#include <stdio.h>


// --------------------------------------------------------------------
// 第二部分：全局变量（写在所有函数外面）
// --------------------------------------------------------------------
// 写在函数外面的变量叫"全局变量"，整个程序里的函数都能使用它。
// 这里 i 做循环计数器，sum 存累加结果。
// 全局变量如果不手动赋值，系统会自动把它设成 0；sum 这里明确写了 = 0，意思更清楚。
// （写在函数里面的"局部变量"不会自动清零，里面是随机值，所以局部变量一定要先赋值再用。）
int i;
int sum = 0;


// --------------------------------------------------------------------
// 第三部分：main 函数 —— 程序从这里开始
// --------------------------------------------------------------------
int main(void) {

    // i 已经是全局变量，所以 for 里只写赋值 i = 1，不用再写 int。
    // for (初始化; 条件; 每轮结束后做的事)：i 从 1 数到 10。
    for (i = 1; i <= 10; i++) {
        // % 是取余：i 除以 2 余 0，就是偶数。
        if (i % 2 == 0) {
            // += 是"加上再赋值"：sum += i 等价于 sum = sum + i。
            // 只有偶数才会被加进来：2 + 4 + 6 + 8 + 10 = 30。
            sum += i;
        }
    }
    printf("1到 10 之间的偶数和为：%d\n", sum);

    // 必须把 sum 清零，再去算下一个结果。如果不清零，就会在上一个结果 30 的基础上继续加，答案就错了。
    sum = 0;
    for (i = 1; i <= 10; i++) {
        // != 是"不等于"：余数不是 0，就是奇数。
        if (i % 2 != 0) {
            // 这一次累加奇数：1 + 3 + 5 + 7 + 9 = 25。
            sum += i;
        }
    }
    printf("1到 10 之间的奇数和为：%d\n", sum);

    // 再次清零。
    sum = 0;

    // 这一次不用 if：让 i 每轮加 2（取值 1、3、5、7、9），本身就只会遇到奇数。
    // i = i + 2 就是 for 括号里"每轮结束后做的事"。
    // 结果同样是 25。这种写法循环只执行 5 次，比上一种（10 次）更省。
    for (i = 1; i <= 10; i = i + 2) {
        sum += i;
    }
    printf("1到 10 之间的奇数和为：%d\n", sum);

    // j 用来暂存奇数和。
    int j;

    // 把奇数和 25 暂存到 j 里。因为下一步要把 sum 清零重新用，不先存起来，25 就丢了。
    j = sum;
    sum = 0;

    // 这一次累加所有的数。
    for (i = 1; i <= 10; i++) {
        // 1 + 2 + ... + 10 = 55。
        sum += i;
    }
    printf("1到 10 之间的和为：%d\n", sum);

    // 偶数和 = 总和 - 奇数和 = 55 - 25 = 30，与最开始直接算出的偶数和一致，说明几种算法互相验证了。
    printf("1到 10 之间的偶数和为：%d\n", sum - j);

    // return 0：结束 main，把 0 交给系统，表示"程序正常结束"。
    return 0;
}

