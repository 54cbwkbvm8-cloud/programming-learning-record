//       2. 1 到 10 的奇数和（用 if 挑出奇数）
//       3. 1 到 10 的奇数和（i 每次加 2，不用 if）
//       4. 1 到 10 的总和，再用"总和 - 奇数和"得到偶数和，和第 1 个结果对照
