// --------------------------------------------------------------------
// 第一部分：引入"工具箱"
// --------------------------------------------------------------------
// <stdio.h> 是"标准输入输出"工具箱，printf（输出）在里面。
#include <stdio.h>


// --------------------------------------------------------------------
// 第二部分：main 函数 —— 程序从这里开始
// --------------------------------------------------------------------
// 程序从 main 开始，从上往下一行一行执行。
int main(void) {

    // --------------------------------------------------------------------
    // 任务 1：输出 1 到 100
    // --------------------------------------------------------------------
    // 先打印一行标题，让每一块输出之间有清楚的分隔。
    printf("==========输出 1～100==========\n");

    // for 循环的写法：for (初始化; 条件; 每轮结束后做的事) { 循环体 }
    // 执行顺序：
    //   1) 先执行一次 int i = 1（初始化）；
    //   2) 检查条件 i <= 100，成立就执行大括号里的循环体；
    //   3) 循环体执行完，做 i++（i 加 1）；
    //   4) 回到第 2 步再检查，条件不成立就结束循环。
    // 这里 i 从 1 数到 100，循环体一共执行 100 轮。
    // int i 写在 for 的括号里，所以 i 只在这个 for 里有效，循环结束后就不存在了。
    for (int i = 1; i <= 100; i++) {
        // 每轮输出当前的 i。%d 是整数占位符；后面带一个空格，数字之间才不会粘在一起。
        printf("%d ", i);
    }

    // 循环全部结束后换一行，不然后面的标题会接在数字后面。
    printf("\n");
    printf("================1~100的数字求和================\n");   // 100的数字求和

    // 一行声明两个变量，用逗号隔开：i 用来计数；sum 存累加的结果，声明时就赋初值 0。
    // 为什么 sum 必须从 0 开始？sum 要不断往上加，起点必须是 0，
    // 否则它里面是随机的旧数据，加出来的结果就是错的。
    // 前面 for 里的 i 已经失效了，所以这里重新声明一个 i。
    int i, sum = 0;

    // 这一次 i 是已经声明好的变量，所以 for 的第一部分只写赋值 i = 1，不再写 int。
    for (i = 1; i <= 100; i++) {
        // += 是"加上再赋值"：sum += i 等价于 sum = sum + i。每一轮把当前的 i 加进 sum。
        // 例：i 是 1，sum 变 1；i 是 2，sum 变 3；i 是 3，sum 变 6……一直加到 i 是 100。
        sum += i;
    }
    printf("1~100的和为：%d\n", sum);   // 100的和为

    // --------------------------------------------------------------------
    // 任务 3：输出 1 到 100 中的偶数
    // --------------------------------------------------------------------
    printf("=============输出 1～100 的偶数=============\n");

    // 思路：把 1 到 100 每个数都走一遍，用 if 挑出偶数。
    for (i = 1; i <= 100; i++) {
        // % 是取余：i 除以 2 余 0，就是偶数。例：6 % 2 是 0（偶数），7 % 2 是 1（奇数）。
        // == 是"判断是否相等"。只有条件成立，才会执行大括号里的 printf。
        if (i % 2 == 0) {
            printf("%d ", i);
        }
    }
    printf("\n");

    // --------------------------------------------------------------------
    // 任务 4：计算 1 到 100 中偶数的和
    // --------------------------------------------------------------------
    printf("======输出 1～100 的偶数和======\n");

    // 再准备一个累加变量 sum2，专门存偶数的和，同样要从 0 开始。
    // 为什么不继续用 sum？sum 里已经存着 5050，不清零继续加会得到错误的结果，所以另开一个变量。
    int sum2 = 0;

    // 再把 1 到 100 走一遍，这次只累加偶数。
    for (i = 1; i <= 100; i++) {
        if (i % 2 == 0) {
            // 只有 i 是偶数时才会执行这句，所以 sum2 是 2 + 4 + 6 + ... + 100 = 2550。
            sum2 += i;
        }
    }
    printf("1~100的偶数和为：%d\n", sum2);   // 100的偶数和为

    // --------------------------------------------------------------------
    // 任务 5：输出九九乘法表
    // --------------------------------------------------------------------
    printf("=============输出九九乘法表=============\n");

    // j 是内层循环的计数器，初始值先设为 0，后面的 for 会把它重新赋成 1。
    int j = 0;

    // 外层循环：i 控制"第几行"，从 1 到 9，一共 9 行。
    for (i = 1; i <= 9; i++) {
        // 内层循环：j 控制这一行里的"第几个式子"，j 从 1 数到 i。
        // 所以第 i 行输出 i 个式子（第 1 行 1 个，第 2 行 2 个……），整体形成一个三角形。
        // 嵌套循环的执行规律：外层每走一轮，内层都要从头到尾完整地跑一遍。
        // 例：i 是 3 时，j 依次取 1、2、3，输出 3*1=3 3*2=6 3*3=9。
        for (j = 1; j <= i; j++) {
            // 三个 %d 依次对应后面的 i、j、i * j（* 是乘号）。末尾的空格用来隔开相邻的式子。
            printf("%d*%d=%d ", i, j, i * j);
        }

        // 内层循环跑完，这一行输完了，换行再进入下一行。
        // 注意它写在内层循环的大括号外面、外层循环的大括号里面，所以每一行只换一次行。
        printf("\n");
    }
    return 0;
}

