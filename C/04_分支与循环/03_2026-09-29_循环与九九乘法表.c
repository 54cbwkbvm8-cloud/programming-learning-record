//       2. 计算 1 到 100 的和
//       3. 输出 1 到 100 中的所有偶数
//       4. 计算 1 到 100 中偶数的和
//       5. 输出九九乘法表
//
// 怎么运行（在 Mac 终端里，先 cd 到这个文件所在的文件夹）：
//   编译：clang -Wall -Wextra -o demo "03_2026-09-29_循环与九九乘法表.c"
//   运行：./demo
//   说明：编译 = 把人能看懂的 C 代码翻译成电脑能执行的程序。
//         -Wall -Wextra 的意思是"把所有可疑的地方都警告我"，
