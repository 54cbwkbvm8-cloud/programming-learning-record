    int max;
// 声明变量并确定其数据类型；未初始化的局部变量不能直接当作已知值使用。
    int min;
// 声明变量并确定其数据类型；未初始化的局部变量不能直接当作已知值使用。
    float avg;
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("请输入 5 个整数：");
// 从标准输入读取数据；检查读取结果和输入范围，避免把无效输入当作有效数据继续处理。
    scanf("%d%d%d%d%d", &a[0], &a[1], &a[2], &a[3], &a[4]);
// 循环按“初始化；条件判断；每轮更新”的顺序执行。先检查条件，再运行循环体，最后更新循环变量；注意边界是否会多执行或少执行一次。
    for (i = 0; i < 5; i++) {
// 更新变量或保存计算结果；逐步跟踪右侧表达式，有助于理解每轮循环中的数据变化。
        sum += a[i];
    }
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("这 5 个整数的和为：%d", sum);
// 更新变量或保存计算结果；逐步跟踪右侧表达式，有助于理解每轮循环中的数据变化。
    max = a[0];
// 循环按“初始化；条件判断；每轮更新”的顺序执行。先检查条件，再运行循环体，最后更新循环变量；注意边界是否会多执行或少执行一次。
    for (i = 1; i < 5; i++) {
// 判断条件 `(a[i] > max)` 是否成立；条件为真时执行对应分支，否则跳过或转入其他分支。
        if (a[i] > max) {
// 更新变量或保存计算结果；逐步跟踪右侧表达式，有助于理解每轮循环中的数据变化。
            max = a[i];
        }
    }
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("\n");
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("这 5 个整数的最大值为：%d", max);
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("\n");
// 更新变量或保存计算结果；逐步跟踪右侧表达式，有助于理解每轮循环中的数据变化。
    min = a[0];
// 循环按“初始化；条件判断；每轮更新”的顺序执行。先检查条件，再运行循环体，最后更新循环变量；注意边界是否会多执行或少执行一次。
    for (i = 1; i < 5; i++) {
// 判断条件 `(a[i] < min)` 是否成立；条件为真时执行对应分支，否则跳过或转入其他分支。
        if (a[i] < min) {
// 更新变量或保存计算结果；逐步跟踪右侧表达式，有助于理解每轮循环中的数据变化。
            min = a[i];
        }
    }
