// --------------------------------------------------------------------
// 第一部分：引入"工具箱"
// --------------------------------------------------------------------
// <stdio.h> 是"标准输入输出"工具箱：printf（输出）和 scanf（输入）都在里面。
#include <stdio.h>


// --------------------------------------------------------------------
// 第二部分：main 函数 —— 程序从这里开始
// --------------------------------------------------------------------
int main(void) {

    // 数组 = 一排连在一起的同类型格子。int a[5] 表示 5 个整数格子，下标是 0 到 4（没有 a[5]）。
    int a[5];

    // i 是循环计数器，后面的 for 循环都用它。
    int i;

    // sum 存总和，必须先设成 0，累加才不会从随机数开始。
    int sum = 0;

    // max 存最大值，min 存最小值，avg 存平均值（平均数可能有小数，所以用 float）。
    int max;
    int min;
    float avg;
    printf("请输入 5 个整数：");

    // 一条 scanf 读 5 个整数：5 个 %d 依次对应后面的 &a[0]、&a[1]……&a[4]。
    // 输入时数字之间用空格或回车隔开都行（scanf 会自动跳过空白）。
    // & 是取地址符：scanf 要把数放进数组元素里，必须知道元素的地址。
    // 例：输入 12 5 30 8 25，a[0] 是 12，a[1] 是 5，a[2] 是 30，a[3] 是 8，a[4] 是 25。
    scanf("%d%d%d%d%d", &a[0], &a[1], &a[2], &a[3], &a[4]);

    // --------------------------------------------------------------------
    // 第三部分：求总和
    // --------------------------------------------------------------------
    // for (初始化; 条件; 每轮结束后做的事)：i 从 0 数到 4，正好走遍数组的 5 个元素。
    // 条件是 i < 5：下标最大是 4，写 <= 5 就会越界。
    for (i = 0; i < 5; i++) {
        // += 是"加上再赋值"：sum += a[i] 等价于 sum = sum + a[i]。例：12 + 5 + 30 + 8 + 25 = 80。
        sum += a[i];
    }

    // %d 是整数占位符，会被 sum 的值替换。这条没有 \n，下面单独换行。
    printf("这 5 个整数的和为：%d", sum);

    // --------------------------------------------------------------------
    // 第四部分：求最大值
    // --------------------------------------------------------------------
    // "打擂台"：先假设第一个元素最大，放进 max，后面的元素依次来挑战。
    max = a[0];

    // 从下标 1 开始比，因为下标 0 的数已经放进 max 了。
    for (i = 1; i < 5; i++) {
        // 如果这个数比当前最大值还大，就更新最大值。
        // 例：数组 12 5 30 8 25：max 先是 12；5 不大于；30 大于，变 30；8、25 不大于；最大值是 30。
        if (a[i] > max) {
            max = a[i];
        }
    }

    // 单独输出一个换行，让下一行的输出另起一行。
    printf("\n");
    printf("这 5 个整数的最大值为：%d", max);
    printf("\n");

    // --------------------------------------------------------------------
    // 第五部分：求最小值
    // --------------------------------------------------------------------
    // 和求最大值对称：先假设第一个最小，遇到更小的就更新。
    min = a[0];
    for (i = 1; i < 5; i++) {
        if (a[i] < min) {
            min = a[i];
        }
    }
    printf("这 5 个整数的最小值为：%d", min);
    printf("\n");

    // --------------------------------------------------------------------
    // 第六部分：求平均值
    // --------------------------------------------------------------------
    // (float)sum 叫"强制类型转换"：把整数 sum 临时当作 float 用。
    // 为什么要转？整数除以整数，小数部分会被丢掉（82 / 5 得 16，不是 16.4）。
    // 先把 sum 转成小数，再除以 5，才能得到带小数的平均值。
    avg = (float)sum / 5;

    // %.2f 表示保留两位小数。例：80 / 5 是 16，显示 16.00。
    printf("这 5 个整数的平均值为：%.2f", avg);
    printf("\n");

    // --------------------------------------------------------------------
    // 第七部分：逆序输出
    // --------------------------------------------------------------------
    printf("数组的逆序为：");

    // 逆序输出的关键：让 i 从最后一个下标 4 开始，每轮减 1（i--），一直到 0 为止。
    // 所以条件写 i >= 0（要包含下标 0）。i-- 是"自减"，等价于 i = i - 1。
    // 例：i 依次是 4、3、2、1、0，输出 a[4]、a[3]、a[2]、a[1]、a[0]，也就是 25 8 30 5 12。
    for (i = 4; i >= 0; i--) {
        // 每个数后面跟一个空格，数字之间才不会粘在一起。
        printf("%d ", a[i]);
    }
    printf("\n");

    // return 0：结束 main，把 0 交给系统，表示"程序正常结束"。
    return 0;
}

