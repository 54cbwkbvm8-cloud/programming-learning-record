// --------------------------------------------------------------------
// 第一部分：引入"工具箱"
// --------------------------------------------------------------------
// <stdio.h> 是"标准输入输出"工具箱：printf（输出）和 scanf（输入）都在里面。
#include <stdio.h>


// --------------------------------------------------------------------
// 第二部分：全局变量（写在所有函数外面）
// --------------------------------------------------------------------
// 写在函数外面的变量叫"全局变量"，整个程序的函数都能使用。
//   a、b、c 存输入的整数，max 存最大值，
//   sum 存累加的和（用 double 类型），i 是计数器，初始值是 1。
// 全局变量如果不手动赋值，系统会自动设成 0，所以 sum 一开始就是 0。
// （写在函数里面的局部变量不会自动清零，里面是随机值。）
int a;
int b;
int c;
int max;
double sum;
int i = 1;


// --------------------------------------------------------------------
// 第三部分：main 函数 —— 程序从这里开始
// --------------------------------------------------------------------
int main(void) {

    // --------------------------------------------------------------------
    // 任务 1：两个整数的和，以及奇偶组合
    // --------------------------------------------------------------------
    printf("请输入两个整数：");

    // 一次读两个整数，用空格或回车隔开。& 是取地址符，scanf 要知道变量的地址才能把数放进去。
    scanf("%d %d", &a, &b);

    // %d 后面可以直接放一个算式：先算出 a + b 的结果，再显示出来。
    printf("a + b =%d\n", a + b);

    // a 和 b 各有"奇"和"偶"两种可能，组合起来一共 4 种，所以用 if ... else if ... else 把 4 种情况分开。
    // % 是取余：除以 2 余 0 是偶数，余数不是 0（!= 0）就是奇数。
    // && 读作"并且"：两个条件都成立，整个条件才成立。
    if (a % 2 == 0 && b % 2 == 0) {
        printf("a 和 b 都是偶数\n");

    // a 是偶数并且 b 是奇数。例：输入 4 和 9：4 % 2 是 0，9 % 2 是 1，正好满足这一条。
    } else if (a % 2 == 0 && b % 2 != 0) {
        printf("a 是偶数，b 是奇数\n");

    // a 是奇数并且 b 是偶数。
    } else if (a % 2 != 0 && b % 2 == 0) {
        printf("a 是奇数，b 是偶数\n");

    // 前面三种都不是，只剩"两个都是奇数"这一种，所以 else 后面不用再写条件。
    } else {
        printf("a 和 b 都是奇数\n");
    }

    // --------------------------------------------------------------------
    // 任务 2：三个数的最大值
    // --------------------------------------------------------------------
    printf("请再输入一个整数：\n");
    scanf("%d", &c);

    // "打擂台"：先假设 a 最大，再让 b、c 依次来挑战。
    max = a;

    // b 比当前最大值大，就更新。
    if (b > max) {
        max = b;
    }

    // c 也要和当前最大值比一次。这里是两个独立的 if（不是 else if），因为 b、c 都要各比一次。
    // 例：a 是 4，b 是 9，c 是 7：max 先是 4；9 > 4，变 9；7 > 9 不成立；最大值是 9。
    if (c > max) {
        max = c;
    }
    printf("最大值是：%d\n", max);

    // --------------------------------------------------------------------
    // 任务 3：用 while 计算 1 到 100 的和
    // --------------------------------------------------------------------
    // 全局变量 i 初始值是 1。while (条件)：条件成立就执行一遍循环体，执行完再回头检查，直到条件不成立。
    while (i <= 100) {
        // 把当前的 i 加进 sum。sum 是 double、i 是 int，相加时 i 会自动当作 double 参与运算。
        sum = sum + i;

        // i++ 让 i 加 1。缺了这一句，i 永远是 1，条件一直成立，就变成死循环。
        i++;
    }
    printf("1~100 的和是：%.0f\n", sum);   // 100 的和是

    // --------------------------------------------------------------------
    // 任务 4：不用数组，边输入边求最大值和平均值
    // --------------------------------------------------------------------
    printf("请输入 10 个整数求最大值：\n");

    // 重新使用 max 和 sum，先清零。
    max = 0;
    sum = 0;

    // i 是全局变量，这里重新让它从 0 数到 9，读 10 个数。
    for (i = 0; i < 10; i++) {
        // 每次读入的数都放进 a，下一次读入会覆盖上一次。不用数组，是因为这里只需要"当时比较一下、累加一下"，不需要保存每个数。
        scanf("%d", &a);

        // || 读作"或者"。第一个数（i 是 0）直接当作最大值；之后的数，只有比 max 大才更新。
        // 为什么要单独处理第一个数？max 开始是 0，如果输入的数全是负数，max 一直保持 0 就是错的。
        // 让第一个数无条件成为初始最大值，就能避免这种错误。
        if (i == 0 || a > max) {
            max = a;
        }

        // 把读到的每个数都累加进总和。
        sum = sum + a;
    }
    printf("最大值是：%d\n", max);

    // sum 是 double，除以 10.0 得到带小数的平均值；%.2f 保留两位小数。
    printf("这十个整数的平均值为 %.2f\n", sum / 10.0);

    // --------------------------------------------------------------------
    // 任务 5：用数组保存 10 个整数，求平均值、最大值、最小值
    // --------------------------------------------------------------------
    // int arr[10] 是 10 个整数格子，下标 0 到 9。这一次要先把 10 个数都存下来，再统计。
    int arr[10];

    // m 做循环计数器，sum2 存总和，max2 存最大值，min2 存最小值。
    int m;
    double sum2 = 0.0;

    // max2、min2 声明时没有赋初值，里面是随机值，下面用"m == 0 ||"来保证第一个数先给它们赋值。
    int max2;
    int min2;
    printf("请输入 10 个整数求最大值：\n");

    // m 从 0 数到 9，正好对应数组的 10 个下标。
    for (m = 0; m < 10; m++) {
        // arr[m] 是数组里的一个整数格子，和普通变量一样需要取地址符 &。
        scanf("%d", &arr[m]);

        // 注意 || 的"短路"特点：左边成立时，右边根本不会计算。
        // m 是 0（第一个数）时，左边 m == 0 成立，右边 arr[m] > max2 就不会被计算。
        // 这一点很重要：此时 max2 还没有被赋过值，不能拿来比较。于是第一个数直接成为最大值。
        // 之后的数，左边不成立，才会拿 arr[m] 和 max2 比较。
        // 编译器看不出这个逻辑，可能会提示 max2 "可能未初始化"，但实际运行是安全的。
        if (m == 0 || arr[m] > max2) {
            max2 = arr[m];
        }

        // 最小值的处理和最大值完全对称。
        if (m == 0 || arr[m] < min2) {
            min2 = arr[m];
        }
    }

    // 数组存好之后，再走一遍，把所有数累加起来。
    for (m = 0; m < 10; m++) {
        // += 是"加上再赋值"：sum2 += arr[m] 等价于 sum2 = sum2 + arr[m]。
        sum2 += arr[m];
    }

    // sum2 / 10.0：总和除以 10.0 得到带小数的平均值，%.2f 保留两位小数。
    printf("平均值是：%.2f\n", sum2 / 10.0);
    printf("最大值是：%d\n", max2);
    printf("最小值是：%d\n", min2);

    // 上面已经输出过一次平均值，这里又输出了一次，内容和上一行相同（原代码如此）。
    printf("这十个整数的平均值为 %.2f\n", sum2 / 10.0);

    // return 0：结束 main，把 0 交给系统，表示"程序正常结束"。
    return 0;
}

