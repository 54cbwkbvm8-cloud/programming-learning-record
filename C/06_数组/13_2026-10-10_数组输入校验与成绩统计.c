#include <stdio.h>
// 该宏用于集中定义常量或短表达式，修改时需确认所有使用位置。
#define N 5
// 定义函数 main；参数接收调用方传入的数据，函数体完成操作，返回语句（如有）把结果交还调用者。
int main(void) {
// 声明数组并为元素分配连续空间；下标从 0 开始，有效范围必须小于数组长度。
    float scores[N];
// 声明并初始化变量；`=` 是赋值运算符，用右侧表达式的值设置左侧变量，而不是比较两个值。
    float sum = 0.0f;
// 声明并初始化变量；`=` 是赋值运算符，用右侧表达式的值设置左侧变量，而不是比较两个值。
    float average = 0.0f;
// 声明变量并确定其数据类型；未初始化的局部变量不能直接当作已知值使用。
    float max;
// 声明变量并确定其数据类型；未初始化的局部变量不能直接当作已知值使用。
    float min;
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("==========学生成绩管理系统==========\n");
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("请输入%d 个学生的成绩:\n", N);
// 循环按“初始化；条件判断；每轮更新”的顺序执行。先检查条件，再运行循环体，最后更新循环变量；注意边界是否会多执行或少执行一次。
    for (int i = 0; i < N; i++) {
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
        printf("请输入第%d 个学生的成绩:", i + 1);
// 判断条件 `(scanf(字符串, &scores[i]) != 1)` 是否成立；条件为真时执行对应分支，否则跳过或转入其他分支。
        if (scanf("%f", &scores[i]) != 1) {
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
            printf("输入错误，请重新输入\n");
// 声明变量并确定其数据类型；未初始化的局部变量不能直接当作已知值使用。
            int c;
// 只要 while 后的条件成立，就重复执行循环体；检查循环体是否会推进相关变量，确保条件最终能变为假。
            while ((c = getchar()) != '\n' && c != EOF)
                ;
// 更新计数变量；`++` 每次加 1，`--` 每次减 1，注意更新发生的位置。
            i--;
            continue;
        }
    }
// 循环按“初始化；条件判断；每轮更新”的顺序执行。先检查条件，再运行循环体，最后更新循环变量；注意边界是否会多执行或少执行一次。
    for (int i = 0; i < N; i++) {
// 更新变量或保存计算结果；逐步跟踪右侧表达式，有助于理解每轮循环中的数据变化。
        sum += scores[i];
    }
// 更新变量或保存计算结果；逐步跟踪右侧表达式，有助于理解每轮循环中的数据变化。
    average = sum / N;
// 更新变量或保存计算结果；逐步跟踪右侧表达式，有助于理解每轮循环中的数据变化。
    max = scores[0];
// 更新变量或保存计算结果；逐步跟踪右侧表达式，有助于理解每轮循环中的数据变化。
    min = scores[0];
// 循环按“初始化；条件判断；每轮更新”的顺序执行。先检查条件，再运行循环体，最后更新循环变量；注意边界是否会多执行或少执行一次。
    for (int i = 1; i < N; i++) {
// 判断条件 `(scores[i] > max)` 是否成立；条件为真时执行对应分支，否则跳过或转入其他分支。
        if (scores[i] > max) {
// 更新变量或保存计算结果；逐步跟踪右侧表达式，有助于理解每轮循环中的数据变化。
            max = scores[i];
        }
// 判断条件 `(scores[i] < min)` 是否成立；条件为真时执行对应分支，否则跳过或转入其他分支。
        if (scores[i] < min) {
// 更新变量或保存计算结果；逐步跟踪右侧表达式，有助于理解每轮循环中的数据变化。
            min = scores[i];
        }
    }
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("平均分：%.2f\n", average);
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("最高分：%.2f\n", max);
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("最低分：%.2f\n", min);
// 结束当前函数调用，并把表达式 `0` 的结果返回给调用者。
    return 0;
}
