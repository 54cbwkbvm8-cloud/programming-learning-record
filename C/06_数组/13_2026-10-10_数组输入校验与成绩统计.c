//   说明：编译 = 把人能看懂的 C 代码翻译成电脑能执行的程序。
//         -Wall -Wextra 的意思是"把所有可疑的地方都警告我"，
//         编译时出现警告，一定要弄明白原因，不要忽略。
// ====================================================================


// --------------------------------------------------------------------
// 第一部分：引入"工具箱"和宏定义
// --------------------------------------------------------------------
// <stdio.h> 是"标准输入输出"工具箱：printf、scanf、getchar 都在里面。
#include <stdio.h>

// #define N 5 叫"宏定义"：编译之前，程序里所有的 N 都会被直接替换成 5（行末不写分号）。
// 为什么这样写？学生人数以后可能改成 10，只改这一行，数组大小、循环次数、平均数的除数就全跟着变，
// 不会漏改。数组的大小必须是确定的常量，所以用 #define 定义。
#define N 5


// --------------------------------------------------------------------
// 第二部分：main 函数 —— 程序从这里开始
// --------------------------------------------------------------------
int main(void) {

    // float scores[N] 声明一个有 N（也就是 5）个元素的 float 数组，用来存成绩。
    // float 是带小数的类型，所以成绩可以是 75.5 这样的小数。下标是 0 到 4。
    float scores[N];

    // sum 存总分，先设成 0（0.0f 末尾的 f 表示这是 float 类型的小数）。
    float sum = 0.0f;

    // average 存平均分，max 存最高分，min 存最低分。
    float average = 0.0f;
    float max;
    float min;

    // --------------------------------------------------------------------
    // 第三部分：输入成绩（带输入校验）
    // --------------------------------------------------------------------
    printf("==========学生成绩管理系统==========\n");

    // 这里的 %d 对应的是 N（也就是 5）。
    printf("请输入%d 个学生的成绩:\n", N);

    // i 从 0 数到 N - 1，每轮读入一个学生的成绩。条件写 i < N：数组 N 个元素，下标最大是 N - 1。
    for (int i = 0; i < N; i++) {
        // i + 1：下标从 0 开始，显示给人看的编号从 1 开始，所以加 1。
        printf("请输入第%d 个学生的成绩:", i + 1);

        // %f 读一个 float 小数。scanf 有返回值：成功读到几个数据就返回几，这里成功时返回 1。
        // != 1 表示"没读成功"，例如应该输入数字，你却输入了字母 abc。
        // 为什么要检查？输入出错时 scores[i] 没有得到正确的值，不检查的话，程序会拿着错误的数据继续往下算。
        if (scanf("%f", &scores[i]) != 1) {
            printf("输入错误，请重新输入\n");
            int c;

            // 这是"清理输入缓冲区"的固定写法。
            // 为什么要清理？scanf 读失败时，错误的字符（比如 abc）还留在输入缓冲区里。
            // 如果不清掉，下一次 scanf 又会读到它，再次失败，程序就会一直卡在这里循环。
            // getchar() 每次从输入里读走一个字符。这个循环不断读走字符，直到读到换行符 '\n'（这一行读完了）
            // 或者 EOF（输入已经结束）为止。
            // c 用 int 而不用 char：因为 EOF 是一个特殊的负数，char 不一定装得下。
            while ((c = getchar()) != '\n' && c != EOF)

                // 循环体只有一个分号，表示"空语句"：读走字符就是循环条件要做的事，循环体不需要再做别的。
                ;

            // 把 i 减 1。这一步和下面的 continue 配合：for 每轮结束时会自动 i++，
            // 这里先减 1，再自动加 1，i 就保持不变，于是同一个学生会重新输入一次。
            i--;

            // continue 的意思是"跳过本轮循环剩下的代码，直接进入下一轮"。
            // 例：输入第 2 个学生时打了 abc：报错、清理、i-- 后 continue，下一轮 i 仍然对应第 2 个学生，重新输入。
            continue;
        }
    }

    // --------------------------------------------------------------------
    // 第四部分：计算平均分
    // --------------------------------------------------------------------
    // 走遍数组，把所有成绩累加起来。
    for (int i = 0; i < N; i++) {
        // += 是"加上再赋值"：sum += scores[i] 等价于 sum = sum + scores[i]。
        sum += scores[i];
    }

    // 总分除以人数。sum 是 float，所以这里是小数除法，不会丢掉小数部分。
    // 例：90 + 75.5 + 60 + 88 + 100 = 413.5，除以 5 得 82.7。
    average = sum / N;

    // --------------------------------------------------------------------
    // 第五部分：找最高分和最低分
    // --------------------------------------------------------------------
    // "打擂台"：先假设第一个成绩既是最高分，也是最低分，后面的成绩依次来挑战。
    max = scores[0];
    min = scores[0];

    // 从下标 1 开始比较，因为下标 0 已经放进 max 和 min 了。
    for (int i = 1; i < N; i++) {
        // 比当前最高分还高，就更新最高分。
        if (scores[i] > max) {
            max = scores[i];
        }

        // 比当前最低分还低，就更新最低分。注意这里是另一个独立的 if，不是 else if：一个成绩两个条件都要各检查一次。
        if (scores[i] < min) {
            min = scores[i];
        }
    }

    // --------------------------------------------------------------------
    // 第六部分：输出结果
    // --------------------------------------------------------------------
    // %.2f 表示按小数输出并保留两位。
    printf("平均分：%.2f\n", average);
    printf("最高分：%.2f\n", max);
    printf("最低分：%.2f\n", min);

    // return 0：结束 main，把 0 交给系统，表示"程序正常结束"。
    return 0;
}

