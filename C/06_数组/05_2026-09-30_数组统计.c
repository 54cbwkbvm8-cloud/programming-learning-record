// --------------------------------------------------------------------
// 第一部分：引入"工具箱"
// --------------------------------------------------------------------
// <stdio.h> 是"标准输入输出"工具箱：printf（输出）和 scanf（输入）都在里面。
#include <stdio.h>


// --------------------------------------------------------------------
// 第二部分：main 函数 —— 程序从这里开始
// --------------------------------------------------------------------
int main(void) {

    // 数组 = 一排连在一起的同类型格子。int arr[10] 表示 10 个整数格子，名字叫 arr。
    // 下标从 0 开始，所以合法下标是 0 到 9，没有 arr[10]（访问它就是"越界"，程序可能出错）。
    // 刚声明的数组里是随机的旧数据，要先输入或赋值才能用。
    // 为什么用数组？要存 10 个数，如果用 10 个变量，代码又长又没法用循环；数组配合循环就很方便。
    int arr[10];

    // max 存最大值，min 存最小值，sum 存总和（先设成 0，因为要不断累加）。
    int max;
    int min;
    int sum = 0;

    // avg 声明了但后面没有用到（平均值直接在 printf 里算的），编译时可能出现"未使用变量"的警告，不影响运行。
    int avg;

    // --------------------------------------------------------------------
    // 第三部分：输入 10 个数字
    // --------------------------------------------------------------------
    printf("请输入10个数字：\n");

    // for (初始化; 条件; 每轮结束后做的事)：i 从 0 数到 9，正好对应数组的 10 个下标。
    // 条件写 i < 10 而不是 i <= 10：因为下标最大是 9，写 <= 会越界。
    // int i 写在 for 括号里，所以这个 i 只在这个 for 里有效。
    for (int i = 0; i < 10; i++) {
        // i + 1：下标从 0 开始，但对人来说是"第 1 个"，所以显示时加 1。例：i 是 0，显示"第 1 个"。
        // %d 是整数占位符，会被后面的 i + 1 替换。
        printf("请输入第%d个数字：", i + 1);

        // scanf 从键盘读一个整数，放进 arr[i]。arr[i] 是数组里的一个整数格子，和普通变量一样，
        // scanf 需要它的"地址"，所以前面要加取地址符 &。
        scanf("%d", &arr[i]);
    }

    // --------------------------------------------------------------------
    // 第四部分：输出刚才输入的数字
    // --------------------------------------------------------------------
    printf("=========================================\n");
    printf("你输入的数字是：\n");

    // 再用一个新的 for 把数组从头到尾走一遍。这里的 i 是新声明的，和上一个 for 里的 i 互不影响。
    for (int i = 0; i < 10; i++) {
        // 两个 %d 依次对应 i + 1 和 arr[i]：前一个是"第几个"，后一个是这个位置里的数。
        printf("第%d个数字是:%d\n", i + 1, arr[i]);
    }

    // --------------------------------------------------------------------
    // 第五部分：找最大值
    // --------------------------------------------------------------------
    // 这一行声明的 i 是整个 main 里都能用的变量，后面的循环用它做计数器（for 里就不用再写 int 了）。
    int i = 0;

    // "打擂台"的思路：先假设第一个数 arr[0] 最大，放进 max，再让后面的数依次来挑战。
    max = arr[0];

    // 从第 2 个数（下标 1）开始比，因为第 1 个已经放进 max 了。
    for (i = 1; i < 10; i++) {
        // 如果这个数比当前最大值还大……
        if (arr[i] > max) {
            // ……就更新最大值。
            // 例：数组是 3 8 1 9 ...：max 先是 3；8 比 3 大，变 8；1 不比 8 大；9 比 8 大，变 9；……最后得到最大值 10。
            max = arr[i];
        }
    }
    printf("=========================================\n");
    printf("最大值是：%d\n", max);

    // --------------------------------------------------------------------
    // 第六部分：找最小值
    // --------------------------------------------------------------------
    // 和找最大值对称：先假设第一个数最小，遇到更小的就更新。
    min = arr[0];
    for (i = 1; i < 10; i++) {
        if (arr[i] < min) {
            min = arr[i];
        }
    }
    printf("最小值是：%d\n", min);

    // --------------------------------------------------------------------
    // 第七部分：计算平均值
    // --------------------------------------------------------------------
    printf("=========================================\n");

    // 累加之前先清零，保证从 0 开始。
    sum = 0;

    // 累加要把每个数都加上，所以下标从 0 开始，一直到 9。
    for (i = 0; i < 10; i++) {
        // += 是"加上再赋值"：sum += arr[i] 等价于 sum = sum + arr[i]。
        sum += arr[i];
    }

    // sum / 10.0：为什么写 10.0 而不是 10？两个整数相除，结果还是整数，小数部分会被丢掉（例如 55 / 10 得 5）。
    // 只要有一个数是小数（10.0），整个运算就按小数算（55 / 10.0 得 5.5）。
    // %f 按小数输出，默认保留 6 位小数。
    printf("平均值是：%f\n", sum / 10.0);

    // return 0：结束 main，把 0 交给系统，表示"程序正常结束"。
    return 0;
}

