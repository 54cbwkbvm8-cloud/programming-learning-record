#include <stdio.h>

// 定义函数 main；参数接收调用方传入的数据，函数体完成操作，返回语句（如有）把结果交还调用者。
int main(void) {
// 声明变量并确定其数据类型；未初始化的局部变量不能直接当作已知值使用。
    int stones;
// 声明变量并确定其数据类型；未初始化的局部变量不能直接当作已知值使用。
    int maxTake;
// 声明变量并确定其数据类型；未初始化的局部变量不能直接当作已知值使用。
    int firstTake;

// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("规则制定：\n");

// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("请输入石子的总颗数：\n");
// 判断条件 `(scanf(字符串, &stones) != 1 || stones <= 0)` 是否成立；条件为真时执行对应分支，否则跳过或转入其他分支。
    if (scanf("%d", &stones) != 1 || stones <= 0) {
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
        printf("输入错误：石子总数必须是正整数。\n");
// 结束当前函数调用，并把表达式 `1` 的结果返回给调用者。
        return 1;
    }

// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("请输入最多能取的石子数：\n");
// 判断条件 `(scanf(字符串, &maxTake) != 1 || maxTake <= 0)` 是否成立；条件为真时执行对应分支，否则跳过或转入其他分支。
    if (scanf("%d", &maxTake) != 1 || maxTake <= 0) {
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
        printf("输入错误：每次最多取石数必须是正整数。\n");
// 结束当前函数调用，并把表达式 `1` 的结果返回给调用者。
        return 1;
    }

// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("=================================================\n");

// 声明并初始化变量；`=` 是赋值运算符，用右侧表达式的值设置左侧变量，而不是比较两个值。
    int remainder = stones % (maxTake + 1);

// 判断条件 `(remainder == 0)` 是否成立；条件为真时执行对应分支，否则跳过或转入其他分支。
    if (remainder == 0) {
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
        printf("提示：当前局面先手没有必胜策略。\n");
// 处理前面条件均不成立时的情况。
    } else {
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
        printf("提示：按照必胜策略，你应该先取 %d 颗石子。\n", remainder);
    }

// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("请输入你先手取的石子数（1 至 %d）：\n", maxTake);

// 判断条件 `(scanf(字符串, &firstTake) != 1 || firstTake < 1 || firstTake > maxTake ||` 是否成立；条件为真时执行对应分支，否则跳过或转入其他分支。
    if (scanf("%d", &firstTake) != 1 || firstTake < 1 || firstTake > maxTake ||
        firstTake > stones) {
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
        printf("输入错误：先手取石数不符合规则。\n");
// 结束当前函数调用，并把表达式 `1` 的结果返回给调用者。
        return 1;
    }

// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("巴什博弈演示：\n");
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("============================================\n");
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("初始石子数为 %d，每次可以取 1 至 %d 颗。\n", stones, maxTake);

// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("你先取 %d 颗，剩余 %d 颗。\n", firstTake, stones - firstTake);

// 更新变量或保存计算结果；逐步跟踪右侧表达式，有助于理解每轮循环中的数据变化。
    stones -= firstTake;

// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("============================================\n");

// 只要 while 后的条件成立，就重复执行循环体；检查循环体是否会推进相关变量，确保条件最终能变为假。
    while (stones > 0) {
// 声明变量并确定其数据类型；未初始化的局部变量不能直接当作已知值使用。
        int opponentTake;

// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
        printf("请输入对手本轮取几颗（1 至 %d，当前剩余 %d）：", maxTake, stones);

// 判断条件 `(scanf(字符串, &opponentTake) != 1)` 是否成立；条件为真时执行对应分支，否则跳过或转入其他分支。
        if (scanf("%d", &opponentTake) != 1) {
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
            printf("输入无效，请重新运行程序并输入整数。\n");
// 结束当前函数调用，并把表达式 `1` 的结果返回给调用者。
            return 1;
        }

// 判断条件 `(opponentTake < 1 || opponentTake > maxTake || opponentTake > stones)` 是否成立；条件为真时执行对应分支，否则跳过或转入其他分支。
        if (opponentTake < 1 || opponentTake > maxTake || opponentTake > stones) {
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
            printf("这次取法不合法，请重新输入。\n");
            continue;
        }

// 更新变量或保存计算结果；逐步跟踪右侧表达式，有助于理解每轮循环中的数据变化。
        stones -= opponentTake;

// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
        printf("对手取走 %d 颗后，还剩 %d 颗。\n", opponentTake, stones);

// 判断条件 `(stones == 0)` 是否成立；条件为真时执行对应分支，否则跳过或转入其他分支。
        if (stones == 0) {
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
            printf("对手取到了最后一颗石子，对手获胜。\n");
            break;
        }

// 声明并初始化变量；`=` 是赋值运算符，用右侧表达式的值设置左侧变量，而不是比较两个值。
        int myTake = maxTake + 1 - opponentTake;

// 判断条件 `(myTake > stones)` 是否成立；条件为真时执行对应分支，否则跳过或转入其他分支。
        if (myTake > stones) {
// 把右侧变量当前保存的值复制到左侧变量；如果右侧是指针，复制的是地址而不是对象内容。
            myTake = stones;
        }

// 更新变量或保存计算结果；逐步跟踪右侧表达式，有助于理解每轮循环中的数据变化。
        stones -= myTake;

// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
        printf("程序回应取走 %d 颗，还剩 %d 颗。\n", myTake, stones);

// 判断条件 `(stones == 0)` 是否成立；条件为真时执行对应分支，否则跳过或转入其他分支。
        if (stones == 0) {
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
            printf("程序取到了最后一颗石子，程序获胜。\n");
            break;
        }
    }

// 结束当前函数调用，并把表达式 `0` 的结果返回给调用者。
    return 0;
}
