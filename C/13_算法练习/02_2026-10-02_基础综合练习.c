// --------------------------------------------------------------------
// 第一部分：引入"工具箱"
// --------------------------------------------------------------------
// <stdio.h> 是"标准输入输出"工具箱：printf（输出）和 scanf（输入）都在里面。
#include <stdio.h>


// --------------------------------------------------------------------
// 第二部分：main 函数 —— 程序从这里开始
// --------------------------------------------------------------------
int main(void) {

    // a、b 存输入的两个整数。刚声明时没有赋值，里面是随机的旧数据，要先输入再使用。
    int a;
    int b;

    // --------------------------------------------------------------------
    // 任务 1：两个整数的和与奇偶判断
    // --------------------------------------------------------------------
    printf("请输入第一个整数：\n");

    // scanf 从键盘读一个整数：%d 读整数，&a 是 a 的地址（& 叫取地址符，scanf 要知道把数放在哪）。
    scanf("%d", &a);
    printf("请输入第二个整数：\n");
    scanf("%d", &b);

    // %d 可以直接放一个算式：先算出 a + b，再显示。
    printf("两个整数的和为 %d\n", a + b);

    // % 是取余，除以 2 余 0 就是偶数。&& 读作"并且"：两边都成立才成立。
    // 这里先判断最特殊的情况：两个数都是偶数。
    if (a % 2 == 0 && b % 2 == 0) {
        printf("两个整数都是偶数\n");

    // else if：前一个条件不成立才会检查这个。|| 读作"或者"：两边成立一边就行。
    // 能走到这里，说明"两个都是偶数"已经不成立，所以这里成立时，恰好是"只有一个是偶数"。
    // 例：a 是 4，b 是 9：两个都是偶数？否；a 是偶数？是，进入这个分支。
    } else if (a % 2 == 0 || b % 2 == 0) {
        printf("两个整数中有一个是偶数\n");

        // 再用一个 if 判断到底是哪一个：if 里面还可以再嵌套 if，叫"嵌套判断"。
        // a 是偶数，那偶数就是第一个整数；否则（else）就是第二个。
        if (a % 2 == 0) {
            printf("第一个整数是偶数\n");
        } else {
            printf("第二个整数是偶数\n");
        }

    // 前面都不成立：既不是都为偶数，也没有一个是偶数，只剩"都是奇数"。
    } else {
        printf("两个整数都是奇数\n");
    }

    // --------------------------------------------------------------------
    // 任务 2：三个整数的和与最大者
    // --------------------------------------------------------------------
    int c;
    printf("请输入第三个整数：");
    scanf("%d", &c);
    printf("三个整数的和为 %d\n", a + b + c);

    // 判断"谁最大"要考虑各种情况。先看 a 是否严格大于另外两个。
    if (a > b && a > c) {
        printf("第一个整数最大\n");

    // 再看 b 是否严格大于另外两个。
    } else if (b > a && b > c) {
        printf("第二个整数最大\n");

    // 再看 c。
    } else if (c > a && c > b) {
        printf("第三个整数最大\n");

    // 前三种都不成立，说明最大值不唯一（有并列）。== 判断相等（两个等号，一个等号是赋值）。
    // 这一条：a 和 b 一样大，并且都比 c 大。
    } else if (a == b && a > c) {
        printf("第一个和第二个整数一样大\n");

    // a 和 c 一样大，都比 b 大。
    } else if (a == c && a > b) {
        printf("第一个和第三个整数一样大\n");

    // b 和 c 一样大，都比 a 大。
    } else if (b == c && b > a) {
        printf("第二个和第三个整数一样大\n");

    // 三个数都相等。
    } else if (a == b && b == c) {
        printf("三个整数一样大\n");

    // 所有可能的情况其实前面都已经覆盖了（有唯一最大的 3 种，两个并列最大的 3 种，三个全相等 1 种），
    // 所以这个 else 实际上永远走不到，是写给"以防万一"用的。
    // 例：a=4，b=9，c=7：a > b？不是；b > a 并且 b > c？是，输出"第二个整数最大"。
    } else {
        printf("没有最大的整数\n");
    }

    // --------------------------------------------------------------------
    // 任务 3：计算 0 到 100 的和
    // --------------------------------------------------------------------
    // sum 存累加的和，必须先设成 0。
    int sum = 0;

    // i 是循环用的计数器，这里先赋了 1，但下面的 for 会把它重新赋成 0，所以这个初值没有用到。
    int i = 1;

    // for (初始化; 条件; 每轮结束后做的事)：i 从 0 数到 100。i 已经声明过了，所以这里不用再写 int。
    for (i = 0; i <= 100; i++) {
        // 把当前的 i 加进 sum。0 加上去不影响结果，所以结果就是 1 到 100 的和 5050。
        sum = sum + i;
    }
    printf("1到100的和为 %d\n", sum);

    // --------------------------------------------------------------------
    // 任务 4：数组的最大值、最小值、平均数
    // --------------------------------------------------------------------
    // 数组 = 一排连在一起的同类型格子。int arr[5] 是 5 个整数格子，下标 0 到 4。
    int arr[5];
    printf("请输入5个整数：\n");

    // 用循环读入 5 个数：i 是 0 到 4，对应 arr[0] 到 arr[4]。条件是 i < 5：下标最大是 4，写 <= 5 会越界。
    for (i = 0; i < 5; i++) {
        // &arr[i]：第 i 个元素的地址。
        scanf("%d", &arr[i]);
    }
    int max;

    // "打擂台"：先假设第一个元素最大。
    max = arr[0];

    // 这里从下标 0 开始比，和 arr[0] 自己比一次也没有问题（结果不变），只是多比了一次。
    for (i = 0; i < 5; i++) {
        // 比当前最大值大，就更新。
        if (arr[i] > max) {
            max = arr[i];
        }
    }
    printf("最大的整数是 %d\n", max);
    int min;

    // 最小值同理：先假设第一个元素最小，遇到更小的就更新。
    min = arr[0];
    for (i = 0; i < 5; i++) {
        if (arr[i] < min) {
            min = arr[i];
        }
    }
    printf("最小的整数是 %d\n", min);
    int sum2;

    // 再准备一个累加器 sum2 求总和，必须先设成 0（前面的 sum 已经装着 5050，不能复用）。
    sum2 = 0;
    for (i = 0; i < 5; i++) {
        sum2 = sum2 + arr[i];
    }
    float avg;

    // (float)sum2 叫"强制类型转换"：把整数 sum2 临时当 float 用。
    // 为什么？整数除以整数，小数部分会被丢掉（82 / 5 得 16，不是 16.4）；先转成小数再除，才能得到带小数的平均数。
    avg = (float)sum2 / 5;

    // %.2f 表示保留两位小数。例：80 / 5 是 16，显示 16.00。
    printf("平均数是 %.2f\n", avg);

    // return 0：结束 main，把 0 交给系统，表示"程序正常结束"。
    return 0;
}

