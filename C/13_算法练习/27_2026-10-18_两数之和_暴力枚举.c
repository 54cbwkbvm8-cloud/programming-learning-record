int main(void) {

    // 测试数组。方括号里不写大小，由大括号里的数据个数决定（4 个）。
    int nums[] = {2, 7, 11, 15};

    // 目标和。
    int target = 9;

    // 用来接收两个下标，初始都是 -1。
    int result[2] = {-1, -1};

    // 求元素个数：sizeof(nums) 是整个数组占的字节数（4 个 int × 4 字节 = 16），sizeof(nums[0]) 是一个元素的字节数（4），
    // 相除得 4。
    int n = sizeof(nums) / sizeof(nums[0]);

    // 调用函数：数组名作为参数，传过去的是地址。函数返回 1（真）就进入 if，返回 0（假）就进入 else。
    if (two_sum(nums, n, target, result)) {
        // 输出两个下标。例：2 + 7 = 9，所以输出 [0,1]。
        printf("[%d,%d]\n", result[0], result[1]);
    } else {
        // 没找到，输出提示。
        printf("Not found\n");
    }

    // return 0：结束 main，把 0 交给系统，表示"程序正常结束"。
    return 0;
}

