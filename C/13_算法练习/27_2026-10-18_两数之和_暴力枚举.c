#include <stdio.h>
// 定义函数 two_sum；参数接收调用方传入的数据，函数体完成操作，返回语句（如有）把结果交还调用者。
int two_sum(const int num[], int n, int target, int result[2]) {
    result[0] = -1;
    result[1] = -1;
// 循环按“初始化；条件判断；每轮更新”的顺序执行。先检查条件，再运行循环体，最后更新循环变量；注意边界是否会多执行或少执行一次。
    for (int i = 0; i < n; i++) {
// 循环按“初始化；条件判断；每轮更新”的顺序执行。先检查条件，再运行循环体，最后更新循环变量；注意边界是否会多执行或少执行一次。
        for (int j = i + 1; j < n; j++) {
// 判断条件 `(num[i] + num[j] == target)` 是否成立；条件为真时执行对应分支，否则跳过或转入其他分支。
            if (num[i] + num[j] == target) {
                result[0] = i;
                result[1] = j;
// 结束当前函数调用，并把表达式 `1` 的结果返回给调用者。
                return 1;
            }
        }
    }
// 结束当前函数调用，并把表达式 `0` 的结果返回给调用者。
    return 0;
}
// 定义函数 main；参数接收调用方传入的数据，函数体完成操作，返回语句（如有）把结果交还调用者。
int main(void) {
// 声明数组并为元素分配连续空间；下标从 0 开始，有效范围必须小于数组长度。
    int nums[] = {2, 7, 11, 15};
// 声明并初始化变量；`=` 是赋值运算符，用右侧表达式的值设置左侧变量，而不是比较两个值。
    int target = 9;
// 声明数组并为元素分配连续空间；下标从 0 开始，有效范围必须小于数组长度。
    int result[2] = {-1, -1};
// 调用 `sizeof()` 完成相应操作；括号中的表达式是传给函数的实参，具体效果由该函数定义决定。
    int n = sizeof(nums) / sizeof(nums[0]);
// 判断条件 `(two_sum(nums, n, target, result))` 是否成立；条件为真时执行对应分支，否则跳过或转入其他分支。
    if (two_sum(nums, n, target, result)) {
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
        printf("[%d,%d]\n", result[0], result[1]);
// 处理前面条件均不成立时的情况。
    } else {
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
        printf("Not found\n");
    }
// 结束当前函数调用，并把表达式 `0` 的结果返回给调用者。
    return 0;
}
