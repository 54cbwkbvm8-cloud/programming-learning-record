#include <stdio.h>


// --------------------------------------------------------------------
// 第二部分：两数之和（暴力枚举）
// --------------------------------------------------------------------
// 参数：num 是原数组（const 表示函数只读不改）；n 是元素个数（数组传进函数后，函数不知道长度，要另外传）；
// target 是目标和；result 用来"带出"两个下标（有 2 个元素的数组）。
// 返回值：找到返回 1，没找到返回 0（C 里习惯用 1 表示"是"，0 表示"否"）。
// 为什么用 result 数组？返回值只有一个，但答案是两个下标。数组传参传的是地址，函数里改 result，调用者的数组也跟着变。
int two_sum(const int num[], int n, int target, int result[2]) {

    // 先把结果设成 -1（表示"还没找到"）。-1 不是合法下标，所以可以表示"无效"。
    result[0] = -1;
    result[1] = -1;

    // 外层循环：i 依次取每一个元素，作为"第一个数"。
    for (int i = 0; i < n; i++) {
        // 内层循环：j 从 i + 1 开始，依次取 i 后面的每一个元素，作为"第二个数"。
        // 为什么 j 从 i + 1 开始？① 同一个元素不能用两次；② 避免重复：(i, j) 和 (j, i) 是同一组，只试一次就够了。
        // 例：数组 {2, 7, 11, 15}：i 是 0 时，j 依次是 1、2、3；i 是 1 时，j 依次是 2、3……所有两两组合恰好试一遍。
        for (int j = i + 1; j < n; j++) {
            // 这两个数的和等于目标值（== 判断相等）。例：2 + 7 == 9，成立。
            if (num[i] + num[j] == target) {
                // 找到了：把两个下标存进 result。
                result[0] = i;
                result[1] = j;

                // 立刻结束函数，返回 1。return 会结束整个函数，所以两层循环都不用再继续。
                return 1;
            }
        }
    }

    // 所有组合都试过了也没找到，返回 0。
    return 0;
}


