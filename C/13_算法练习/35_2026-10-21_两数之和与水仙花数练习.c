#include <stdio.h>


// --------------------------------------------------------------------
// 第二部分：判断水仙花数的函数
// --------------------------------------------------------------------
// 函数头的读法：int 是返回值类型；isNarcissistic 是函数名；int n 是参数（要判断的数）。
// 返回 1 表示"是水仙花数"，返回 0 表示"不是"（C 语言里，比较的结果就是 1 或 0）。
int isNarcissistic(int n) {

    // 整数除法会丢掉小数部分：153 / 100 得 1，就是百位数字。
    int hundreds = n / 100;

    // n / 10 去掉个位（153 变 15），再 % 10 取最后一位 5，就是十位数字。% 是取余。
    int tens = (n / 10) % 10;

    // n % 10 是除以 10 的余数，就是个位数字：153 % 10 得 3。
    int ones = n % 10;

    // == 判断相等。右边是三个数字的立方和（每个数自己乘三次再相加），例：153 得 1 + 125 + 27 = 153。
    // 比较的结果是 1（相等）或 0（不相等），直接 return 这个结果，不需要再写 if。
    return n == hundreds * hundreds * hundreds + tens * tens * tens + ones * ones * ones;
}


// --------------------------------------------------------------------
// 第三部分：main 函数 —— 程序从这里开始
