    int target = 10;

    // 求元素个数：整个数组的字节数 ÷ 一个元素的字节数。5 个 int × 4 字节 = 20，20 ÷ 4 = 5。
    int size = sizeof(nums) / sizeof(nums[0]);

    // found 是"标志变量"：0 表示还没找到，找到之后改成 1。
    int found = 0;

    // --------------------------------------------------------------------
