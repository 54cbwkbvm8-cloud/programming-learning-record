// --------------------------------------------------------------------
// 第一部分：引入"工具箱"
// --------------------------------------------------------------------
// <stdio.h> 是"标准输入输出"工具箱：printf（输出）和 scanf（输入）都在里面。
#include <stdio.h>


// --------------------------------------------------------------------
// 第二部分：全局变量（写在所有函数外面）
// --------------------------------------------------------------------
// 写在函数外面的变量叫"全局变量"，整个程序的函数都能使用。
// a、b 存输入的两个整数；max、min 存较大值和较小值。
// 全局变量不手动赋值时，系统会自动设成 0。（函数里面的局部变量不会，里面是随机值。）
int a;
int b;
int max;
int min;


// --------------------------------------------------------------------
// 第三部分：main 函数 —— 程序从这里开始
// --------------------------------------------------------------------
int main(void) {

    // --------------------------------------------------------------------
    // 任务 1：两个整数的较大值、较小值，奇偶判断
    // --------------------------------------------------------------------
    printf("请输入两个整数：");

    // 一次读两个整数，用空格或回车隔开。%d 读整数；& 是取地址符，scanf 要知道变量的地址才能把数放进去。
    scanf("%d %d", &a, &b);

    // 比较两个数：a 更大，max 就是 a，min 就是 b。
    if (a > b) {
        max = a;
        min = b;

    // 否则（b 更大，或者两数相等），max 取 b，min 取 a。两数相等时，max 和 min 一样，结果也是对的。
    } else {
        max = b;
        min = a;
    }

    // 两个 %d 依次对应后面的 max、min。
    printf("max = %d, min = %d\n", max, min);

    // % 是取余：除以 2 余 0 就是偶数，否则是奇数。例：8 % 2 是 0，3 % 2 是 1。
    // == 是"判断相等"（两个等号），一个等号 = 是赋值，不能混。
    if (a % 2 == 0) {
        printf("a 是偶数\n");
    } else {
        printf("a 是奇数\n");
    }

    // 对 b 做同样的判断。
    if (b % 2 == 0) {
        printf("b 是偶数\n");
    } else {
        printf("b 是奇数\n");
    }

    // --------------------------------------------------------------------
    // 任务 2：计算 1 到 n 的和
    // --------------------------------------------------------------------
    int sum;

    // sum 存累加的和，必须先设成 0。
    sum = 0;

    // n 是用户输入的上限。num 是能放 10 个整数的数组（下标 0 到 9），给任务 3 用。
    int n;
    int num[10];
    printf("请输入 n 的值: ");
    scanf("%d", &n);

    // for (初始化; 条件; 每轮结束后做的事)：i 从 1 数到 n。i 写在 for 里，所以只在这个 for 里有效。
    for (int i = 1; i <= n; i++) {
        // += 是"加上再赋值"：sum += i 等价于 sum = sum + i。例：n 是 10，结果 1 + 2 + ... + 10 = 55。
        sum += i;
    }
    printf("1~n 的和为: %d\n", sum);

    // --------------------------------------------------------------------
    // 任务 3：10 个整数的最大值、最小值、偶数和奇数的个数
    // --------------------------------------------------------------------
    printf("请输入 10 个整数: ");

    // 用循环读入 10 个数：i 是 0 到 9，正好对应数组 num 的 10 个下标。
    for (int i = 0; i < 10; i++) {
        // &num[i] 是第 i 个元素的地址（& 取地址符）。
        scanf("%d", &num[i]);
    }

    // "打擂台"：先假设第一个数既是最大值也是最小值，然后依次来挑战。
    int arr_max = num[0];
    int arr_min = num[0];

    // 这里从下标 0 开始比，和自己比一次也没问题（结果不变）。
    for (int i = 0; i < 10; i++) {
        // 比当前最大值大，就更新最大值。
        if (num[i] > arr_max) {
            arr_max = num[i];
        }

        // 比当前最小值小，就更新最小值。这里是另一个独立的 if（不是 else if）：每个数两个条件都要各检查一次。
        if (num[i] < arr_min) {
            arr_min = num[i];
        }
    }
    printf("max = %d, min = %d\n", arr_max, arr_min);

    // count 是"计数器"，统计偶数个数，必须从 0 开始。
    int count = 0;
    for (int i = 0; i < 10; i++) {
        // 余数是 0 就是偶数。
        if (num[i] % 2 == 0) {
            // count++ 等价于 count = count + 1。
            count++;
        }
    }
    printf("数组的偶数有%d个\n", count);

    // 奇数的个数不用再数一遍：10 个数里，不是偶数的就是奇数，所以 10 - count。
    printf("数组的奇数有%d个\n", 10 - count);

    // return 0：结束 main，把 0 交给系统，表示"程序正常结束"。
    return 0;
}

