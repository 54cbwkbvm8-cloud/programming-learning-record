#include <stdio.h>

int binary_search(const int arr[], int n, int target, int show) {

    int left = 0;
    int right = n - 1;

    int step = 0;

    while (left <= right) {
        step = step + 1;

        int mid = left + (right - left) / 2;

        if (show) {
            printf("第%d轮：left = %d  right = %d  mid = %d  arr[mid] = %d\n", step, left, right,
                   mid, arr[mid]);
        }

        if (arr[mid] == target) {

            if (show) {
                printf("        arr[%d] = %d，等于目标 %d -> 找到了！\n", mid, arr[mid], target);
            }
            return mid;
        } else if (arr[mid] < target) {

            if (show) {
                printf("        %d < %d -> 目标在右边，丢掉左半边，left 改为 mid + 1 = %d\n",
                       arr[mid], target, mid + 1);
            }
            left = mid + 1;
        } else {

            if (show) {
                printf("        %d > %d -> 目标在左边，丢掉右半边，right 改为 mid - 1 = %d\n",
                       arr[mid], target, mid - 1);
            }
            right = mid - 1;
        }
    }

    if (show) {
        printf("区间已空：left = %d > right = %d -> 没有找到，返回 -1\n", left, right);
    }
    return -1;
}

int run_test(const char name[], const int arr[], int n, int target, int expected) {

    int result = binary_search(arr, n, target, 0);

    if (result == expected) {

        printf("【通过✅】%s：查找 %d，期望 %d，实际 %d\n", name, target, expected, result);
        return 1;
    } else {
        printf("【失败❌】%s：查找 %d，期望 %d，实际 %d\n", name, target, expected, result);
        return 0;
    }
}

int main(void) {

    int arr[8] = {2, 5, 8, 12, 16, 23, 38, 56};

    int n = sizeof(arr) / sizeof(arr[0]);

    int one[1] = {7};
    int two[2] = {3, 9};
    int empty[1] = {0};
    int messy[5] = {5, 2, 8, 1, 9};
    int messy_n = sizeof(messy) / sizeof(messy[0]);

    int result;
    int passed = 0;

    int total = 13;

    printf("========== 第一部分：追踪 left / right / mid ==========\n");

    printf("下标：");
    for (int i = 0; i < n; i++) {
        printf("%4d", i);
    }
    printf("\n数组：");
    for (int i = 0; i < n; i++) {
        printf("%4d", arr[i]);
    }
    printf("\n\n");

    printf("【查找 16】\n");
    result = binary_search(arr, n, 16, 1);
    printf("结果：返回 %d\n\n", result);

    printf("【查找 2】\n");
    result = binary_search(arr, n, 2, 1);
    printf("结果：返回 %d\n\n", result);

    printf("【查找 20】\n");
    result = binary_search(arr, n, 20, 1);
    printf("结果：返回 %d\n\n", result);

    printf("========== 第二部分：自动测试 ==========\n");

    passed += run_test("目标在中间（16）", arr, n, 16, 4);
    passed += run_test("目标是第一个元素（2）", arr, n, 2, 0);
    passed += run_test("目标是最后一个元素（56）", arr, n, 56, 7);

    passed += run_test("目标不存在（20）", arr, n, 20, -1);
    passed += run_test("目标比所有元素都小（1）", arr, n, 1, -1);
    passed += run_test("目标比所有元素都大（100）", arr, n, 100, -1);

    passed += run_test("单元素-找到（7）", one, 1, 7, 0);
    passed += run_test("单元素-目标更小（3）", one, 1, 3, -1);
    passed += run_test("单元素-目标更大（9）", one, 1, 9, -1);

    passed += run_test("两个元素-找左边（3）", two, 2, 3, 0);
    passed += run_test("两个元素-找右边（9）", two, 2, 9, 1);
    passed += run_test("两个元素-目标在中间落空（5）", two, 2, 5, -1);

    passed += run_test("空数组（n = 0）", empty, 0, 5, -1);

    printf("\n测试结果：通过✅ %d / %d\n", passed, total);

    if (passed == total) {
        printf("恭喜你，全部通过！✅\n");
    } else {

        printf("还有 %d 个测试未通过❌，请检查代码，加油继续努力！\n", total - passed);
    }

    printf("\n========== 第三部分：为什么必须有序 ==========\n");
    printf("无序数组 {5, 2, 8, 1, 9}，查找 2（它明明在下标 1）：\n");

    result = binary_search(messy, messy_n, 2, 1);
    printf("二分查找结果：返回 %d（应该是 1，却是 -1，说明数组无序时二分查找会出错）\n", result);
    printf("\n");

    printf("========== 测试结束 ==========\n");

    return 0;
}

