// --------------------------------------------------------------------
// 第一部分：引入"工具箱"和宏定义
// --------------------------------------------------------------------
// <stdio.h> 是"标准输入输出"工具箱：printf（输出）和 scanf（输入）都在里面。
#include <stdio.h>

// #define 叫"宏定义"：编译之前，程序里所有的 N 都会被替换成 1000（行末不写分号）。
// 这里 N 表示"最多允许输入多少个数"，也用来定义数组的大小，以后要改上限只改这一处。
#define N 1000


// --------------------------------------------------------------------
// 第二部分：全局变量
// --------------------------------------------------------------------
// num 是全局变量（写在函数外面，所有函数都能用），用来存"用户要输入几个数"。
int num;


// --------------------------------------------------------------------
// 第三部分：main 函数 —— 程序从这里开始
// --------------------------------------------------------------------
int main(void) {

    // sum 存总和，用 long long（范围更大的整数类型），这样即使数字很大、个数很多，总和也不容易溢出。必须先设成 0。
    long long sum = 0;

    // count 是"计数器"：统计偶数的个数，从 0 开始。
    int count = 0;

    // --------------------------------------------------------------------
    // 输入并检查"个数"
    // --------------------------------------------------------------------
    printf("请输入数字个数：");

    // scanf 读一个整数放进 num：%d 读整数，&num 是 num 的地址（& 取地址符）。
    // scanf 返回成功读到的个数，成功应该是 1；!= 1 表示没读成功（比如输入了字母）。
    if (scanf("%d", &num) != 1) {
        printf("输入错误！\n");

        // return 1：提前结束 main，把 1 交给系统，表示"出错了"（0 表示正常）。
        return 1;
    }

    // 检查个数是否合法：|| 读作"或者"，小于 1 或者大于 N（1000）都不合法。
    // 为什么要限制上限？下面的数组只有 N 个格子，个数超过 N 就会写到数组外面（越界）。
    if (num < 1 || num > N) {
        // %d 对应后面的 N（1000）。
        printf("数字个数必须在1到%d之间！\n", N);
        return 1;
    }

    // 数组：一排 N（1000）个整数格子，下标 0 到 999。用来存输入的数。
    int a[N];
    printf("请输入%d个数字：", num);

    // for (初始化; 条件; 每轮结束后做的事)：i 从 0 数到 num - 1，读入 num 个数。条件写 i < num：下标最大是 num - 1。
    for (int i = 0; i < num; i++) {
        // 读一个整数放进第 i 个元素（&a[i] 是它的地址），同时检查是否读成功，没读成功就提示并结束程序。
        if (scanf("%d", &a[i]) != 1) {
            printf("输入错误！\n");
            return 1;
        }
    }

    // --------------------------------------------------------------------
    // 统计：和、最大值、最小值、偶数个数
    // --------------------------------------------------------------------
    // "打擂台"：先假设第一个数既是最大值，也是最小值。
    int max = a[0];
    int min = a[0];

    // 走遍所有输入的数，一次循环里同时完成四件事。
    for (int i = 0; i < num; i++) {
        // 累加：把当前的数加进总和。
        sum = sum + a[i];

        // 比当前最小值小，就更新最小值。
        if (a[i] < min) {
            min = a[i];
        }

        // 比当前最大值大，就更新最大值。
        // 这两个是各自独立的 if（不是 else if），每个数都要分别和最小值、最大值比一次。
        if (a[i] > max) {
            max = a[i];
        }

        // % 是取余：除以 2 余 0 就是偶数，计数器加 1。
        if (a[i] % 2 == 0) {
            // count++ 等价于 count = count + 1。
            count++;
        }
    }

    // --------------------------------------------------------------------
    // 输出 1 到 100 中 3 的倍数
    // --------------------------------------------------------------------
    // m 是循环计数器。
    int m;
    printf("三的倍数有：");

    // 把 1 到 100 每个数都走一遍。
    for (m = 1; m <= 100; m++) {
        // m 除以 3 余 0，就是 3 的倍数。例：9 % 3 是 0，10 % 3 是 1。
        if (m % 3 == 0) {
            // 输出这个数，后面带一个空格，数字之间就不会粘在一起。
            printf("%d ", m);
        }
    }

    // 输出完后换行。
    printf("\n");

    // --------------------------------------------------------------------
    // 输出统计结果
    // --------------------------------------------------------------------
    // %lld 是 long long 类型的占位符（sum 是 long long，必须用 %lld，用 %d 会出错）。
    // 前面的 %d 对应 num（个数），后面的值依次是统计结果。
    printf("这%d个数字的和为：%lld\n", num, sum);
    printf("这%d个数字中偶数的个数为：%d\n", num, count);
    printf("这%d个数字中最大的数为：%d\n", num, max);
    printf("这%d个数字中最小的数为：%d\n", num, min);

    // return 0：结束 main，把 0 交给系统，表示"程序正常结束"。
    return 0;
}

