// --------------------------------------------------------------------
// 第一部分：引入"工具箱"
// --------------------------------------------------------------------
// <stdio.h> 是"标准输入输出"工具箱：printf（输出）和 scanf（输入）都在里面。
#include <stdio.h>


// --------------------------------------------------------------------
// 第二部分：main 函数 —— 程序从这里开始
// --------------------------------------------------------------------
int main(void) {

    // --------------------------------------------------------------------
    // 任务 1：1 到 100 的和
    // --------------------------------------------------------------------
    // i2 做循环计数器；sum 存累加结果，必须先设成 0。
    int i2;
    int sum = 0;

    // for (初始化; 条件; 每轮结束后做的事)：i2 从 1 数到 100，共 100 轮。i2++ 是"加 1"。
    for (i2 = 1; i2 <= 100; i2++) {
        // 把当前的数加进 sum。结果是 1 + 2 + ... + 100 = 5050。
        sum = sum + i2;
    }
    printf("1到 100的和是 %d\n", sum);

    // --------------------------------------------------------------------
    // 任务 2：1 到 100 中 3 的倍数的个数
    // --------------------------------------------------------------------
    // i 是另一个计数器；count 是"计数器"，每遇到一个 3 的倍数就加 1，所以从 0 开始。
    int i;
    int count = 0;

    // 把 1 到 100 每个数都走一遍。
    for (i = 1; i <= 100; i++) {
        // % 是取余：i 除以 3 余 0，就说明 i 是 3 的倍数。例：9 % 3 是 0，10 % 3 是 1。
        if (i % 3 == 0) {
            // count++ 等价于 count = count + 1。1 到 100 里共有 33 个 3 的倍数。
            count++;
        }
    }

    printf("1～100 中 3 的倍数有 %d 个\n", count);

    // --------------------------------------------------------------------
    // 任务 3：输入 10 个整数，求最大值和最小值
    // --------------------------------------------------------------------
    // max 存最大值，min 存最小值，arr 是能放 10 个整数的数组（下标 0 到 9）。
    int max;
    int min;
    int arr[10];
    printf("=========请输入 10 个整数：=========\n");
    printf("用回车键隔开 或者 空格键隔开\n");

    // 这里在 for 里面又写了 int i：这是一个新的 i，只在这个 for 里有效，和外面的 i 互不影响（同名时里面的优先）。
    for (int i = 0; i < 10; i++) {
        // 把 10 个数读进数组。&arr[i] 是第 i 个元素的地址（& 取地址符）。
        scanf("%d", &arr[i]);
    }

    // "打擂台"：先假设第一个数最大，其余的依次来挑战。
    max = arr[0];

    // 从下标 1 开始比。
    for (int i = 1; i < 10; i++) {
        // 比当前最大值大就更新。
        if (arr[i] > max) {
            max = arr[i];
        }
    }

    // %d 是整数占位符。
    printf("max = %d\n", max);

    // 找最小值。
    for (int i = 0; i < 10; i++) {
        // ⚠ 这里有个缺陷：min 在第 19 行声明后，一直没有赋初值（正确的做法是在循环前写 min = arr[0];）。
        // 没有初值的变量里是随机的旧数据，拿它来比较，结果不可靠：
        // 如果这个随机值恰好很小，最小值就会一直是这个随机值，而不是真正的最小数。
        // 有的编译器（比如 clang）会给出"min 未初始化"的警告。这是原代码的缺陷，这里不改，只提醒你。
        if (arr[i] < min) {
            min = arr[i];
        }
    }
    printf("min = %d\n", min);

    // --------------------------------------------------------------------
    // 任务 4：九九乘法表
    // --------------------------------------------------------------------
    printf("========九九乘法表========\n");

    // j 是内层循环的计数器。
    int j;

    // 外层循环：i 控制行，1 到 9 共 9 行。
    for (i = 1; i <= 9; i++) {
        // 内层循环：j 控制这一行里的第几个式子，j 从 1 数到 i，所以第 i 行有 i 个式子，整体是三角形。
        // 嵌套循环的规律：外层每走一轮，内层从头到尾完整跑一遍。
        for (j = 1; j <= i; j++) {
            // 三个 %d 依次对应 i、j、i * j（* 是乘号）。\t 是"制表符"，相当于按一下 Tab 键，让每列对齐。
            printf("%d*%d=%d\t", i, j, i * j);
        }

        // 内层循环一行输完后换行。注意它写在内层循环外面、外层循环里面，所以每一行只换一次行。
        printf("\n");
    }

    // --------------------------------------------------------------------
    // 任务 5：星号三角形
    // --------------------------------------------------------------------
    printf("=======打印三角形========\n");

    // 外层循环控制行数：9 行。
    for (i = 1; i <= 9; i++) {
        // 内层循环控制每行星号的个数：第 i 行输出 i 个 *。
        for (j = 1; j <= i; j++) {
            // 每次输出一个星号，不换行，这样同一行的星号会连在一起。
            printf("*");
        }

        // 一行输完，换行。
        printf("\n");
    }

    // return 0：结束 main，把 0 交给系统，表示"程序正常结束"。
    return 0;
}

