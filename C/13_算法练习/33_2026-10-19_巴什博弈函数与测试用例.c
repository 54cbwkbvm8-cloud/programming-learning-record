// --------------------------------------------------------------------
// <stdbool.h> 提供 bool 类型（只有两个值：true 表示"真 / 是"，false 表示"假 / 否"）。
// bool 让"判断结果"的意思比用 1 和 0 更清楚。
#include <stdbool.h>

// <stdio.h> 是"标准输入输出"工具箱，printf 在里面。
#include <stdio.h>


// --------------------------------------------------------------------
// 第二部分：判断先手能不能必胜
// --------------------------------------------------------------------
// 函数头的读法：bool 是返回值类型（返回真或假）；canWin 是函数名；n 是石子总数，m 是每次最多取几颗。
bool canWin(int n, int m) {

    // 先检查参数：石子数和最多取的数都必须是正数。|| 读作"或者"，只要有一个不是正数就无效。
    if (n <= 0 || m <= 0) {
        // 无效的情况返回 false。return 会结束函数，并把结果交给调用者。
        return false;
    }

    // 核心判断：% 是取余，n % (m + 1) 是"n 除以 (m + 1) 的余数"。余数不是 0（!= 0），先手就必胜。
    // 这个比较的结果本身就是真或假，所以直接 return 它，不用再写 if。
    // 例：n 是 10，m 是 3：10 % 4 = 2，不等于 0，返回 true；n 是 8，m 是 3：8 % 4 = 0，返回 false。
    return n % (m + 1) != 0;
}


// --------------------------------------------------------------------
// 第三部分：测试函数
// --------------------------------------------------------------------
// 作用：对一组 (n, m) 调用 canWin，把结果和建议的第一步输出出来。
// void 表示不返回值；testNo 是测试编号，只用于输出。
void testCase(int n, int m, int testNo) {

    // 调用函数，把返回的真或假存进 bool 变量 result。
    bool result = canWin(n, m);

    // 先输出这一组测试的参数，结尾没有换行，后面的内容会接着输出在同一行。
    printf("Test %d: n=%d, m=%d, ", testNo, n, m);

    // 参数无效时，输出提示、分隔线，然后用 return; 提前结束这个函数。
    // return; 用在 void 函数里，表示"提前结束函数"（void 没有返回值，所以 return 后面什么都不写）。
    if (n <= 0 || m <= 0) {
        printf("参数无效\n");
        printf("------------------------------------------\n");
        return;
    }

    // 余数 remainder 就是先手第一步该取的颗数（余数为 0 时没有必胜的第一步）。
    int remainder = n % (m + 1);

    // result ? "true" : "false" 叫"三目运算符"：条件 ? 值1 : 值2，条件成立取值1，否则取值2。
    // 这里：result 是真就取字符串 "true"，否则取 "false"。
    // 为什么要这样写？printf 没有专门输出 bool 的占位符，所以把真假转成字符串，用 %s 输出。
    printf("remainder=%d, result=%s\n", remainder, result ? "true" : "false");

    // result 是真，先手必胜，给出建议。
    if (result) {
        // %d 对应 remainder：先手第一步取 remainder 颗，让剩下的石子变成 (m + 1) 的倍数。
        printf("建议先手第一步取 %d 个石头\n", remainder);

    // result 是假：余数为 0，先手没有必胜策略。
    } else {
        printf("先手没有必胜策略，不存在能保证必胜的第一步\n");
    }

    printf("------------------------------------------\n");
}


