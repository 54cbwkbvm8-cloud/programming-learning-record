// 定义函数 canWin；参数接收调用方传入的数据，函数体完成操作，返回语句（如有）把结果交还调用者。
bool canWin(int n, int m) {
// 判断条件 `(n <= 0 || m <= 0)` 是否成立；条件为真时执行对应分支，否则跳过或转入其他分支。
    if (n <= 0 || m <= 0) {
// 结束当前函数调用，并把表达式 `false` 的结果返回给调用者。
        return false;
    }
// 结束当前函数调用，并把表达式 `n % (m + 1) != 0` 的结果返回给调用者。
    return n % (m + 1) != 0;
}

// 定义函数 testCase；参数接收调用方传入的数据，函数体完成操作，返回语句（如有）把结果交还调用者。
