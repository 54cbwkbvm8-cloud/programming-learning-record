// --------------------------------------------------------------------
// 第一部分：引入"工具箱"
// --------------------------------------------------------------------
// <stdio.h> 是"标准输入输出"工具箱：printf（输出）和 scanf（输入）都在里面。
#include <stdio.h>


// --------------------------------------------------------------------
// 第二部分：main 函数 —— 程序从这里开始
// --------------------------------------------------------------------
int main(void) {

    // max 存最大值；number 用来接收每次输入的数。它们刚声明时没有赋值，里面是随机的旧数据，使用前必须先赋值。
    int max;
    int number;

    // --------------------------------------------------------------------
    // 练习 1：边输入边求最大值（不用数组）
    // --------------------------------------------------------------------
    printf("========== 输入十个数字（用空格隔开）求最大值 ==========\n");

    // scanf 从键盘读一个整数放进 max：%d 读整数，&max 是 max 的地址（& 取地址符，scanf 需要知道放在哪）。
    // "打擂台"：先把第一个输入的数直接当作最大值。输入时数字之间用空格或回车隔开都可以。
    scanf("%d", &max);

    // for (初始化; 条件; 每轮结束后做的事)：i 从 1 数到 9，共 9 轮，读剩下的 9 个数（第 1 个已经读进 max 了）。
    // int i 写在 for 里面，所以 i 只在这个 for 里有效。
    for (int i = 1; i < 10; i++) {
        // 每轮读一个数放进 number，下一轮读入的新数会覆盖它（这里不需要保存每个数，只需要当时比一下）。
        scanf("%d", &number);

        // 如果新读到的数比当前最大值还大，就更新最大值。
        // 例：输入 3 8 1 9 ...：max 先是 3；8 > 3，变 8；1 不大；9 > 8，变 9……最后 max 是 10。
        if (number > max) {
            max = number;
        }
    }

    // %d 是整数占位符，会被 max 的值替换。
    printf("最大值为：%d\n", max);

    // --------------------------------------------------------------------
    // 练习 2：边输入边求和
    // --------------------------------------------------------------------
    printf("========== 输入十个数字（用空格隔开）求和 ==========\n");

    // sum 存累加的和，必须先设成 0，累加才从 0 开始。
    int sum = 0;

    // i 从 0 数到 9，共 10 轮，读 10 个数。
    for (int i = 0; i < 10; i++) {
        scanf("%d", &number);

        // += 是"加上再赋值"：sum += number 等价于 sum = sum + number。
        sum += number;
    }

    // 例：1 到 10 的和是 55。
    printf("和为：%d\n", sum);

    // 这条 printf 的字符串被拆成了三段写，C 会自动把相邻的字符串拼成一整句，输出的是一行长标题。
    // ## 练习 3：统计奇数的个数（计数器）
    printf("========== "
           "输入十个数字判断是不是偶数，不是偶数就加一，最后输出奇数的个数（用空格隔开）计数器====="
           "======\n");

    // count 是"计数器"：每遇到一个奇数就加 1，所以必须从 0 开始。
    int count = 0;

    // 读 10 个数，逐个判断。
    for (int i = 0; i < 10; i++) {
        scanf("%d", &number);

        // % 是取余：除以 2 的余数。余数不是 0（!= 0 表示"不等于 0"）的就是奇数。
        if (number % 2 != 0) {
            // count++ 等价于 count = count + 1。只有奇数才会执行到这里。
            // 例：1 到 10 里有 1、3、5、7、9 共 5 个奇数。
            count++;
        }
    }
    printf("奇数个数为：%d\n", count);

    // --------------------------------------------------------------------
    // 练习 4：数组版求最大值
    // --------------------------------------------------------------------
    printf("========== 输入十个数字（用空格隔开）求最大值(数组版)==========\n");

    // 数组 = 一排连在一起的同类型格子。int a[10] 是 10 个整数格子，下标 0 到 9（没有 a[10]）。
    // 和前面不同：这次先把 10 个数都存下来，再统计。好处是以后还能反复使用这些数据。
    int a[10];

    // 用循环把 10 个数读进数组：i 依次是 0 到 9，对应 a[0] 到 a[9]。
    for (int i = 0; i < 10; i++) {
        // &a[i] 是数组第 i 个元素的地址。a[i] 是一个普通的 int 格子，所以前面要加 &。
        scanf("%d", &a[i]);
    }

    // 先假设第一个元素最大，放进 max2。
    int max2 = a[0];

    // 从第 2 个元素（下标 1）开始比较。
    for (int i = 1; i < 10; i++) {
        // 比 max2 大就更新。例：12 5 30 8 25 17 ...：max2 先是 12；30 > 12，变 30；后面没有比 30 更大的，最大值是 30。
        if (a[i] > max2) {
            max2 = a[i];
        }
    }
    printf("最大值为：%d\n", max2);

    // return 0：结束 main，把 0 交给系统，表示"程序正常结束"。
    return 0;
}

