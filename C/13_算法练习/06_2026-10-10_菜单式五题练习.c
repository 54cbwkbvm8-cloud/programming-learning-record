// --------------------------------------------------------------------
// 第一部分：引入"工具箱"
// --------------------------------------------------------------------
// <stdio.h> 是"标准输入输出"工具箱：printf（输出）和 scanf（输入）都在里面。
#include <stdio.h>


// --------------------------------------------------------------------
// 第二部分：第 1 题 —— 求 a + b
// --------------------------------------------------------------------
// 函数 = 一段有名字、可以反复调用的"小程序"。void 表示不返回值，(void) 表示不需要参数。
// 把每道题写成独立的函数，main 里只负责"选题"，结构清楚，也方便单独测试。
void p1_abc(void) {

    // a、b 存输入的两个整数，声明时就赋初值 0。
    int a = 0;
    int b = 0;

    // 一条 scanf 读两个整数：%d%d 依次对应 &a、&b，输入时用空格或回车隔开。
    // & 是取地址符：scanf 要知道变量放在哪，才能把读到的数写进去。
    scanf("%d%d", &a, &b);

    // %d 后面可以直接放算式：先算出 a + b，再输出。\n 是换行。
    printf("%d\n", a + b);
}


// --------------------------------------------------------------------
// 第三部分：第 2 题 —— 求 1 + 2 + ... + n
// --------------------------------------------------------------------
void p2_sequence_sum(void) {

    // long long 是范围更大的整数类型（能存很大的数）。n 可能很大，n * (n + 1) 更大，用 int 会溢出（超出范围出错）。
    long long n = 0;

    // 读 long long 要用 %lld（两个 l）。
    scanf("%lld", &n);

    // sum 存结果，也用 long long。
    long long sum = 0;

    // 用公式直接算，不用循环：1 + 2 + ... + n = n × (n + 1) ÷ 2。例：n 是 10，10 × 11 ÷ 2 = 55。
    // 为什么先乘后除？n × (n + 1) 一定是偶数（两个相邻整数里必有一个偶数），所以除以 2 正好整除，不会丢掉小数。
    sum = n * (n + 1) / 2;

    // 输出 long long 也要用 %lld。
    printf("%lld\n", sum);
}


// --------------------------------------------------------------------
// 第四部分：第 3 题 —— 闰年判断
// --------------------------------------------------------------------
void p3_leap_year(void) {
    int year = 0;
    scanf("%d", &year);

    // 闰年规则：能被 4 整除但不能被 100 整除，或者能被 400 整除。
    // % 是取余：余 0 就是能整除。&& 是"并且"，|| 是"或者"，!= 是"不等于"，括号让里面先算。
    // 例：2024 是闰年；1900 不是（能被 100 整除，不能被 400 整除）；2000 是（能被 400 整除）。
    if ((year % 4 == 0 && year % 100 != 0) || year % 400 == 0) {
        printf("yes\n");
    } else {
        printf("no\n");
    }
}


// --------------------------------------------------------------------
// 第五部分：第 4 题 —— 水仙花数
// --------------------------------------------------------------------
// 水仙花数：一个三位数，它每一位数字的立方和等于它本身。例：153 = 1³ + 5³ + 3³ = 1 + 125 + 27。
// 这个函数判断 x 是不是水仙花数：是返回 1，不是返回 0（C 里习惯用 1 表示"是"，0 表示"否"）。
int is_narcissistic(int x) {

    // 整数除法会丢掉小数部分：153 / 100 得 1，这就是百位数字。
    int hundreds = x / 100;

    // x / 10 先得到去掉个位的数（153 变 15），再 % 10 取出最后一位 5，就是十位数字。
    // / 和 % 优先级相同，从左往右算：(x / 10) % 10。
    int tens = x / 10 % 10;

    // x % 10 是 x 除以 10 的余数，就是个位数字：153 % 10 得 3。
    int units = x % 10;

    // 三个数字各自的立方（自己乘三次）相加。例：153 得 1 + 125 + 27 = 153。
    int cube_sum = hundreds * hundreds * hundreds + tens * tens * tens + units * units * units;

    // 立方和等于它本身，就是水仙花数，返回 1；否则返回 0。
    if (cube_sum == x) {
        return 1;
    } else {
        return 0;
    }
}

// 把所有三位数（100 到 999）逐个检查，输出水仙花数。
void p4_narcissistic(void) {

    // for (初始化; 条件; 每轮结束后做的事)：i 从 100 数到 999，每个三位数都检查一遍。
    for (int i = 100; i <= 999; i++) {
        // 调用函数：函数返回 1（真）就进入 if，返回 0（假）就跳过。C 里非 0 就是"真"。
        if (is_narcissistic(i)) {
            printf("%d\n", i);
        }
    }

    // 所有水仙花数输出完后，再输出一个空行。
    printf("\n");
}


// --------------------------------------------------------------------
// 第六部分：第 5 题 —— 排序
// --------------------------------------------------------------------
void p5_sort(void) {

    // n 是要排序的个数。
    int n = 0;
    scanf("%d", &n);

    // 数组：一排 205 个整数格子，下标 0 到 204。
    // ⚠ 提醒：n 不能超过 205，否则读入数据时会写到数组外面（越界）。这里没有检查 n 的大小。
    int a[205];

    // 用循环把 n 个数读进数组。
    for (int i = 0; i < n; i++) {
        // &a[i] 是数组第 i 个元素的地址。
        scanf("%d", &a[i]);
    }

    // 排序（交换法）：第 i 个位置，依次和它后面的每一个数比较，如果前面的比后面的大，就交换。
    // 这样一轮下来，a[i] 里就放着"从 i 往后的所有数里最小的那个"。i 从小到大做完，整个数组就从小到大排好了。
    // 例：2 9 1 7 4：i 是 0 时，2 和 9 不换；2 和 1 比，2 > 1 交换，得 1 9 2 7 4；后面的都比 1 大，不再交换……
    for (int i = 0; i < n; i++) {
        // 内层循环：j 从 i + 1 开始，依次和 a[i] 比较。
        for (int j = i + 1; j < n; j++) {
            // 前面的比后面的大，说明顺序反了，需要交换。
            if (a[i] > a[j]) {
                // 交换两个变量的值，必须借助第三个变量 temp：就像互换两杯水，要有第三个空杯子。
                // 先把 a[i] 存进 temp，再让 a[i] 变成 a[j]，最后让 a[j] 变成 temp。
                int temp = a[i];
                a[i] = a[j];
                a[j] = temp;
            }
        }
    }

    // 排好之后，把数组从头到尾输出。
    for (int i = 0; i < n; i++) {
        // 只有不是第一个数时，才先输出一个空格。这样数字之间有空格，但最后一个数后面没有多余的空格。
        if (i > 0) {
            printf(" ");
        }
        printf("%d", a[i]);
    }

    // 输出完后换行。
    printf("\n");
}


