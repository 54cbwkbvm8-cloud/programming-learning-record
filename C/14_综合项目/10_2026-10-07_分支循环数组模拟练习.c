// --------------------------------------------------------------------
// 第四部分：函数定义 —— 最大值
// --------------------------------------------------------------------
// 函数定义：函数头加大括号里的函数体，是函数真正的代码。
// 思路是"打擂台"：先假设第一个元素最大，再让后面的依次来挑战。
int max(int a[], int n) {

    // 先假设第一个元素 a[0] 最大（下标从 0 开始）。
    int max_value = a[0];

    // 从第 2 个元素（下标 1）开始比较。条件是 i < n：n 个元素的下标最大是 n - 1，写 <= 会越界。
    for (int i = 1; i < n; i++) {
        // 比当前最大值大，就更新。
        if (a[i] > max_value) {
            max_value = a[i];
        }
    }

    // return 把结果交给调用者：循环结束时，max_value 就是最大值。
    return max_value;
}


// --------------------------------------------------------------------
// 第五部分：函数定义 —— 最小值
// --------------------------------------------------------------------
// 和求最大值对称：先假设第一个最小，遇到更小的就更新。
int min(int a[], int n) {
    int min_value = a[0];
    for (int i = 1; i < n; i++) {
        if (a[i] < min_value) {
            min_value = a[i];
        }
    }
    return min_value;
}


// --------------------------------------------------------------------
// 第六部分：函数定义 —— 求总和
// --------------------------------------------------------------------
int sum(int a[], int n) {

    // 累加器，必须先设成 0。它和函数名 sum 相同：在这个函数里，sum 指的是这个局部变量（局部的优先），所以不冲突，
    // 但容易让人看混。
    int sum = 0;
    for (int i = 0; i < n; i++) {
        // += 是"加上再赋值"：sum += a[i] 等价于 sum = sum + a[i]。
        sum += a[i];
    }
    return sum;
}


// --------------------------------------------------------------------
// 第七部分：函数定义 —— 求平均数
// --------------------------------------------------------------------
// 函数体只有一句，写在一行里：先调用 sum 求总和，再除以个数。
// (float)sum(a, n) 是强制类型转换：把整数总和临时当作 float。
// 为什么要转？整数除以整数，小数部分会被丢掉（82 / 5 得 16，不是 16.4）；先转成小数再除，才有小数部分。
// 这个函数里没有叫 sum 的局部变量，所以这里的 sum 指的是上面那个求总和的函数。
float average(int a[], int n) { return (float)sum(a, n) / n; }

