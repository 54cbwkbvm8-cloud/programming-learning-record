#include <stdio.h>
int main(void) {
    int choice;
    float a;
    float b;
    while (1) {
        printf("============简易计算器============\n");
        printf("1.加法\n");
        printf("2.减法\n");
        printf("3.乘法\n");
        printf("4.除法\n");
        printf("5.退出\n");
        printf("=================================\n");
        printf("请选择：");
        scanf("%d", &choice);
        if (choice == 5) {
            break;
        }
        if (choice == 1) {
            printf("请输入第一个数字：");
            scanf("%f", &a);
            printf("请输入第二个数字：");
            scanf("%f", &b);
            printf("%.2f + %.2f = %.2f\n", a, b, a + b);
        } else if (choice == 2) {
            printf("请输入第一个数字：");
            scanf("%f", &a);
            printf("请输入第二个数字：");
            scanf("%f", &b);
            printf("%.2f - %.2f = %.2f\n", a, b, a - b);
        } else if (choice == 3) {
            printf("请输入第一个数字：");
            scanf("%f", &a);
            printf("请输入第二个数字：");
            scanf("%f", &b);
            printf("%.2f * %.2f = %.2f\n", a, b, a * b);
        } else if (choice == 4) {
            printf("请输入第一个数字：");
            scanf("%f", &a);
            printf("请输入第二个数字：");
            scanf("%f", &b);
            if (b == 0) {
                printf("除数不能为 0\n");
            } else {
                printf("%.2f / %.2f = %.2f\n", a, b, a / b);
            }
        } else {
            printf("输入错误，请重新输入！\n");
        }
    }
    return 0;
}
