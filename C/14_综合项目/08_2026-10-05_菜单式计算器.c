// --------------------------------------------------------------------
// 第一部分：引入"工具箱"
// --------------------------------------------------------------------
// <stdio.h> 是"标准输入输出"工具箱：printf（输出）和 scanf（输入）都在里面。
#include <stdio.h>


// --------------------------------------------------------------------
// 第二部分：main 函数 —— 程序从这里开始
// --------------------------------------------------------------------
int main(void) {

    // choice 存菜单选项（整数）；a、b 存参与计算的两个数，用 float 是为了支持小数。
    int choice;
    float a;
    float b;

    // while (1) 是"无限循环"：条件 1 永远为真，所以会一直重复显示菜单。
    // 退出这个循环只有一个出口：选了 5 之后执行的 break。
    // 为什么这样写？菜单程序要一直运行到用户主动选择"退出"，次数不确定，适合用"无限循环 + break"。
    while (1) {
        // 每一轮都先把菜单显示出来。\n 表示换行。
        printf("============简易计算器============\n");
        printf("1.加法\n");
        printf("2.减法\n");
        printf("3.乘法\n");
        printf("4.除法\n");
        printf("5.退出\n");
        printf("=================================\n");

        // 提示用户输入选项，结尾没有 \n，输入的内容会紧跟在后面。
        printf("请选择：");

        // scanf 从键盘读一个整数放进 choice：%d 读整数，&choice 是 choice 的地址（& 取地址符，scanf 要知道放在哪）。
        // ⚠ 提醒：这里没有检查 scanf 是否读成功。如果输入的是字母，choice 不会变，那个字母还留在输入里，
        // 下一轮 scanf 又会读到它，菜单就会一直重复刷屏（原代码如此，这里不改，只提醒你）。
        scanf("%d", &choice);

        // 选项 5 是退出：== 判断相等（两个等号，一个等号是赋值）。
        if (choice == 5) {
            // break 的意思是"立刻跳出整个循环"，跳出之后程序继续执行循环后面的 return 0。
            break;
        }

        // 用 if ... else if ... else 做"多选一"：从上往下依次检查选项，匹配到哪个就执行哪段，其余的跳过。
        if (choice == 1) {
            printf("请输入第一个数字：");

            // %f 读一个小数（float）。&a 是 a 的地址。输入 3.5，a 就是 3.5。
            scanf("%f", &a);
            printf("请输入第二个数字：");
            scanf("%f", &b);

            // 三个 %.2f 依次对应后面的 a、b、a + b。%.2f 表示按小数输出，保留两位小数。
            // 例：a 是 3.5，b 是 2.25：输出 3.50 + 2.25 = 5.75。
            printf("%.2f + %.2f = %.2f\n", a, b, a + b);

        // 选项 2：减法，流程和加法完全一样，只是运算换成 -。
        } else if (choice == 2) {
            printf("请输入第一个数字：");
            scanf("%f", &a);
            printf("请输入第二个数字：");
            scanf("%f", &b);
            printf("%.2f - %.2f = %.2f\n", a, b, a - b);

        // 选项 3：乘法，运算是 *（乘号）。
        } else if (choice == 3) {
            printf("请输入第一个数字：");
            scanf("%f", &a);
            printf("请输入第二个数字：");
            scanf("%f", &b);
            printf("%.2f * %.2f = %.2f\n", a, b, a * b);

        // 选项 4：除法，运算是 /（除号）。
        } else if (choice == 4) {
            printf("请输入第一个数字：");
            scanf("%f", &a);
            printf("请输入第二个数字：");
            scanf("%f", &b);

            // 除数不能是 0：数学上不允许，程序里 0 做除数会出错。所以做除法之前，先检查 b 是不是 0。
            // 这里是 if 里面再嵌套 if，叫"嵌套判断"。
            if (b == 0) {
                printf("除数不能为 0\n");
            } else {
                printf("%.2f / %.2f = %.2f\n", a, b, a / b);
            }

        // 前面的 1～4 都不是，也不是 5（5 在前面已经 break 了），说明输入的选项不合法，提示重新输入。
        // 然后这一轮结束，回到 while 的开头，重新显示菜单。
        } else {
            printf("输入错误，请重新输入！\n");
        }
    }

    // return 0：结束 main，把 0 交给系统，表示"程序正常结束"。
    return 0;
}

