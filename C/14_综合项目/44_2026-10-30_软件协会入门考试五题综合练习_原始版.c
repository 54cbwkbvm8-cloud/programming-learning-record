// <stdbool.h> 提供 bool 类型：只有 true（真）和 false（假）两个值。
#include <stdbool.h>
#include <stdio.h>

// 函数头：bool 是返回值类型（返回真或假）；n、m 用 long long（范围很大的整数），即使输入很大的数也能处理。
bool first_win(long long n, long long m) {

    // 先检查参数：石子数和最多取的数都必须是正数，否则返回 false。
    if (n <= 0 || m <= 0) {
        return false;
    }

    // m 已经是 long long 的最大值时，m + 1 会溢出（超出能表示的范围，结果就错了）。
    // 这时每次最多能取的颗数已经不小于任何可能的 n，先手一次就能取完，必胜，所以直接返回 true，不再计算 m + 1。
    if (m == LLONG_MAX) {
        return true;
    }

    // % 是取余。余数不是 0（!= 0），先手必胜。比较的结果本身就是真或假，直接 return。
    // 例：n 是 30，m 是 3：30 % 4 = 2，不等于 0，返回 true。
    return n % (m + 1) != 0;
}

int main(void) {
    long long n;
    long long m;

    // %lld 是读取 long long 的格式符；一条 scanf 读两个数，用空格或回车隔开；& 是取地址符。
    // scanf 返回成功读到的个数，应该是 2；!= 2 表示输入不是两个整数，提示后用 return 1 结束（1 表示出错）。
    if (scanf("%lld %lld", &n, &m) != 2) {
        printf("输入错误：请输入两个整数。\n");
        return 1;
    }

    // 再检查两个数都必须是正整数。
    if (n <= 0 || m <= 0) {
        printf("输入错误：石子总数n和每次最多取数m都必须是正整数。\n");
        return 1;
    }

    // ? : 叫"三目运算符"：条件 ? 值1 : 值2，条件成立取值1，否则取值2。
    // first_win 返回真，就输出 "true"，否则输出 "false"。把字符串直接当作 printf 的参数，因为里面没有 % 号，所以是安全的。
    printf(first_win(n, m) ? "true\n" : "false\n");

    return 0;
}

