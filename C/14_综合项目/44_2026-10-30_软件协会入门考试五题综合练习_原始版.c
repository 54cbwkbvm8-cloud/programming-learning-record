// --------------------------------------------------------------------
// 规则：n 颗石子，两人轮流取，每次取 1 到 m 颗，取走最后一颗的赢。
// 结论：n % (m + 1) 不等于 0，先手必胜（第一步取"余数"颗，之后始终让剩下的石子数是 (m + 1) 的倍数）；
