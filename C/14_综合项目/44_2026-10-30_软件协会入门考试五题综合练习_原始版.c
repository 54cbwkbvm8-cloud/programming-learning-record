#elif defined(RUN_Q4)

#include <stdio.h>

// 把"是不是和积数"的判断单独写成一个函数：是返回 1，不是返回 0（C 里习惯用 1 表示"是"，0 表示"否"）。
// 为什么要写成函数？判断的逻辑和输出的逻辑分开，结构更清楚，也方便单独测试。
int is_sum_product(int n) {

    // 先检查范围：只有三位数才有意义，不是三位数就直接返回 0。|| 读作"或者"。
    if (n < 100 || n > 999) {
        return 0;
    }

    // a、b、c 是百位、十位、个位。n / 10 % 10：先 n / 10 去掉个位，再 % 10 取最后一位，就是十位。
    int a = n / 100;
    int b = n / 10 % 10;
    int c = n % 10;

    // 比较的结果是 1（相等）或 0（不相等），直接作为返回值。
    return (a + b + c) * (a * b * c) == n;
}

int main(void) {
    int num;

    // 把每个三位数都检查一遍。
    for (num = 100; num <= 999; num++) {

        // 调用函数：返回 1（真）就进入 if，返回 0（假）就跳过。C 里非 0 就是"真"。
        if (is_sum_product(num)) {
            printf("%d\n", num);
        }
    }

    return 0;
}


