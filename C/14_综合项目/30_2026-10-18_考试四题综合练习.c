// --------------------------------------------------------------------
// 第一部分：引入"工具箱"
// --------------------------------------------------------------------
// <stdio.h> 是"标准输入输出"工具箱：printf（输出）和 scanf（输入）都在里面。
#include <stdio.h>


// --------------------------------------------------------------------
// 第二部分：main 函数 —— 程序从这里开始
// --------------------------------------------------------------------
int main(void) {

    // --------------------------------------------------------------------
    // 第一题：1 到 100 之间的奇数
    // --------------------------------------------------------------------
    printf("1-100 之间的奇数：\n");

    // i 是循环计数器。
    int i;

    // for (初始化; 条件; 每轮结束后做的事)：i 从 1 数到 100，每个数都走一遍。i++ 是"加 1"。
    for (i = 1; i <= 100; i++) {
        // % 是取余：i 除以 2 的余数。余数不是 0（!= 表示"不等于"）的，就是奇数。例：7 % 2 是 1，8 % 2 是 0。
        if (i % 2 != 0) {
            // %d 是整数占位符，输出 i；\n 换行，每个奇数占一行。
            printf("%d\n", i);
        }
    }
    printf("\n");

    // --------------------------------------------------------------------
    // 第二题：两数之和
    // --------------------------------------------------------------------
    printf("两数之和：\n");

    // 数组：一排连在一起的同类型格子。方括号里不写大小，由大括号里的数据个数决定（4 个），下标 0 到 3。
    int nums[] = {2, 7, 11, 15};

    // target 是目标和。
    int target = 9;

    // m1 和 n1 是两层循环的计数器，分别表示"第一个数的下标"和"第二个数的下标"。
    int m1;
    int n1;

    // 外层循环：m1 依次取每个元素，作为"第一个数"。
    for (m1 = 0; m1 < 4; m1++) {
        // 内层循环：n1 从 m1 + 1 开始，取后面的每个元素作为"第二个数"。
        // 从 m1 + 1 开始是为了：同一个元素不能用两次，同一组也不重复试。
        // 所以所有"两两组合"恰好试一遍：(0,1)、(0,2)、(0,3)、(1,2)、(1,3)、(2,3)。
        for (n1 = m1 + 1; n1 < 4; n1++) {
            // 两个数的和等于目标值（== 判断相等）。例：下标 0 的数是 2，下标 1 的数是 7，2 + 7 == 9，成立。
            if (nums[m1] + nums[n1] == target) {
                // 输出这两个数的下标。这里没有 break，找到之后还会继续找，所以会输出所有符合条件的组合。
                printf("[%d,%d]\n", m1, n1);
            }
        }
    }
    printf("\n");

    // --------------------------------------------------------------------
    // 第三题：水仙花数
    // --------------------------------------------------------------------
    // 水仙花数：三位数，各位数字的立方和等于它本身。例：153 = 1³ + 5³ + 3³ = 1 + 125 + 27。
    printf("100 到 999 之间的水仙花数：\n");

    // numbers 是当前检查的数；a、b、c 分别存它的百位、十位、个位数字。
    int numbers = 100;
    int a;
    int b;
    int c;

    // numbers 从 100 数到 999，每个三位数都检查一遍。
    for (numbers = 100; numbers < 1000; numbers++) {
        // 整数除法会丢掉小数部分：153 / 100 得 1，就是百位数字。
        a = numbers / 100;

        // numbers / 10 去掉个位（153 变 15），再 % 10 取最后一位 5，就是十位数字。/ 和 % 优先级相同，从左往右算。
        b = numbers / 10 % 10;

        // % 10 取个位数字：153 % 10 得 3。
        c = numbers % 10;

        // 每个数字乘三次得到立方，三个立方相加，和本身比较（==）。相等就是水仙花数。
        // 100 到 999 里有 153、370、371、407。
        if (a * a * a + b * b * b + c * c * c == numbers) {
            printf("%d\n", numbers);
        }
    }
    printf("\n");

    // --------------------------------------------------------------------
    // 第四题：巴什博弈（取石子游戏）
    // --------------------------------------------------------------------
    // 规则：n 颗石子，两人轮流取，每次取 1 到 m 颗，取走最后一颗的赢。
    // 必胜策略：先手第一步取 n % (m + 1) 颗，之后对方取 x 颗，自己就取 (m + 1 - x) 颗，
    // 每一轮双方合计取走 m + 1 颗，剩下的石子数永远是 (m + 1) 的倍数。如果 n % (m + 1) 是 0，先手没有必胜策略。
    printf("巴什博弈：\n");

    // n 是石子总数，m 是每次最多取几颗，firstTake 是先手第一步取的颗数。
    int n;
    int m;
    int firstTake;

    printf("规则制定：\n");

    printf("请输入石子的总颗数：\n");

    // scanf 读一个整数放进 n（& 取地址符）。返回值不是 1 说明没读成功。
    // || 读作"或者"：读失败，或者石子数不是正数，都是无效输入。
    // || 有"短路"特点：左边成立，右边就不会计算，所以读失败时不会去用没有赋值的 n。
    if (scanf("%d", &n) != 1 || n <= 0) {
        printf("输入错误：石子总数必须是正整数。\n");

        // return 1：提前结束程序，1 表示"出错"（0 表示正常）。
        return 1;
    }

    printf("请输入最多能取的石子数：\n");

    // 同样检查：必须是正整数。
    if (scanf("%d", &m) != 1 || m <= 0) {
        printf("输入错误：每次最多取石数必须是正整数。\n");
        return 1;
    }

    printf("=================================================\n");

    // % 是取余。n % (m + 1) 就是先手第一步该取的颗数。
    // 例：10 颗石子，每次最多取 3 颗：10 % (3 + 1) = 2，先手取 2 颗，剩 8 颗（4 的倍数）。
    int remainder = n % (m + 1);

    // 余数是 0：先手没有必胜策略。否则按提示的颗数取，就能必胜。
    if (remainder == 0) {
        printf("提示：当前局面先手没有必胜策略。\n");
    } else {
        printf("提示：按照必胜策略，你应该先取 %d 颗石子。\n", remainder);
    }

    printf("请输入你先手取的石子数（1 至 %d）：\n", m);

    // 检查先手取的数是否合法：必须读成功；至少 1 颗；不能超过每次最多取的 m；也不能超过剩下的石子数 n。
    // 任意一个条件成立，都说明输入不合法。
    if (scanf("%d", &firstTake) != 1 || firstTake < 1 || firstTake > m || firstTake > n) {
        printf("输入错误：先手取石数不符合规则。\n");
        return 1;
    }

    printf("巴什博弈演示：\n");
    printf("============================================\n");
    printf("初始石子数为 %d，每次可以取 1 至 %d 颗。\n", n, m);

    printf("你先取 %d 颗，剩余 %d 颗。\n", firstTake, n - firstTake);

    // -= 是"减去再赋值"：n -= firstTake 等价于 n = n - firstTake。更新剩余石子数。
    n -= firstTake;

    printf("============================================\n");

    // 只要还有石子，游戏就继续：每一轮是"对手取一次，你回应一次"。
    while (n > 0) {
        // opponentTake 是对手本轮取的颗数，声明在循环里面，每一轮重新创建。
        int opponentTake;

        printf("请输入对手本轮取几颗（1 至 %d，当前剩余 %d）：", m, n);

        // 读对手的取法，没读成功（比如输入了字母）就提示并结束程序。
        if (scanf("%d", &opponentTake) != 1) {
            printf("输入无效，请重新运行程序并输入整数。\n");
            return 1;
        }

        // 检查对手的取法是否合法：至少 1 颗，不超过 m，也不超过剩下的石子数。
        if (opponentTake < 1 || opponentTake > m || opponentTake > n) {
            printf("这次取法不合法，请重新输入。\n");

            // continue 的意思是"跳过本轮剩下的代码，直接进入下一轮"：回到 while 的开头，重新输入。
            continue;
        }

        // 把对手取走的石子从剩余数里减掉。
        n -= opponentTake;

        printf("对手取走 %d 颗后，还剩 %d 颗。\n", opponentTake, n);

        // 对手取完后石子没了，说明对手取到了最后一颗，对手获胜。break 的意思是"立刻跳出整个循环"。
        if (n == 0) {
            printf("对手取到了最后一颗石子，对手获胜。\n");
            break;
        }

        // 你的回应：取 (m + 1 - 对手取的数) 颗，让这一轮双方合计恰好取走 m + 1 颗。
        // 例：m 是 3，对手取 3 颗，你取 3 + 1 - 3 = 1 颗；对手取 2 颗，你取 2 颗。
        int myTake = m + 1 - opponentTake;

        // 算出来的颗数比剩下的还多（石子不够），就只能把剩下的全取走。
        if (myTake > n) {
            myTake = n;
        }

        n -= myTake;

        printf("你回应取走 %d 颗，还剩 %d 颗。\n", myTake, n);

        // 你取走之后石子没了，说明你取到了最后一颗，你获胜。
        if (n == 0) {
            printf("你取到了最后一颗石子，你获胜。\n");
            break;
        }
    }

    // return 0：结束 main，把 0 交给系统，表示"程序正常结束"。
    return 0;
}

