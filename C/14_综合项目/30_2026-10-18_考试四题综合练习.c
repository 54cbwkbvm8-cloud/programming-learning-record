//       2. 两数之和：在数组 {2, 7, 11, 15} 里找出和为 9 的两个数的下标
//       3. 输出 100 到 999 之间的水仙花数（各位数字的立方和等于它本身）
//       4. 巴什博弈：一堆石子，轮流取，每次取 1 到 m 颗，取走最后一颗的人赢
//          （必胜策略：让剩下的石子数是 (m + 1) 的倍数）
//
// 怎么运行（在 Mac 终端里，先 cd 到这个文件所在的文件夹）：
//   编译：clang -Wall -Wextra -o demo "30_2026-10-18_考试四题综合练习.c"
//   运行：./demo
//   说明：编译 = 把人能看懂的 C 代码翻译成电脑能执行的程序。
//         -Wall -Wextra 的意思是"把所有可疑的地方都警告我"，
