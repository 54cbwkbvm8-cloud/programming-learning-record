// --------------------------------------------------------------------
// 第一部分：引入"工具箱"
// --------------------------------------------------------------------
// <stdio.h> 是"标准输入输出"工具箱：printf（输出）和 scanf（输入）都在里面。
#include <stdio.h>


// --------------------------------------------------------------------
// 第二部分：函数声明
// --------------------------------------------------------------------
// 函数声明（函数原型）：只写函数头，末尾加分号。提前告诉编译器有这几个函数。
// int a[] 是整型数组参数，n 是元素个数（数组传进函数后，函数不知道长度，要另外传）。
int max(int a[], int n);
int min(int a[], int n);

// sum 的返回类型是 float。
float sum(int a[], int n);


// --------------------------------------------------------------------
// 第三部分：函数定义 —— 最大值
// --------------------------------------------------------------------
// 思路是"打擂台"：先假设第一个元素最大，再让后面的依次来挑战。
int max(int a[], int n) {

    // 一行声明两个变量：i 做循环计数器；max 初始值取 a[0]（数组下标从 0 开始）。
    // max 和函数名 max 相同：在函数里，max 指的是这个局部变量（局部的优先），所以不冲突，但容易看混。
    int i, max = a[0];

    // for (初始化; 条件; 每轮结束后做的事)：i 从 1 数到 n - 1。条件是 i < n：n 个元素的下标最大是 n - 1，写 <= 会越界。
    for (i = 1; i < n; i++) {
        // 比当前最大值大，就更新。
        if (a[i] > max) {
            max = a[i];
        }
    }

    // return 把结果交给调用者。
    return max;
}


// --------------------------------------------------------------------
// 第四部分：函数定义 —— 最小值
// --------------------------------------------------------------------
// 和 max 对称：先假设第一个元素最小，遇到更小的就更新。
int min(int a[], int n) {
    int i, min = a[0];
    for (i = 1; i < n; i++) {
        if (a[i] < min) {
            min = a[i];
        }
    }
    return min;
}


// --------------------------------------------------------------------
// 第五部分：函数定义 —— 总和
// --------------------------------------------------------------------
float sum(int a[], int n) {

    // sum 是累加器，必须先设成 0。它和函数名 sum 相同，这里指的是局部变量。
    int i, sum = 0;
    for (i = 0; i < n; i++) {
        // += 是"加上再赋值"：sum += a[i] 等价于 sum = sum + a[i]。
        sum += a[i];
    }

    // 函数的返回类型是 float，而 sum 是 int：return 时 int 会自动转成 float（80 变成 80.0）。
    return sum;
}


// --------------------------------------------------------------------
// 第六部分：main 函数 —— 程序从这里开始
// --------------------------------------------------------------------
int main(void) {

    // age 存年龄；score 存成绩（float，可以带小数）。
    int age;
    float score;
    printf("请输入年龄：");

    // scanf 从键盘读一个整数放进 age：%d 读整数，&age 是 age 的地址（& 取地址符）。
    scanf("%d", &age);
    printf("请输入你的成绩：");

    // %f 读一个小数（float）。
    scanf("%f", &score);

    // grade 存等级，是单个字符（char），值用单引号写，例如 'A'。
    char grade;

    // 按成绩划分等级：从上往下检查，遇到第一个成立的就执行并跳过其余分支。
    // 能走到某一行，说明前面的条件都不成立，所以只需要写下限。
    // 这是原代码设定的分档：60 分及以上是 A，50 到 59 是 B，40 到 49 是 C，30 到 39 是 D，其余是 E。
    // 例：输入 85.5：>= 60 成立，等级 A。
    if (score >= 60) {
        grade = 'A';
    } else if (score >= 50) {
        grade = 'B';
    } else if (score >= 40) {
        grade = 'C';
    } else if (score >= 30) {
        grade = 'D';
    } else {
        grade = 'E';
    }

    // 一条 printf 里有三个占位符，按顺序对应后面的 age、score、grade：
    // %d 整数，%f 小数（默认显示 6 位小数，所以 85.5 显示成 85.500000），%c 单个字符。
    printf("你的年龄是 %d 岁\n你的成绩是 %f\n你的等级是 %c\n", age, score, grade);

    // --------------------------------------------------------------------
    // 用 for 循环求 1 到 10 的和
    // --------------------------------------------------------------------
    printf("用 for 循环输出 1 到 10 的和\n");

    // total 存累加的和，必须先设成 0。
    int total = 0;
    int i;

    // i 从 1 数到 10。
    for (i = 1; i <= 10; i++) {
        // 每轮把当前的 i 加进 total。1 + 2 + ... + 10 = 55。
        total += i;
    }
    printf("1 到 10 的和是 %d\n", total);

    // --------------------------------------------------------------------
    // 用 while 循环求 1 到 10 的和
    // --------------------------------------------------------------------
    printf("用 while 循环输出 1 到 10 的和\n");

    // 重新累加之前，先把 total 清零，否则会在上一次的 55 的基础上继续加。
    total = 0;

    // while 的初始化要写在循环外面：给 i 重新赋值 1。
    i = 1;

    // while (条件)：条件成立就执行一遍循环体，执行完回头再检查。
    while (i <= 10) {
        total += i;

        // 让 i 加 1，缺了它就是死循环。
        i++;
    }
    printf("1 到 10 的和是 %d\n", total);

    // --------------------------------------------------------------------
    // 输入 10 个数，求最大值、最小值、总和
    // --------------------------------------------------------------------
    // 数组：10 个整数格子，下标 0 到 9。
    int a[10];
    printf("请输入 10 个数：\n");

    // 用循环读入 10 个数：i 是 0 到 9，对应 a[0] 到 a[9]。
    for (i = 0; i < 10; i++) {
        // i + 1：下标从 0 开始，显示给人看的编号从 1 开始，所以加 1。
        printf("请输入第 %d 个数：", i + 1);

        // &a[i] 是第 i 个元素的地址。
        scanf("%d", &a[i]);
    }

    // max(a, 10)：调用函数，数组名 a 传过去的是数组的起始地址，10 是元素个数；函数返回最大值，交给 %d 显示。
    printf("这十个数的最大值是：%d\n", max(a, 10));
    printf("这十个数的最小值是：%d\n", min(a, 10));

    // sum 返回的是 float，所以这里用 %.2f（保留两位小数）来输出。
    printf("这十个数的和是：%.2f\n", sum(a, 10));

    // return 0：结束 main，把 0 交给系统，表示"程序正常结束"。
    return 0;
}

