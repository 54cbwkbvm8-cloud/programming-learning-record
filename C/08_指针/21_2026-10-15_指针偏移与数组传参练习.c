#include <stddef.h>
#include <stdio.h>
// 定义函数 print_array；参数接收调用方传入的数据，函数体完成操作，返回语句（如有）把结果交还调用者。
void print_array(const int *arr, size_t length) {
// 声明变量并确定其数据类型；未初始化的局部变量不能直接当作已知值使用。
    size_t i;
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("数组元素有：");
// 循环按“初始化；条件判断；每轮更新”的顺序执行。先检查条件，再运行循环体，最后更新循环变量；注意边界是否会多执行或少执行一次。
    for (i = 0; i < length; i++) {
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
        printf("%d ", arr[i]);
    }
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("\n");
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("函数内部 sizeof(arr) = %zu字节\n", sizeof(arr));
}
// 定义函数 main；参数接收调用方传入的数据，函数体完成操作，返回语句（如有）把结果交还调用者。
int main(void) {
// 声明数组并为元素分配连续空间；下标从 0 开始，有效范围必须小于数组长度。
    int a[] = {10, 20, 30, 40, 50};
// 声明或初始化指针变量；指针保存地址，使用前必须确认它指向有效对象，不能解引用空指针。
    int *p = &a[3];
// 调用 `sizeof()` 完成相应操作；括号中的表达式是传给函数的实参，具体效果由该函数定义决定。
    size_t length = sizeof(a) / sizeof(a[0]);
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("数组长度为：%zu\n", length);
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("整个数组占用的空间为：%zu字节\n", sizeof(a));
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("一个元素占用的空间为：%zu 字节", sizeof(a[0]));
// 调用 `print_array()` 完成相应操作；括号中的表达式是传给函数的实参，具体效果由该函数定义决定。
    print_array(a, length);
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("p指向的元素：%d\n", *p);
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("p指向的元素的下一个元素*(p + 1)是：%d\n", *(p + 1));
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("p指向的元素的上一个元素*(p - 1)是：%d\n", *(p - 1));
// 结束当前函数调用，并把表达式 `0` 的结果返回给调用者。
    return 0;
}
