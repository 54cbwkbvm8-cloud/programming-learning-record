// --------------------------------------------------------------------
// 第一部分：引入"工具箱"
// --------------------------------------------------------------------
// <stddef.h> 提供 size_t（表示"大小、个数"的无符号整数类型）和 NULL。
#include <stddef.h>

// <stdio.h> 是"标准输入输出"工具箱，printf 在里面。
#include <stdio.h>


// --------------------------------------------------------------------
// 第二部分：打印数组的函数
// --------------------------------------------------------------------
// 参数 const int *arr 拆开看：
//   int *arr ：arr 是一个"指向 int 的指针"，里面存的是一个 int 的地址（这里是数组第一个元素的地址）；
//   const    ：承诺"在函数里只读不改"这些数据，如果误改，编译器会报错。
// 为什么数组参数要写成指针？数组传给函数时，传过去的只是"第一个元素的地址"（数组退化成了指针），
// 函数并不知道数组有多长，所以要用 length 另外把元素个数传进来。
void print_array(const int *arr, size_t length) {

    // 循环下标，类型和 length 一致（都是 size_t），比较时不会出现符号不一致的警告。
    size_t i;
    printf("数组元素有：");

    // i 从 0 数到 length - 1，走遍所有元素。
    for (i = 0; i < length; i++) {
        // 对指针也可以用方括号：arr[i] 的意思是"从 arr 指向的位置往后数第 i 个元素"。
        printf("%d ", arr[i]);
    }
    printf("\n");

    // 这里的 sizeof(arr) 得到的是"指针本身的大小"（64 位系统上是 8 字节），不是整个数组的大小。
    // 原因就是前面说的：传进函数后，arr 只是一个指针。所以必须额外传 length。
    // %zu 是输出 size_t 类型的占位符。
    printf("函数内部 sizeof(arr) = %zu字节\n", sizeof(arr));
}


// --------------------------------------------------------------------
// 第三部分：main 函数 —— 程序从这里开始
// --------------------------------------------------------------------
int main(void) {

    // 数组 = 一排连续的 int 格子。方括号里不写数字，编译器会按大括号里有几个数来决定大小，这里是 5 个。
    // 下标从 0 开始：a[0] 是 10，a[3] 是 40。
    int a[] = {10, 20, 30, 40, 50};

    // 指针 = 专门存放"地址"的变量。int *p 表示 p 是"指向 int 的指针"。
    // &a[3] 是 a[3] 的地址（& 叫取地址符）。所以 p 指向数组的第 4 个元素（值是 40）。
    // 记忆：& 是"取地址"；* 在声明里表示"这是指针"，在使用时表示"取出地址里的内容"（叫"解引用"）。
    int *p = &a[3];

    // sizeof(a) 是整个数组占的字节数：5 个 int × 每个 4 字节 = 20；
    // sizeof(a[0]) 是一个元素占的字节数：4；相除得到元素个数 5。
    // 好处：以后数组元素个数变了，这一句不用改。
    // 注意：只有在数组定义所在的这个范围里，sizeof(a) 才是整个数组的大小。
    size_t length = sizeof(a) / sizeof(a[0]);
    printf("数组长度为：%zu\n", length);
    printf("整个数组占用的空间为：%zu字节\n", sizeof(a));

    // 这一条的结尾没有 \n，所以下一条输出（print_array 里的文字）会接在同一行后面。
    printf("一个元素占用的空间为：%zu 字节", sizeof(a[0]));

    // 调用函数：数组名 a 作为参数时，传过去的是数组第一个元素的地址（等价于 &a[0]），
    // 再把元素个数 length 一起传过去。
    print_array(a, length);

    // *p 叫"解引用"：取出 p 指向的那个地址里存的值。p 指向 a[3]，所以 *p 是 40。
    printf("p指向的元素：%d\n", *p);

    // 指针加 1，不是地址数值加 1 个字节，而是"移动到下一个元素"（实际加 sizeof(int) 个字节）。
    // 所以 p + 1 指向 a[4]，*(p + 1) 是 50。
    // 括号不能省：*(p + 1) 是"先移动，再取值"；*p + 1 是"先取值 40，再加 1"，意思完全不同。
    printf("p指向的元素的下一个元素*(p + 1)是：%d\n", *(p + 1));

    // p - 1 指向前一个元素 a[2]，*(p - 1) 是 30。
    // 做指针偏移时要保证不超出数组范围，否则就是越界访问，结果不可预料。
    printf("p指向的元素的上一个元素*(p - 1)是：%d\n", *(p - 1));

    // return 0：结束 main，把 0 交给系统，表示"程序正常结束"。
    return 0;
}

