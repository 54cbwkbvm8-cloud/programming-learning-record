// --------------------------------------------------------------------
// 第一部分：引入"工具箱"
// --------------------------------------------------------------------
// <stdio.h> 是"标准输入输出"工具箱，printf 在里面。
#include <stdio.h>


// --------------------------------------------------------------------
// 第二部分：用指针交换两个变量
// --------------------------------------------------------------------
// 参数 int *a、int *b：两个"指向 int 的指针"，接收的是变量的地址。
// 有了地址，函数就能直接找到 main 里的那两个变量，并修改它们。
void swap(int *a, int *b) {

    // 交换要借助一个临时变量，就像要互换两杯水，必须有第三个空杯子。
    // *a 叫"解引用"：取出 a 指向的那个变量的值，先存进 temp 备份。
    int temp = *a;

    // 把 b 指向的变量的值，写进 a 指向的变量。（a 原来的值已经备份在 temp 里了，不会丢。）
    *a = *b;

    // 把备份的值写进 b 指向的变量。
    // 例：*a 是 10，*b 是 20：temp 先存 10；*a 变成 20；*b 变成 10。交换完成。
    *b = temp;
}


// --------------------------------------------------------------------
// 第三部分：普通的值传递
// --------------------------------------------------------------------
// 参数 int a、int b：普通的整数参数。C 语言默认是"值传递"：
// 调用时把实参的值复制一份给形参，函数里改的只是复制品，不会影响调用处的原变量。
void swapByValue(int a, int b) {

    // 在函数里，a 和 b 确实被交换了，但它们只是复制品。
    int temp = a;
    a = b;
    b = temp;

    // 在函数内部输出，可以看到 a 和 b 已经交换了。
    printf("普通值传递函数内部：a = %d, b = %d\n", a, b);
}


// --------------------------------------------------------------------
// 第四部分：main 函数 —— 程序从这里开始
// --------------------------------------------------------------------
int main(void) {

    // x、y 用来测试指针版本；m、n 用来测试值传递版本。
    int x = 10;
    int y = 20;

    // m、n 的初始值和 x、y 相同，方便对比两种方法的结果。
    int m = 10;
    int n = 20;
    printf("=====1.指针参数交换=====\n");

    // %d 是整数占位符，依次对应后面的 x、y。
    printf("交换前：x = %d, y = %d\n", x, y);

    // & 叫"取地址符"：&x 是 x 的地址。把两个变量的地址传给 swap，swap 就能通过地址直接修改 x 和 y。
    swap(&x, &y);

    // 交换后：x 是 20，y 是 10，真的交换了。
    printf("交换后：x = %d, y = %d\n", x, y);
    printf("=====2.普通值传递版本=====\n");
    printf("交换前：m = %d, n = %d\n", m, n);

    // 这里传的是 m、n 的值（复制品）。函数内部会输出交换后的 a = 20，b = 10。
    swapByValue(m, n);

    // 回到 main，m 和 n 仍然是 10 和 20，没有交换。
    // 对比结论：想让函数修改调用者的变量，就要传地址（指针）；传值只是复制，改不了原变量。
    // scanf 读变量时要在变量前写 &，也是同样的道理：要把读到的值"送回"变量，必须给它地址。
    printf("调用后：m = %d, n = %d\n", m, n);

    // return 0：结束 main，把 0 交给系统，表示"程序正常结束"。
    return 0;
}

