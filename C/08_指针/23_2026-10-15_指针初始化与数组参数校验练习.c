// --------------------------------------------------------------------
// 参数 const int arr[] 是"数组参数"：实际传进来的是第一个元素的地址（等价于 const int *arr）；
// const 表示函数里只读不改。length 是元素个数：数组传进函数后，函数不知道有多长，要另外传。
// 为什么要检查参数？函数是给别人调用的，传进来的指针可能是空的，长度也可能是 0 或负数，
// 不检查就直接访问，程序会崩溃。
void print_array(const int arr[], int length) {

    // NULL 叫"空指针"，表示"这个指针没有指向任何东西"。== 是判断相等。
    // arr 是 NULL 时，不能再去访问 arr[i]。
    if (arr == NULL) {
        printf("错误：数组指针为空，不能访问数组。\n");
    }

    // ⚠ 提醒：上面那个 if 里缺少 return;，所以 arr 为 NULL 时，打印完错误信息，程序还会继续往下执行，
    // 后面的 arr[i] 会去访问空指针，导致程序崩溃。教程版里补上了 return;。
    // 这是原代码的缺陷，这里不改，只提醒你。
    // length 必须大于 0 才有元素可以打印。<= 读作"小于或等于"。
    if (length <= 0) {
        printf("错误：数组长度必须大于0,数组长度为 0 或者小于 0，没有可以打印的元素\n");

        // return; 用在 void 函数里，表示"提前结束这个函数"（void 函数没有返回值，所以 return 后面什么都不写）。
        return;
    }
    printf("数组元素为：");

    // i 从 0 数到 length - 1，走遍数组。
    for (int i = 0; i < length; i++) {
        // arr[i] 是数组的第 i 个元素（下标从 0 开始），%d 是整数占位符。
        printf("%d ", arr[i]);

        // 最后一个元素后面不需要逗号，所以只有"不是最后一个元素"时才输出逗号。
        // 例：长度是 5 时，i 是 0 到 3 输出逗号，i 是 4 时不输出。
        // 这个 if 后面没有大括号，所以它只管下面紧挨着的那一条语句。
        if (i < length - 1)
            printf(",");
    }
    printf("\n");
}


