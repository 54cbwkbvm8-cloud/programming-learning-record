#include <stdio.h>
// 定义函数 print_array；参数接收调用方传入的数据，函数体完成操作，返回语句（如有）把结果交还调用者。
void print_array(const int arr[], int length) {
// 判断条件 `(arr == NULL)` 是否成立；条件为真时执行对应分支，否则跳过或转入其他分支。
    if (arr == NULL) {
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
        printf("错误：数组指针为空，不能访问数组。\n");
    }
// 判断条件 `(length <= 0)` 是否成立；条件为真时执行对应分支，否则跳过或转入其他分支。
    if (length <= 0) {
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
        printf("错误：数组长度必须大于0,数组长度为 0 或者小于 0，没有可以打印的元素\n");
// 结束当前函数调用；当前函数不再继续执行后续语句。
        return;
    }
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("数组元素为：");
// 循环按“初始化；条件判断；每轮更新”的顺序执行。先检查条件，再运行循环体，最后更新循环变量；注意边界是否会多执行或少执行一次。
    for (int i = 0; i < length; i++) {
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
        printf("%d ", arr[i]);
// 判断条件 `(i < length - 1)` 是否成立；条件为真时执行对应分支，否则跳过或转入其他分支。
        if (i < length - 1)
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
            printf(",");
    }
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("\n");
}
// 定义函数 main；参数接收调用方传入的数据，函数体完成操作，返回语句（如有）把结果交还调用者。
int main(void) {
// 声明并初始化变量；`=` 是赋值运算符，用右侧表达式的值设置左侧变量，而不是比较两个值。
    int number = 42;
// 声明或初始化指针变量；指针保存地址，使用前必须确认它指向有效对象，不能解引用空指针。
    int *p = NULL;
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("===1.指针初始化演示===\n");
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("指针初始化时为 NULL，此时不解引用。\n");
// 更新变量或保存计算结果；逐步跟踪右侧表达式，有助于理解每轮循环中的数据变化。
    p = &number;
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("p现在保存 number 的地址。\n");
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("number = %d\n", number);
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("解引用运算符*访问了p 指向的对象，所以*p = %d\n", *p);
// 声明数组并为元素分配连续空间；下标从 0 开始，有效范围必须小于数组长度。
    int numbers[] = {10, 20, 30, 40, 50};
// 调用 `sizeof()` 完成相应操作；括号中的表达式是传给函数的实参，具体效果由该函数定义决定。
    int length = (int)sizeof(numbers) / sizeof(numbers[0]);
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("\n2.数组参数与长度演示\n");
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("调用函数前计算得到的数组长度：%d\n", length);
// 调用 `print_array()` 完成相应操作；括号中的表达式是传给函数的实参，具体效果由该函数定义决定。
    print_array(numbers, 0);
// 调用 `print_array()` 完成相应操作；括号中的表达式是传给函数的实参，具体效果由该函数定义决定。
    print_array(NULL, 3);
// 结束当前函数调用，并把表达式 `0` 的结果返回给调用者。
    return 0;
}
