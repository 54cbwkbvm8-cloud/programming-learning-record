// <stddef.h> 提供 size_t（表示"大小、个数"的无符号整数类型）和 NULL。
#include <stddef.h>

// <stdio.h> 是"标准输入输出"工具箱，printf 在里面。
#include <stdio.h>


// --------------------------------------------------------------------
// 第二部分：第一题 —— 变量作用域
// --------------------------------------------------------------------
// void 表示函数不返回值，(void) 表示没有参数。
// "作用域"就是一个变量"能被使用的范围"：局部变量从声明的地方开始，到它所在的那对大括号结束。
void demonstrate_scope(void) {

    // 外层变量 x，值是 1，作用域是这个函数里它之后的所有位置。
    int x = 1;
    printf("【第一题：变量作用域】\n");

    // 单独的一对大括号 { } 叫"代码块"，它划出一个新的小范围。
    {
        // 在代码块里又声明了一个同名变量 x：它是另一个变量，和外面的 x 毫无关系，只在这对大括号里有效。
        // 在块里写 x，指的是离自己最近的这个（值是 2），外面那个 x（值是 1）被"遮住"了。
        int x = 2;

        // 这里访问的是块里的 x，输出 2；后面带一个空格，不换行。
        printf("%d ", x);
    }

    // 块已经结束，里面的那个 x 就不存在了，这里的 x 又是外层的 x，输出 1。
    // 所以这个函数输出的是 "2 1"。结论：同名变量时，访问的是离自己最近的那个。
    printf("%d\n", x);
}


// --------------------------------------------------------------------
// 第三部分：第二题 —— 指针与数组
// --------------------------------------------------------------------
void demonstrate_pointer(void) {

    // 数组：5 个 int 格子，下标 0 到 4。
    int a[5] = {10, 20, 30, 40, 50};

    // 数组名 a 在表达式里代表第一个元素的地址；a + 2 是向后移动 2 个元素，指向 a[2]。
    // int *p 表示 p 是"指向 int 的指针"，里面存的就是这个地址。
    int *p = a + 2;
    printf("【第二题：指针与数组】\n");

    // *p 叫"解引用"：取出 p 指向的值，是 30。
    printf("p 指向的元素a[2] = %d\n", *p);

    // p - 1 指向前一个元素 a[1]，*(p - 1) 是 20。括号不能省：*p - 1 是先取值再减 1，意思不同。
    printf("*(p - 1) = %d\n", *(p - 1));

    // p[0] 等价于 *(p + 0)，也就是 *p，是 30；再加上 *(p - 1)（20），结果是 50。
    // %d 后面可以直接放一个算式，先算出结果再显示。
    printf("p[0] + *(p - 1) = %d\n", p[0] + *(p - 1));
}


// --------------------------------------------------------------------
// 第四部分：第四题 —— 数组作为函数参数
// --------------------------------------------------------------------
// 参数 int *a：调用时传的虽然是数组，但进到函数里，a 只是一个"指向 int 的指针"（存的是数组首元素的地址）。
// 参数 length：调用处另外传进来的真实元素个数。
void show_array_parameter_size(int *a, size_t length) {
    printf("【第四题：数组与函数参数】\n");

    // size_t 是表示"大小、个数"的无符号整数类型，输出它要用 %zu。
    // sizeof(a)：a 现在是指针，所以得到的是"指针本身的大小"（64 位系统上是 8 字节），而不是数组的大小。
    size_t pointer_bytes = sizeof(a);

    // 单个 int 元素的大小，是 4 字节。
    size_t element_bytes = sizeof(a[0]);

    // 这就是常见的"错误写法"：想用 sizeof(a) / sizeof(a[0]) 求元素个数，
    // 但 a 是指针，算出来是 8 / 4 = 2，不是真实的 5。
    // 这个算法只在"数组本身所在的范围"里才正确（见 main 里的 length）。
    size_t mistake_count = pointer_bytes / element_bytes;
    printf("函数形参 sizeof(a) = %zu 字节\n", pointer_bytes);
    printf("单个元素 sizeof(a[0]) = %zu 字节\n", element_bytes);
    printf("题目表达式 sizeof(a) / sizeof(a[0]) = %zu（错误结果）\n", mistake_count);

    // 正确做法：在数组所在的地方先把个数算好，再作为参数 length 传给函数。
    printf("从调用处传入的真实元素个数 = %zu\n\n", length);
}


// --------------------------------------------------------------------
// 第五部分：main 函数 —— 程序从这里开始
