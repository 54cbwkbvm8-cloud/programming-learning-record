// --------------------------------------------------------------------
// 第一部分：引入"工具箱"
// --------------------------------------------------------------------
// <stdio.h> 是"标准输入输出"工具箱，printf 在里面。
#include <stdio.h>


// --------------------------------------------------------------------
// 第二部分：main 函数 —— 程序从这里开始
// --------------------------------------------------------------------
int main(void) {

    // --------------------------------------------------------------------
    // 第三部分：指针的基本读写
    // --------------------------------------------------------------------
    printf("===安全使用指针===\n");

    // 声明一个整数变量 value，初始值 10。
    int value = 10;

    // int *p 表示 p 是"指向 int 的指针"，专门存放 int 变量的地址。
    // &value 是 value 的地址（& 叫取地址符）。这一句让 p 指向 value。
    // 为什么声明时就赋值？指针如果没有指向有效的地址就去使用，程序会出错；声明时就让它指向 value，最安全。
    int *p = &value;
    printf("value 当前的值是：%d\n", value);

    // *p 叫"解引用"：访问 p 指向的那个变量。p 指向 value，所以 *p 就是 value，值是 10。
    printf("*p当前读到的值是：%d\n", *p);

    // 通过指针修改：把 20 写进 p 指向的地方。p 指向 value，所以 value 变成了 20。
    // 这就是指针的作用之一：不直接用变量名，也能读写那个变量。
    *p = 20;

    // value 变成了 20，证明通过 *p 确实修改了 value。
    printf("通过*p 修改后 value 的值是：%d\n", value);

    // --------------------------------------------------------------------
    // 第四部分：switch 的"穿透"
    // --------------------------------------------------------------------
    printf("\n===switch的执行顺序===\n");
    int choice = 2;

    // 字符串里 \n 的后面多了一个空格，所以下一行输出的开头会多一个空格。
    printf("choice 当前的值是：%d\n ", choice);
    printf("switch输出的值是：\n");

    // switch 拿 choice 的值和每个 case 比较，找到相等的 case，就从那里开始往下执行。choice 是 2，所以从 case 2 开始。
    switch (choice) {
    // case 1 的末尾没有 break。
    case 1:
        printf("A");

    // 匹配！从这里开始执行：输出 B。
    // 因为这里也没有 break，程序不会停，会接着执行下一个 case 里的代码（不再判断条件），这就是"穿透"。
    // 编译时 -Wextra 会对 case 1、case 2 各给出一条 this statement may fall through（这条语句可能穿透）的警告，
    // 正是在提醒你：这里漏写了 break。本程序是故意演示穿透，所以这两条警告可以放心。
    case 2:
        printf("B");

    // 继续执行：输出 C 和换行。
    case 3:
        printf("C\n");

        // 遇到 break，跳出整个 switch。所以最终输出是 BC。
        // 如果 choice 是 1，会输出 ABC；如果是 3，只输出 C。
        // 结论：每个 case 末尾一般都要写 break，除非你就是想要"穿透"。
        break;

    // default 表示"所有 case 都不匹配时"才执行（比如 choice 是 9）。这里是一句输出文字，这次运行不会执行到。
    // default 在最后，所以不写 break 也可以。
    default:
        printf("我真牛逼\n");
    }

    // return 0：结束 main，把 0 交给系统，表示"程序正常结束"。
    return 0;
}

