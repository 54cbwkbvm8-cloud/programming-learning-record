    printf("*p当前读到的值是：%d\n", *p);
    *p = 20;
    printf("通过*p 修改后 value 的值是：%d\n", value);
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("\n===switch的执行顺序===\n");
// 声明并初始化变量；`=` 是赋值运算符，用右侧表达式的值设置左侧变量，而不是比较两个值。
    int choice = 2;
