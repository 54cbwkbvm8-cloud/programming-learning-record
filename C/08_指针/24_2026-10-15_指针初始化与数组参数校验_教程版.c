/*
 * 文件用途：本文件围绕“指针初始化与数组参数校验 教程版”展开。
 * 核心知识点：指针、数组、循环、分支判断、函数。
 * 基本流程：根据代码中的输入或初始数据，按条件、循环和函数调用完成处理，再输出结果。
 * 输入：本文件使用预设数据、初始化值或函数参数。输出：通过控制台打印结果。
 * 阅读提醒：指针和动态内存相关操作必须确认地址有效，并注意释放已申请的内存。 检查数组下标、字符串结束符和缓冲区容量，避免越界访问。
 * 依赖头文件：stdio.h。
 */
#include <stdio.h> // 引入标准输入输出库，让程序可以使用 printf() 输出文字和数据。

void print_array(const int arr[],
                 int length) { // 定义数组打印函数：arr 接收首元素地址，length 接收元素个数。
    if (arr == NULL) {         // 先检查传入的指针是否为空；空指针不指向可访问的数组元素。
        printf("错误：数组指针为空，不能访问数组。\n"); // 告诉调用者当前没有可访问的数组地址。
        return; // 立即结束本次函数调用，避免继续读取 arr[i]。
    } // 结束空指针检查分支。

    if (length <= 0) { // 检查长度是否为 0 或负数，防止循环没有意义地执行或使用无效长度。
        printf("数组长度为 0 或小于 0，没有可打印的元素。\n"); // 说明数组当前没有可遍历的元素。
        return;                                                // 结束函数，不进入数组遍历循环。
    } // 结束长度检查分支。

    printf("数组元素：");              // 先输出提示文字，随后输出数组中的各个元素。
    for (int i = 0; i < length; i++) { // 从下标 0 开始，每次加 1，直到 i 等于 length 时停止。
        printf("%d", arr[i]); // 读取下标为 i 的整数元素并输出；arr[i] 等价于通过指针访问对应元素。
        if (i < length - 1) { // 如果当前元素不是最后一个元素，就需要在后面输出分隔符。
            printf(", ");     // 在相邻元素之间输出逗号和空格，使结果更易阅读。
        } // 结束分隔符判断。
    } // 结束数组遍历循环。
    printf("\n"); // 所有元素输出完成后换行，让下一次输出从新的一行开始。
} // 结束 print_array() 函数定义。

int main(void) {     // 主函数是程序运行的入口；void 表示这里不接收命令行参数。
    int number = 42; // 定义整数变量 number，并初始化为 42，后面让指针指向它。
    int *p = NULL;   // 定义指向 int 的指针 p，并初始化为空指针；此时不能使用 *p 读取整数。
    printf("一、指针初始化演示\n");              // 输出第一部分标题。
    printf("p 初始化为 NULL，此时不解引用。\n"); // 强调空指针只是表示当前没有可用目标地址。

    p = &number; // 使用取地址符 & 获取 number 的地址，并把这个有效地址存入 p。
    printf("p 现在保存 number 的地址。\n"); // 说明 p 已经指向一个真实存在的整数变量。
    printf("number = %d\n", number);        // 使用 %d 输出 number 中保存的整数值。
    printf("*p = %d\n", *p); // 使用解引用运算符 * 访问 p 指向的对象，因此这里输出 42。

    int numbers[] = {10, 20, 30, 40}; // 定义含有 4 个整数的数组，并用 10、20、30、40 初始化。
// 声明并初始化变量；`=` 是赋值运算符，用右侧表达式的值设置左侧变量，而不是比较两个值。
    int length =
        (int)(sizeof(numbers) /
              sizeof(
                  numbers
                      [0])); // 在数组仍是完整数组的这里，用总字节数除以单个元素字节数得到元素个数。
    printf("\n二、数组参数与长度演示\n");                 // 输出第二部分标题。
    printf("调用函数前计算得到的数组长度：%d\n", length); // 展示计算出的元素个数，当前应为 4。
    print_array(numbers, length); // 传入数组首元素地址和元素个数，让函数知道应该读取多少个元素。
    print_array(numbers, 0);      // 测试长度为 0 的边界情况；函数应提示没有可打印元素。
    print_array(NULL, 3);         // 测试空指针防护；函数应报出提示后返回，而不会访问数组元素。

    return 0; // 向操作系统返回 0，通常表示程序正常结束。
} // 结束 main() 函数定义。
