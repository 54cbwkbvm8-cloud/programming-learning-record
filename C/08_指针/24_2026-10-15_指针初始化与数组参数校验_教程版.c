#include <stdio.h>


// --------------------------------------------------------------------
// 第二部分：打印数组的函数（带参数检查）
// --------------------------------------------------------------------
// （这个函数头被拆成了两行写，意思不变。）
// 参数 const int arr[] 是"数组参数"：实际传进来的是第一个元素的地址（等价于 const int *arr）；
// const 表示函数里只读不改。length 是元素个数：数组传进函数后，函数不知道有多长，要另外传。
// 为什么要检查参数？传进来的指针可能是空的，长度也可能是 0 或负数，不检查就访问，程序会崩溃。
void print_array(const int arr[],
                 int length) {
    // 检查 1：数组指针是不是 NULL（空指针 = 没有指向任何数据）。== 是判断相等。
    if (arr == NULL) {
        printf("错误：数组指针为空，不能访问数组。\n");

        // return; 用在 void 函数里，表示"提前结束这个函数"。
        // 这是和 23 号文件的关键区别：那里缺少这个 return，指针为空时还会继续往下访问，导致崩溃。
        // 有了 return，指针为空时函数到这里就结束了，后面不会再访问 arr，程序不会出错。
        return;
    }

    // 检查 2：长度必须大于 0。<= 读作"小于或等于"。
    if (length <= 0) {
        printf("数组长度为 0 或小于 0，没有可打印的元素。\n");
        return;
    }

    printf("数组元素：");

    // i 从 0 数到 length - 1，走遍数组。arr[i] 是数组的第 i 个元素（下标从 0 开始）。
    for (int i = 0; i < length; i++) {
        printf("%d", arr[i]);

        // 最后一个元素后面不需要分隔符，所以只有"不是最后一个元素"时才输出逗号和空格。
        if (i < length - 1) {
            printf(", ");
        }
    }
    printf("\n");
}


