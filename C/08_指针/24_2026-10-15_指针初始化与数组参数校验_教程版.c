int main(void) {
    int number = 42;

    // int *p 表示 p 是"指向 int 的指针"，专门存放地址。声明时还不知道指向哪里，就先设成 NULL，
    // 避免它里面是随机的地址（"野指针"）。指向 NULL 的指针不能解引用（不能写 *p）。
    int *p = NULL;
    printf("一、指针初始化演示\n");
    printf("p 初始化为 NULL，此时不解引用。\n");

    // 让 p 指向 number：&number 是 number 的地址（& 叫取地址符）。
    p = &number;
    printf("p 现在保存 number 的地址。\n");
    printf("number = %d\n", number);

    // *p 叫"解引用"：取出 p 指向的变量的值。p 指向 number，所以 *p 是 42。
    printf("*p = %d\n", *p);

    // 数组，方括号里不写大小，由大括号里的数据个数决定，这里是 4 个元素。
    int numbers[] = {10, 20, 30, 40};

    // 求元素个数：sizeof(numbers) 是整个数组占的字节数（4 个 int × 4 字节 = 16），
    // sizeof(numbers[0]) 是一个元素的字节数（4），16 ÷ 4 得 4。外面的 (int) 把结果转成 int。
    // 下面这个表达式被排版拆成了好几行，其实就是一句话。
    int length =
        (int)(sizeof(numbers) /
              sizeof(
                  numbers
                      [0]));
    printf("\n二、数组参数与长度演示\n");
    printf("调用函数前计算得到的数组长度：%d\n", length);

    // 测试 1：正常调用，传数组名和真实长度，会输出 10, 20, 30, 40。
    print_array(numbers, length);

    // 测试 2：长度传 0，函数提示"长度为 0 或小于 0"，然后返回。
    print_array(numbers, 0);

    // 测试 3：数组指针传 NULL，函数提示"数组指针为空"，然后返回，不会崩溃。
    print_array(NULL, 3);

    // return 0：结束 main，把 0 交给系统，表示"程序正常结束"。
    return 0;
}

