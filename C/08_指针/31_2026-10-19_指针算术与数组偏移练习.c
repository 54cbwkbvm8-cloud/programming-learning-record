// --------------------------------------------------------------------
// 第一部分：引入"工具箱"
// --------------------------------------------------------------------
// <stdio.h> 是"标准输入输出"工具箱，printf 在里面。
#include <stdio.h>


// --------------------------------------------------------------------
// 第二部分：main 函数 —— 程序从这里开始
// --------------------------------------------------------------------
int main(void) {

    // 数组：5 个 int 格子，下标 0 到 4，大括号里依次给每个元素赋初值。
    int a[5] = {10, 20, 30, 40, 50};

    // --------------------------------------------------------------------
    // 第一组：数组 a 和指针 p
    // --------------------------------------------------------------------
    // 数组名 a 在表达式里代表"第一个元素的地址"（也就是 &a[0]）。
    // "地址 + 2"是按"元素个数"来移动的：a + 2 指向往后数第 2 个元素，也就是 a[2]。
    // 所以 p 指向 a[2]，*p 是 30。
    // 为什么加 2 不是加 2 个字节？C 会按指针指向的类型自动换算：int 占 4 字节，所以实际移动 8 个字节。
    // int *p 表示 p 是"指向 int 的指针"，专门存放地址。
    int *p = a + 2;

    // 先把原数组的内容显示出来，方便对照后面的结果。
    printf("原数组:{10,20,30,40,50}\n");

    // *p 叫"解引用"：取出 p 指向的值，是 30。
    printf("p = a + 2,p 指向 a[2],其值为 %d\n", *p);

    // p[0] 等价于 *(p + 0)，也就是 *p。下标运算 p[i] 的本质就是 *(p + i)，所以 p[0] 是 30。
    printf("p[0] = %d\n", p[0]);

    // p - 1 指向前一个元素 a[1]，*(p - 1) 就是 a[1]，值是 20。
    // 括号不能省：*(p - 1) 是"先移动再取值"；*p - 1 是"先取值 30 再减 1"，得到 29，意思完全不同。
    printf("*(p - 1) = %d\n", *(p - 1));

    // p + 1 指向后一个元素 a[3]，*(p + 1) 是 40。
    printf("*(p + 1) = %d\n", *(p + 1));

    // p[-1] 等价于 *(p - 1)，是 20。对指针（不是数组名）使用下标，下标可以是负数，表示"往前数"。
    // 前提：不能超出原数组的范围，否则就是越界访问。
    printf("p[-1] = %d\n", p[-1]);

    // 输出一个空行，把两组演示隔开。
    printf("\n");

    // --------------------------------------------------------------------
    // 第二组：换一个数组再做一遍
    // --------------------------------------------------------------------
    // 换一个有 4 个元素的数组，用同样的方法再检验一次理解。
    int b[4] = {3, 6, 9, 12};

    // q 指向 b[2]，值是 9。
    int *q = b + 2;
    printf("新数组:{3,6,9,12}\n");

    // 和第一组一一对应：*q 是 9；q[0] 是 9；*(q - 1) 是 6；*(q + 1) 是 12；q[-1] 是 6。
    // 注意：q + 1 已经是最后一个元素 b[3]，再往后 +1 就超出数组范围（越界），不能访问。
    printf("q = b + 2,q 指向 b[2],其值为 %d\n", *q);
    printf("q[0] = %d\n", q[0]);
    printf("*(q - 1) = %d\n", *(q - 1));
    printf("*(q + 1) = %d\n", *(q + 1));
    printf("q[-1] = %d\n", q[-1]);
    printf("\n");

    // return 0：结束 main，把 0 交给系统，表示"程序正常结束"。
    return 0;
}

