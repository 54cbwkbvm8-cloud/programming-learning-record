// --------------------------------------------------------------------
// 第三部分：函数定义 —— 求最大值
// --------------------------------------------------------------------
// 这里是 max 的完整代码。思路是"打擂台"：先假设第一个元素最大，再依次拿后面的元素去挑战。
int max(int a[], int n) {

    // 声明局部变量 max，初始值取数组的第一个元素 a[0]（数组下标从 0 开始）。
    // 变量名 max 和函数名 max 相同：在这个函数里，max 指的是这个局部变量（局部的优先），所以不会冲突。
    // 但这样容易看混，自己写代码时建议起不同的名字，比如 max_value。
    int max = a[0];

    // 从第 2 个元素（下标 1）开始比较，因为第 1 个已经当作最大值了。
    // 条件是 i < n 而不是 i <= n：n 个元素的下标是 0 到 n - 1，写 <= 会越界访问到数组外面。
    for (int i = 1; i < n; i++) {
        // a[i] 表示数组的第 i 个元素。如果它比当前最大值还大……
        if (a[i] > max) {
            // ……就更新最大值。
            max = a[i];
        }
    }

    // 循环结束后，max 里就是最大值，返回给调用者。
    // 例：数组是 12 5 30 8 25：max 先是 12；5 不比它大；30 比它大，变成 30；8、25 都不比 30 大；返回 30。
    return max;
}


// --------------------------------------------------------------------
// 第四部分：函数定义 —— 求最小值
// --------------------------------------------------------------------
// 和 max 对称：先假设第一个元素最小，遇到更小的就更新。同样把 min 当作局部变量名。
int min(int a[], int n) {
    int min = a[0];
    for (int i = 1; i < n; i++) {
        if (a[i] < min) {
            min = a[i];
        }
    }
    return min;
}


// --------------------------------------------------------------------
// 第五部分：函数定义 —— 求平均值
// --------------------------------------------------------------------
// 平均值 = 总和 ÷ 个数。返回类型是 float，因为平均数可能有小数。
float average(int a[], int n) {

    // 累加器，必须先设成 0。它和函数 sum 同名，在这里指的是局部变量。
    int sum = 0;

    // 累加要把每个元素都加上，所以下标从 0 开始，一直到 n - 1。
    for (int i = 0; i < n; i++) {
        // += 是"加上再赋值"：sum += a[i] 等价于 sum = sum + a[i]。
        sum += a[i];
    }

    // (float)sum 叫"强制类型转换"：把整数 sum 临时当作 float 来用。
    // 为什么要转换？两个整数相除，结果还是整数，小数部分会被丢掉。例：82 / 5 得到 16，而不是 16.4。
    // 先把 sum 转成小数，再除以 n，才能得到带小数的结果。
    return (float)sum / n;
}


// --------------------------------------------------------------------
// 第六部分：函数定义 —— 求总和
// --------------------------------------------------------------------
// 返回数组所有元素的和，累加过程和上面 average 里的一样。
int sum(int a[], int n) {
    int sum = 0;
    for (int i = 0; i < n; i++) {
        sum += a[i];
    }
    return sum;
}


