// --------------------------------------------------------------------
// 第一部分：引入"工具箱"
// --------------------------------------------------------------------
// <stdio.h> 是"标准输入输出"工具箱：printf（输出）和 scanf（输入）都在里面。
#include <stdio.h>


// --------------------------------------------------------------------
// 第二部分：功能 1 —— 求两个整数中较大的
// --------------------------------------------------------------------
// 函数 = 一段可以反复使用的"小程序"，有名字、有输入、有输出。
// 函数头 int max(int a, int b) 的读法：
//   int          ：返回值类型，函数执行完会交还一个整数；
//   max          ：函数名；
//   int a, int b ：参数，调用时要传入两个整数，在函数里分别叫 a 和 b。
// 为什么要写成函数？"比较大小"这段逻辑后面要用很多次，写一次，到处调用，不用重复写。
int max(int a, int b) {

    // 比较 a 和 b。
    if (a > b) {
        // return 的意思是"结束这个函数，并把后面的值交还给调用它的地方"。a 更大，就把 a 交出去。
        return a;

    // 否则（b 更大，或者两数相等）交出 b。两数相等时，交出哪个结果都一样。
    } else {
        return b;
    }
}


// --------------------------------------------------------------------
// 第三部分：功能 2 —— 判断是不是偶数
// --------------------------------------------------------------------
// 返回值约定：是偶数返回 1，不是返回 0。
// C 语言习惯用 1 表示"真 / 是"，0 表示"假 / 否"，这样函数的结果可以直接拿去做 if 判断。
int isEven(int number) {

    // % 是取余：number 除以 2 余 0，就是偶数。
    if (number % 2 == 0) {
        return 1;   // 1 表示"是偶数"
    } else {
        return 0;   // 0 表示"不是偶数"
    }
}


// --------------------------------------------------------------------
// 第四部分：功能 3 —— 求平方
// --------------------------------------------------------------------
// 函数体很短，可以整个写在一行：return number * number 就是返回 number 乘以自己。
// 例：square(12) 得到 144。
int square(int number) { return number * number; }


// --------------------------------------------------------------------
// 第五部分：功能 4 —— 求三个整数中最大的
// --------------------------------------------------------------------
// 一个函数里可以调用另一个函数：这里直接借用上面的 max，不用重新写比较逻辑。
int max3(int a, int b, int c) {

    // 先用 max(a, b) 求出 a、b 中较大的，再和 c 比。
    if (max(a, b) > c) {
        // a、b 中较大的比 c 还大，它就是三个数里的最大值。
        // 例：a 是 3，b 是 15，c 是 9：max(3, 15) 是 15，15 > 9 成立，返回 15。
        return max(a, b);
    } else {
        return c;   // 否则 c 最大（或和它一样大）
    }
}


// --------------------------------------------------------------------
// 第六部分：main 函数 —— 程序从这里开始
// --------------------------------------------------------------------
// 程序从 main 开始，从上往下一行一行执行。
