// --------------------------------------------------------------------
// 返回约定：偶数返回 1，奇数返回 0。C 语言习惯用 1 表示"真 / 是"，0 表示"假 / 否"。
int is_even(int a) {

    // % 是取余：a 除以 2 余 0，就是偶数。例：9 % 2 是 1，所以 9 不是偶数。
    if (a % 2 == 0) {
        return 1;
    } else {
        return 0;
    }
}


