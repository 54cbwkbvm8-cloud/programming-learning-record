#include <stdio.h>
// 调用 `max()` 完成相应操作；括号中的表达式是传给函数的实参，具体效果由该函数定义决定。
int max(int a, int b);
// 调用 `square()` 完成相应操作；括号中的表达式是传给函数的实参，具体效果由该函数定义决定。
int square(int a);
// 调用 `is_even()` 完成相应操作；括号中的表达式是传给函数的实参，具体效果由该函数定义决定。
int is_even(int a);
// 定义函数 max；参数接收调用方传入的数据，函数体完成操作，返回语句（如有）把结果交还调用者。
int max(int a, int b) {
// 判断条件 `(a > b)` 是否成立；条件为真时执行对应分支，否则跳过或转入其他分支。
    if (a > b) {
// 结束当前函数调用，并把表达式 `a` 的结果返回给调用者。
        return a;
// 处理前面条件均不成立时的情况。
    } else {
// 结束当前函数调用，并把表达式 `b` 的结果返回给调用者。
        return b;
    }
}
// 这里声明函数或带类型的表达式；结合函数体与调用处确认参数和返回值的用途。
int square(int a) { return a * a; }
// 定义函数 is_even；参数接收调用方传入的数据，函数体完成操作，返回语句（如有）把结果交还调用者。
int is_even(int a) {
// 判断条件 `(a % 2 == 0)` 是否成立；条件为真时执行对应分支，否则跳过或转入其他分支。
    if (a % 2 == 0) {
// 结束当前函数调用，并把表达式 `1` 的结果返回给调用者。
        return 1;
// 处理前面条件均不成立时的情况。
    } else {
// 结束当前函数调用，并把表达式 `0` 的结果返回给调用者。
        return 0;
    }
}
// 定义函数 main；参数接收调用方传入的数据，函数体完成操作，返回语句（如有）把结果交还调用者。
int main(void) {
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("请输入a和b的值：");
// 声明变量并确定其数据类型；未初始化的局部变量不能直接当作已知值使用。
    int a, b;
// 从标准输入读取数据；检查读取结果和输入范围，避免把无效输入当作有效数据继续处理。
    scanf("%d %d", &a, &b);
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("最大值为：%d\n", max(a, b));
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("a的平方为：%d\n", square(a));
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("a是否为偶数：%d  (1为偶数，0为奇数)\n", is_even(a));
// 结束当前函数调用，并把表达式 `0` 的结果返回给调用者。
    return 0;
}
