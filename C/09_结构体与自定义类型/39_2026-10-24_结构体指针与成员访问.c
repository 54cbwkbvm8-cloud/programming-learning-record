// --------------------------------------------------------------------
// 第一部分：引入"工具箱"和宏定义
// --------------------------------------------------------------------
// <stdio.h> 是"标准输入输出"工具箱，printf 在里面。
#include <stdio.h>

// #define 叫"宏定义"：编译之前，程序里所有的 NAME_LENGTH 都会被替换成 50（行末不写分号）。
// 这样名字长度要修改时，只改这一处就行。
#define NAME_LENGTH 50


// --------------------------------------------------------------------
// 第二部分：定义结构体类型 Student
// --------------------------------------------------------------------
// struct { ... } 把学号、姓名、成绩"打包"成一个整体；typedef ... Student; 给它起一个类型名 Student，
// 以后直接写 Student 就行，不用每次都写 struct。
typedef struct {
    int id;
    char name[NAME_LENGTH];
    float score;
} Student;


// --------------------------------------------------------------------
// 第三部分：通过指针修改成绩的函数
// --------------------------------------------------------------------
// 参数 Student *p：p 是"指向 Student 的指针"，接收的是结构体变量的地址。参数 new_score 是新的成绩。
// 函数体只有一句，所以写在一行里：p->score = new_score;
// 箭头 -> 叫"通过指针访问成员"：p->score 的意思是"p 指向的那个结构体里的 score 成员"。
// 因为传进来的是地址，所以这里改的是 main 里的原结构体，不是复制品。
// 对比：如果参数写成 Student（整个结构体）而不是 Student *，函数改的只是复制品，main 里的不会变。
void change_score(Student *p, float new_score) { p->score = new_score; }


// --------------------------------------------------------------------
// 第四部分：main 函数 —— 程序从这里开始
// --------------------------------------------------------------------
int main(void) {

    // 创建结构体变量 s，用大括号按成员的顺序赋初值：id 是 1001，name 是 "ZhangSan"，score 是 80.0。
    // 80.0f 末尾的 f 表示这是 float 类型的小数。
    Student s = {1001, "ZhangSan", 80.0f};

    // Student *p：p 是"指向 Student 的指针"。&s 是 s 的地址（& 叫取地址符）。
    // 所以 p 指向 s，通过 p 就能找到并修改 s。
    Student *p = &s;

    // 准备好要改成的新成绩。
    float new_score = 95.5f;

    // --------------------------------------------------------------------
    // 第五部分：查看指针保存的地址
    // --------------------------------------------------------------------
    printf("=====结构体指针与->运算符=====\n");

    // %p 是输出"内存地址"的占位符。
    // (void *) 是强制类型转换，把地址转成通用指针类型 void *，这是 printf 的 %p 要求的标准写法。
    // &s 是变量 s 的地址。
    printf("结构体变量s的地址：%p\n", (void *)&s);

    // 输出 p 里保存的地址：应该和上一行完全相同，因为 p 指向 s。
    printf("指针p保存的地址：%p\n", (void *)p);

    // 比较 p 保存的地址和 s 的地址是否相等（== 判断相等）。相等就说明 p 确实指向 s。
    if (p == &s) {
        printf("检查结果：p指向s。\n");
    }

    // --------------------------------------------------------------------
    // 第六部分：三种访问成员的写法
    // --------------------------------------------------------------------
    printf("\n-----三种成员访问写法-----\n");

    // s 是结构体变量本身，用点 . 访问成员：s.score。
    printf("s.score = %.2f\n", s.score);

    // p 是指针，用箭头 -> 访问成员：p->score。-> 是"先通过指针找到结构体，再取成员"的简写。
    printf("p->score = %.2f\n", p->score);

    // (*p) 先"解引用"，得到 p 指向的整个结构体 s，再用点 . 取成员。
    // 括号必须写：点 . 的优先级比 * 高，写成 *p.score 会被理解成 *(p.score)，是错的。
    // 三种写法结果完全一样，都是 80.00。实际写代码时，通过指针访问成员几乎都写 ->，最简洁。
    printf("(*p).score = %.2f\n", (*p).score);

    // --------------------------------------------------------------------
    // 第七部分：通过指针修改成绩
    // --------------------------------------------------------------------
    printf("\n-----通过指针修改成绩-----\n");
    printf("调用函数前，s.score = %.2f\n", s.score);

    // 调用函数：把指针 p（也就是 s 的地址）和新成绩 95.5 传进去。
    // 函数里通过 p->score = new_score 直接改了 s 的成绩。
    change_score(p, new_score);

    // s 自己的成绩已经变成 95.50，说明函数确实修改了原来的结构体。
    printf("调用函数后，s.score = %.2f\n", s.score);

    // 通过指针看到的也是 95.50：p 和 s 指向的是同一个结构体。
    printf("调用函数后，p->score = %.2f\n", p->score);

    // return 0：结束 main，把 0 交给系统，表示"程序正常结束"。
    return 0;
}

