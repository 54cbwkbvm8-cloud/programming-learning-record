#include <stdio.h>
// 该宏用于集中定义常量或短表达式，修改时需确认所有使用位置。
#define NAME_LENGTH 50
// 定义结构体 该结构体，把相关字段组合成一个自定义数据类型；结尾的 typedef 别名便于后续声明变量。
typedef struct {
// 声明变量并确定其数据类型；未初始化的局部变量不能直接当作已知值使用。
    int id;
// 声明数组并为元素分配连续空间；下标从 0 开始，有效范围必须小于数组长度。
    char name[NAME_LENGTH];
// 声明变量并确定其数据类型；未初始化的局部变量不能直接当作已知值使用。
    float score;
} Student;
// 通过结构体指针访问并更新指定成员；`p->field` 等价于 `(*p).field`，前提是 p 指向有效结构体。
void change_score(Student *p, float new_score) { p->score = new_score; }
// 定义函数 main；参数接收调用方传入的数据，函数体完成操作，返回语句（如有）把结果交还调用者。
int main(void) {
// 声明并初始化变量；`=` 是赋值运算符，用右侧表达式的值设置左侧变量，而不是比较两个值。
    Student s = {1001, "ZhangSan", 80.0f};
// 声明或初始化指针变量；指针保存地址，使用前必须确认它指向有效对象，不能解引用空指针。
    Student *p = &s;
// 声明并初始化变量；`=` 是赋值运算符，用右侧表达式的值设置左侧变量，而不是比较两个值。
    float new_score = 95.5f;
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("=====结构体指针与->运算符=====\n");
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("结构体变量s的地址：%p\n", (void *)&s);
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("指针p保存的地址：%p\n", (void *)p);
// 判断条件 `(p == &s)` 是否成立；条件为真时执行对应分支，否则跳过或转入其他分支。
    if (p == &s) {
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
        printf("检查结果：p指向s。\n");
    }
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("\n-----三种成员访问写法-----\n");
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("s.score = %.2f\n", s.score);
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("p->score = %.2f\n", p->score);
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("(*p).score = %.2f\n", (*p).score);
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("\n-----通过指针修改成绩-----\n");
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("调用函数前，s.score = %.2f\n", s.score);
// 调用 `change_score()` 完成相应操作；括号中的表达式是传给函数的实参，具体效果由该函数定义决定。
    change_score(p, new_score);
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("调用函数后，s.score = %.2f\n", s.score);
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("调用函数后，p->score = %.2f\n", p->score);
// 结束当前函数调用，并把表达式 `0` 的结果返回给调用者。
    return 0;
}
