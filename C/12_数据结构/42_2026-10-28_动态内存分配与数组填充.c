// --------------------------------------------------------------------
// 第一部分：引入"工具箱"
// --------------------------------------------------------------------
// <stdint.h> 提供 SIZE_MAX（size_t 类型能表示的最大数），下面用它检查数字会不会溢出。
#include <stdint.h>

// <stdio.h> 是"标准输入输出"工具箱：printf、scanf、fprintf、perror 都在里面。
#include <stdio.h>

// <stdlib.h> 里有 malloc（申请内存）和 free（释放内存）。
#include <stdlib.h>


// --------------------------------------------------------------------
// 第二部分：main 函数 —— 程序从这里开始
// --------------------------------------------------------------------
int main(void) {

    // size_t 是专门表示"个数、大小"的无符号整数类型（不会是负数），申请内存的个数用它最合适。
    // n 就是用户要的整数个数。读它和输出它都要用 %zu。
    size_t n;

    // --------------------------------------------------------------------
    // 第三部分：输入并检查 n
    // --------------------------------------------------------------------
    printf("请输入要分配的整数个数n：");

    // %zu 是读取 size_t 的格式符；&n 是 n 的地址（& 取地址符），scanf 把读到的数放进去。
    // scanf 返回成功读到的个数，成功应该是 1；!= 1 表示没读成功（比如输入了字母）。
    // || 读作"或者"：读失败，或者 n 是 0，都是无效输入（申请 0 个整数没有意义）。
    // || 有"短路"特点：左边成立，右边就不会再算，所以读失败时不会去用没有赋值的 n。
    if (scanf("%zu", &n) != 1 || n == 0) {
        // fprintf(stderr, ...) 和 printf 类似，但是输出到"标准错误"（stderr）：专门用来输出错误信息。
        // 正常信息走 stdout，错误信息走 stderr，方便把两者分开处理。
        fprintf(stderr, "输入无效：n必须是大于0的整数。\n");

        // return 1：提前结束程序，把 1 交给系统，表示"出错了"（0 表示正常）。
        return 1;
    }

    // 防止溢出：下面要计算 n * sizeof(int)（总共需要多少字节）。
    // 如果 n 太大，乘出来的结果会超过 size_t 的最大值，数字"绕圈"变成一个很小的数，
    // 导致只申请到很少的内存，却当成很多来用，造成越界。
    // 所以先检查：n 不能超过 SIZE_MAX / sizeof(int)（用除法来检查，本身不会溢出）。
    // sizeof(int) 是一个 int 占的字节数，通常是 4。
    if (n > SIZE_MAX / sizeof(int)) {
        fprintf(stderr, "请求的内存n过大，所需内存的字节数会溢出，无法分配。\n");
        return 1;
    }

    // --------------------------------------------------------------------
    // 第四部分：申请内存
    // --------------------------------------------------------------------
    // malloc(字节数)：在"堆"上向系统申请一块连续的内存，返回这块内存的起始地址；失败返回 NULL。
    // n * sizeof(int)：要放 n 个 int，每个 sizeof(int) 个字节，总共 n × sizeof(int) 个字节。
    // int *a：a 是"指向 int 的指针"，保存这块内存的起点。之后可以像数组一样用 a[0]、a[1]……
    // 为什么用 malloc 而不是普通数组？普通数组的大小要在写代码时就定死；
    // malloc 可以等用户输入 n 之后再决定申请多大，更灵活。
    // 注意：malloc 申请到的内存里是随机的旧数据，用之前要先赋值。
    int *a = malloc(n * sizeof(int));

    // 申请可能失败（内存不足），这时 malloc 返回 NULL。必须检查：不检查就去用，程序会崩溃。
    if (a == NULL) {
        // perror 会输出"malloc: 系统给出的错误原因"，比自己写一句固定的话更能说明问题。
        perror("malloc");
        return 1;
    }

    // --------------------------------------------------------------------
    // 第五部分：填充并输出
    // --------------------------------------------------------------------
    // i 从 0 数到 n - 1，走遍这块内存里的每个 int。i 也用 size_t，和 n 的类型一致。
    for (size_t i = 0; i < n; i++) {
        // a[i] 是第 i 个 int（下标从 0 开始，和普通数组的用法一样）。
        // 第 i 个位置放 (i + 1) 的平方：i 是 0 放 1，i 是 1 放 4，i 是 2 放 9……
        // (int) 是强制类型转换：i 是 size_t，算出来也是 size_t，要转回 int 才能存进 int 的格子。
        a[i] = (int)((i + 1) * (i + 1));
    }

    // 再走一遍，把每个元素输出。
    for (size_t i = 0; i < n; i++) {
        // %zu 输出下标 i（size_t 类型），%d 输出元素的值。末尾的空格让每一项之间隔开。
        printf("a[%zu] = %d ", i, a[i]);
    }

    // 所有元素输出完后，换一行。
    printf("\n");

    // --------------------------------------------------------------------
    // 第六部分：释放内存
    // --------------------------------------------------------------------
    // free(a)：把 malloc 借来的内存还给系统。每一次 malloc，都要有一次对应的 free。
    // 不还的话就是"内存泄漏"。
    free(a);

    // free 之后，a 里保存的地址已经无效了（叫"悬空指针"）。把它设成 NULL，防止后面不小心再使用它。
    a = NULL;

    // return 0：结束 main，把 0 交给系统，表示"程序正常结束"。
    return 0;
}

