/*
 * 文件用途：本文件围绕“单链表节点连接与遍历”展开。
 * 核心知识点：指针、结构体、动态内存、链表、循环、分支判断、函数。
 * 基本流程：根据代码中的输入或初始数据，按条件、循环和函数调用完成处理，再输出结果。
 * 输入：本文件使用预设数据、初始化值或函数参数。输出：通过控制台打印结果。
 * 阅读提醒：指针和动态内存相关操作必须确认地址有效，并注意释放已申请的内存。
 * 依赖头文件：stdio.h, stdlib.h。
 */
#include <stdio.h>
#include <stdlib.h>
// 定义结构体 Node，把相关字段组合成一个自定义数据类型；结尾的 typedef 别名便于后续声明变量。
typedef struct Node {
// 定义整数字段 `data`，用于保存当前节点或记录中的数值。
    int data;
// 定义指针成员 `next`，专门保存下一个同类节点的地址；最后一个节点通常把 next 设为 NULL。
    struct Node *next;
} Node;
// 定义函数 create_node；参数接收调用方传入的数据，函数体完成操作，返回语句（如有）把结果交还调用者。
Node *create_node(int value) {
// 调用 `malloc()` 按指定字节数申请动态内存，并把返回地址保存到指针中；申请失败会返回 NULL，因此后续必须检查。
    Node *new_node = (Node *)malloc(sizeof(Node));
// 判断条件 `(new_node == NULL)` 是否成立；条件为真时执行对应分支，否则跳过或转入其他分支。
    if (new_node == NULL) {
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
        printf("错误：内存申请失败，无法创建节点。\n");
// 结束当前函数调用，并把表达式 `NULL` 的结果返回给调用者。
        return NULL;
    }
// 通过结构体指针访问并更新指定成员；`p->field` 等价于 `(*p).field`，前提是 p 指向有效结构体。
    new_node->data = value;
// 把当前节点的 `next` 设为 NULL，表示它后面没有下一个节点，链表到这里结束。
    new_node->next = NULL;
// 结束当前函数调用，并把表达式 `new_node` 的结果返回给调用者。
    return new_node;
}
// 定义函数 main；参数接收调用方传入的数据，函数体完成操作，返回语句（如有）把结果交还调用者。
int main(void) {
// 声明或初始化指针变量；指针保存地址，使用前必须确认它指向有效对象，不能解引用空指针。
    Node *node1 = create_node(10);
// 声明或初始化指针变量；指针保存地址，使用前必须确认它指向有效对象，不能解引用空指针。
    Node *node2 = create_node(20);
// 声明或初始化指针变量；指针保存地址，使用前必须确认它指向有效对象，不能解引用空指针。
    Node *node3 = create_node(30);
// 判断条件 `(node1 == NULL || node2 == NULL || node3 == NULL)` 是否成立；条件为真时执行对应分支，否则跳过或转入其他分支。
    if (node1 == NULL || node2 == NULL || node3 == NULL) {
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
        printf("错误：至少有一个节点创建失败，程序结束。\n");
// 释放此前动态申请的内存；释放后不要再通过旧指针访问这块内存。
        free(node1);
// 释放此前动态申请的内存；释放后不要再通过旧指针访问这块内存。
        free(node2);
// 释放此前动态申请的内存；释放后不要再通过旧指针访问这块内存。
        free(node3);
// 结束当前函数调用，并把表达式 `1` 的结果返回给调用者。
        return 1;
    }
// 把右侧节点的地址写入当前节点的 `next` 指针，从而建立或修改两个节点之间的连接。
    node1->next = node2;
// 把右侧节点的地址写入当前节点的 `next` 指针，从而建立或修改两个节点之间的连接。
    node2->next = node3;
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("=====三个节点的内容与连接关系=====\n");
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("node1：地址%p，data = %d，next = %p\n", (void *)node1, node1->data,
           (void *)node1->next);
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("node2：地址%p，data = %d，next = %p\n", (void *)node2, node2->data,
           (void *)node2->next);
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("node3：地址%p，data = %d，next = %p\n", (void *)node3, node3->data,
           (void *)node3->next);
// 判断条件 `(node3->next == NULL)` 是否成立；条件为真时执行对应分支，否则跳过或转入其他分支。
    if (node3->next == NULL) {
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
        printf("node3->next = NULL，表示链表在node3这里结束。\n");
    }
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("通过node1->next->next->data访问第三节点：%d\n", node1->next->next->data);
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("\n=====从节点头出发，沿着next依次遍历=====\n");
// 声明或初始化指针变量；指针保存地址，使用前必须确认它指向有效对象，不能解引用空指针。
    Node *current = node1;
// 声明并初始化变量；`=` 是赋值运算符，用右侧表达式的值设置左侧变量，而不是比较两个值。
    int position = 1;
// 只要 while 后的条件成立，就重复执行循环体；检查循环体是否会推进相关变量，确保条件最终能变为假。
    while (current != NULL) {
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
        printf("第%d个节点：data = %d\n", position, current->data);
// 把 `current` 更新为当前节点的下一个节点，沿着 next 指针继续遍历链表；到达 NULL 时遍历结束。
        current = current->next;
// 将计数/下标变量加 1，通常用于记录已处理的元素数量或推进下一轮循环。
        position++;
    }
// 把右侧变量当前保存的值复制到左侧变量；如果右侧是指针，复制的是地址而不是对象内容。
    current = node1;
// 只要 while 后的条件成立，就重复执行循环体；检查循环体是否会推进相关变量，确保条件最终能变为假。
    while (current != NULL) {
// 声明或初始化指针变量；指针保存地址，使用前必须确认它指向有效对象，不能解引用空指针。
        Node *next_node = current->next;
// 释放此前动态申请的内存；释放后不要再通过旧指针访问这块内存。
        free(current);
// 把右侧变量当前保存的值复制到左侧变量；如果右侧是指针，复制的是地址而不是对象内容。
        current = next_node;
    }
// 结束当前函数调用，并把表达式 `0` 的结果返回给调用者。
    return 0;
}
