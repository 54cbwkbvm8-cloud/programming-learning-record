// 作用：输入一行字符串，统计其中英文字母和数字的个数，
//       并把字符串里的小写字母全部转换成大写字母。
//
// 怎么运行（在 Mac 终端里，先 cd 到这个文件所在的文件夹）：
//   编译：clang -Wall -Wextra -o demo "20_2026-10-14_字符串统计与大小写转换练习.c"
