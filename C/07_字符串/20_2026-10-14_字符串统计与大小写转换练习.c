// --------------------------------------------------------------------
// 第一部分：引入"工具箱"
// --------------------------------------------------------------------
// <stdio.h> 是"标准输入输出"工具箱：printf（输出）、fgets（读一行）都在里面。
#include <stdio.h>

// <string.h> 是"字符串工具箱"：下面用到的 strlen（求长度）、strcspn（查找字符位置）都在里面。
#include <string.h>


// --------------------------------------------------------------------
// 第二部分：main 函数 —— 程序从这里开始
// --------------------------------------------------------------------
int main(void) {

    // C 语言的字符串就是"以 '\0'（空字符）结尾的 char 数组"。
    // char str[200] 能放 200 个字节，最多存 199 个字符，留 1 个格子给结束标志 '\0'。
    char str[200];

    // 两个计数器：letter_count 数英文字母，digit_count 数数字。计数器必须从 0 开始。
    int letter_count = 0;
    int digit_count = 0;

    // i 是循环的下标；len 存字符串的长度。
    int i;
    int len = 0;
    printf("请输入第一个字符串：");

    // fgets(放在哪里, 最多读多少, 从哪里读)：读一整行文字，可以带空格。
    // sizeof(str) 是数组的总字节数（200），fgets 最多读 199 个字符并补上 '\0'，不会越界。
    // fgets 读失败（或输入已经结束）时返回 NULL，这时直接 return 1 提前结束程序（非 0 表示出错）。
    if (fgets(str, sizeof(str), stdin) == NULL) {
        return 1;
    }

    // 去掉 fgets 读进来的换行符。
    // strcspn(str, "\n")：求 str 里"第一个 '\n' 出现的下标"；如果没有 '\n'，就返回字符串的长度。
    // 再把这个位置改成 '\0'，字符串就在这里结束：有换行符就把它砍掉，没有就只是重写一遍结尾的 '\0'。
    // 例：输入 Hi 再按回车，str 里是 "Hi\n"，'\n' 的下标是 2，str[2] 变成 '\0'，得到 "Hi"。
    str[strcspn(str, "\n")] = '\0';

    // strlen 求字符串长度，它的类型是 size_t（无符号整数）。
    // (int) 是强制类型转换，转成 int 再存进 len，这样后面和 int 类型的 i 比较时不会有"有符号与无符号比较"的警告。
    len = (int)strlen(str);

    // 逐个字符处理：i 从 0 数到 len - 1，str[i] 就是字符串的第 i 个字符（下标从 0 开始）。
    for (i = 0; i < len; i++) {
        // 先把当前字符备份到 c 里，后面的判断都用 c。这样即使 str[i] 被改成了大写，c 仍然是原来的字符。
        // c 是循环体里的局部变量，每一轮都会重新创建。
        char c = str[i];

        // 判断是不是数字字符。字符在电脑里是用编号（ASCII 码）存的，'0' 到 '9' 的编号是连续的，
        // 所以"介于 '0' 和 '9' 之间"就是数字字符。
        // 单引号 '0' 表示"字符 0"，不是数字 0。&& 读作"并且"，两边都成立才成立。
        // 例：'7' 满足 >= '0' 且 <= '9'，是数字；'a' 不满足，不是数字。
        if (c >= '0' && c <= '9') {
            // ++ 是"自增"：digit_count++ 等价于 digit_count = digit_count + 1。
            digit_count++;
        }

        // 判断是不是小写字母。小写字母 'a' 到 'z' 的编号也是连续的。
        if (c >= 'a' && c <= 'z') {
            // 小写转大写：同一个字母，小写和大写的编号相差固定的数——'a' 是 97，'A' 是 65，差 32。
            // 所以 'a' - 'A' 就是这个固定的差（32）。小写字母减去它，就得到对应的大写字母。
            // 例：'h' 是 104，104 - 32 = 72，72 正好是 'H'。结果写回 str[i]，字符串里这一位就变成大写了。
            str[i] = c - ('a' - 'A');
        }

        // 判断是不是英文字母：是小写字母，或者是大写字母。|| 读作"或者"。
        // 两组条件各自用括号括起来，保证 && 先算、再用 || 连接。
        // 注意这里用的是备份 c（原来的字符），不是已经可能被改过的 str[i]，所以不管有没有转换，都能正确计数。
        if ((c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z')) {
            letter_count++;
        }
    }

    // %d 是整数占位符，输出 letter_count 的值。
    printf("英文字母的数量是：%d\n", letter_count);
    printf("数字的数量是：%d\n", digit_count);

    // %s 是字符串占位符。这时 str 里的小写字母已经全部变成大写了。
    printf("转换后的字符串：%s\n", str);

    // return 0：结束 main，把 0 交给系统，表示"程序正常结束"。
    return 0;
}

