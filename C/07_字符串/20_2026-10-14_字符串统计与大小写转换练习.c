/*
 * 文件用途：本文件围绕“字符串统计与大小写转换练习”展开。
 * 核心知识点：字符串、循环、分支判断、函数。
 * 基本流程：根据代码中的输入或初始数据，按条件、循环和函数调用完成处理，再输出结果。
 * 输入：从标准输入读取数据或由调用者传入参数。输出：通过控制台打印处理结果。
 * 阅读提醒：检查数组下标、字符串结束符和缓冲区容量，避免越界访问。
 * 依赖头文件：stdio.h, string.h。
 */
#include <stdio.h>
#include <string.h>
// 定义函数 main；参数接收调用方传入的数据，函数体完成操作，返回语句（如有）把结果交还调用者。
int main(void) {
// 声明数组并为元素分配连续空间；下标从 0 开始，有效范围必须小于数组长度。
    char str[200];
// 声明并初始化变量；`=` 是赋值运算符，用右侧表达式的值设置左侧变量，而不是比较两个值。
    int letter_count = 0;
// 声明并初始化变量；`=` 是赋值运算符，用右侧表达式的值设置左侧变量，而不是比较两个值。
    int digit_count = 0;
// 声明变量并确定其数据类型；未初始化的局部变量不能直接当作已知值使用。
    int i;
// 声明并初始化变量；`=` 是赋值运算符，用右侧表达式的值设置左侧变量，而不是比较两个值。
    int len = 0;
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("请输入第一个字符串：");
// 判断条件 `(fgets(str, sizeof(str), stdin) == NULL)` 是否成立；条件为真时执行对应分支，否则跳过或转入其他分支。
    if (fgets(str, sizeof(str), stdin) == NULL) {
// 结束当前函数调用，并把表达式 `1` 的结果返回给调用者。
        return 1;
    }
    str[strcspn(str, "\n")] = '\0';
// 调用 `strlen()` 完成相应操作；括号中的表达式是传给函数的实参，具体效果由该函数定义决定。
    len = (int)strlen(str);
// 循环按“初始化；条件判断；每轮更新”的顺序执行。先检查条件，再运行循环体，最后更新循环变量；注意边界是否会多执行或少执行一次。
    for (i = 0; i < len; i++) {
// 声明数组并为元素分配连续空间；下标从 0 开始，有效范围必须小于数组长度。
        char c = str[i];
// 判断条件 `(c >= 字符 && c <= 字符)` 是否成立；条件为真时执行对应分支，否则跳过或转入其他分支。
        if (c >= '0' && c <= '9') {
// 更新计数变量；`++` 每次加 1，`--` 每次减 1，注意更新发生的位置。
            digit_count++;
        }
// 判断条件 `(c >= 字符 && c <= 字符)` 是否成立；条件为真时执行对应分支，否则跳过或转入其他分支。
        if (c >= 'a' && c <= 'z') {
            str[i] = c - ('a' - 'A');
        }
// 判断条件 `((c >= 字符 && c <= 字符) || (c >= 字符 && c <= 字符))` 是否成立；条件为真时执行对应分支，否则跳过或转入其他分支。
        if ((c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z')) {
// 更新计数变量；`++` 每次加 1，`--` 每次减 1，注意更新发生的位置。
            letter_count++;
        }
    }
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("英文字母的数量是：%d\n", letter_count);
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("数字的数量是：%d\n", digit_count);
// 向标准输出打印提示或结果；格式字符串中的占位符必须与后续实参的类型匹配。
    printf("转换后的字符串：%s\n", str);
// 结束当前函数调用，并把表达式 `0` 的结果返回给调用者。
    return 0;
}
