// 作用：练习字符串的输入和常用函数：
//       fgets   ：读一整行文字（可以带空格）
//       strlen  ：求字符串长度；sizeof 求数组大小
//       strcpy  ：复制字符串
//       strncmp ：比较两个字符串，判断谁大谁小
//
// 怎么运行（在 Mac 终端里，先 cd 到这个文件所在的文件夹）：
//   编译：clang -Wall -Wextra -o demo "19_2026-10-13_字符串输入与常用函数练习.c"
//   运行：./demo
//   说明：编译 = 把人能看懂的 C 代码翻译成电脑能执行的程序。
//         -Wall -Wextra 的意思是"把所有可疑的地方都警告我"，
//         编译时出现警告，一定要弄明白原因，不要忽略。
// ====================================================================


// --------------------------------------------------------------------
// 第一部分：引入"工具箱"
// --------------------------------------------------------------------
// <stdio.h> 是"标准输入输出"工具箱：printf（输出）、fgets（读一行）都在里面。
#include <stdio.h>

// <string.h> 是"字符串工具箱"：strlen（求长度）、strcpy（复制）、strncmp（比较）都在里面。
#include <string.h>


// --------------------------------------------------------------------
// 第二部分：main 函数 —— 程序从这里开始
// --------------------------------------------------------------------
int main(void) {

    // C 语言没有专门的"字符串类型"。字符串就是"以 '\0'（空字符，编号 0）结尾的 char 数组"。
    // char str[100]：能放 100 个字节的字符数组，用来存第一行文字。
    // = {0} 表示把所有格子都初始化成 0（也就是全是 '\0'），相当于"空字符串"，避免里面是随机数据。
    // （这里的 { 和 0 被拆成了两行写，意思和 = {0} 完全一样。）
    char str[100] = {
        0};

    // copied 用来存复制出来的字符串，other 用来存第二行文字，都初始化成全 0。
    char copied[100] = {0};
    char other[100] = {0};

    // size_t 是专门用来表示"大小、长度"的整数类型（不会是负数）。
    // strlen 和 sizeof 的结果都是 size_t，所以 len 也用它。printf 输出 size_t 要用 %zu。
    size_t len = 0;

    // compare_result 存字符串比较的结果。
    int compare_result = 0;

    // 提示里写"最多 99 个字节"：数组一共 100 个格子，要留 1 个格子放结束标志 '\0'。
    printf("请输入第一行文字（最多 99 个字节）：");

    // fgets(放在哪里, 最多读多少, 从哪里读)：从输入里读一整行文字，可以包含空格。
    //   str         ：读到的文字放进 str；
    //   sizeof(str) ：sizeof 求数组占多少个字节，这里是 100；fgets 最多读 99 个字符并补上 '\0'，不会写出数组外面；
    //   stdin       ：标准输入，也就是键盘。
    // 为什么不用 scanf("%s")？scanf 读到空格就停，读不了带空格的句子；fgets 会一直读到换行为止。
    // fgets 读失败（或输入已经结束）时返回 NULL（表示"空、没有"），所以要先检查，失败就提前结束。
    // 注意：用户按下的回车（换行符 '\n'）也会被 fgets 读进来，放在字符串末尾，下面会把它去掉。
    if (fgets(str, sizeof(str), stdin) == NULL) {
        printf("读取失败\n");

        // return 1：提前结束 main，把 1 交给系统。按约定，0 表示正常结束，非 0 表示出错。
        return 1;
    }

    // strlen(str) 数出 str 里第一个 '\0' 之前有多少个字节（不含 '\0'）。
    // 例：读到的是 "Hi 你好\n"：H、i、空格各 1 个字节共 3 个，"你好"两个汉字共 6 个字节，换行符 1 个，所以是 10。
    len = strlen(str);

    // 去掉末尾的换行符。先判断 len > 0（字符串不是空的），再看最后一个字符 str[len - 1] 是不是 '\n'。
    // 为什么是 len - 1？下标从 0 开始，长度是 len 的字符串，最后一个字符的下标是 len - 1。
    // && 读作"并且"：左边不成立时，右边就不会再检查，所以不会去访问不存在的 str[-1]。
    if (len > 0 && str[len - 1] == '\n') {
        // 把 '\n' 改写成 '\0'（字符串结束标志），字符串就在这里结束，换行符被"砍掉"了。
        str[len - 1] = '\0';

        // 长度也跟着减 1。
        len--;
    }

    // 重新计算一次长度，保证 len 一定是最新、正确的值。
    len = strlen(str);

    // --------------------------------------------------------------------
    // 第三部分：查看字符串长度和数组长度
    // --------------------------------------------------------------------
    printf("\n-----第一行文字的结果-----\n");

    // %s 是字符串的占位符，会输出 str 里的内容（遇到 '\0' 就停止）。
    printf("你输入的内容是：%s\n", str);

    // %zu 是输出 size_t 类型的占位符。strlen 求的是"字符串当前有多长"。
    printf("你输入的内容字符串长度是：%zu\n", len);

    // sizeof(str) 求的是"数组一共有多大"，是 100，和里面存了什么无关。
    // 对比：strlen 看的是内容的长度，sizeof 看的是容器的大小。
    printf("你输入的数组长度是：%zu\n", sizeof(str));

    // 提示：strlen 数的是字节数，不一定等于汉字的个数。
    // 在 UTF-8 编码（Mac 默认使用）里，一个汉字占 3 个字节，所以"你好"的 strlen 是 6，不是 2。
    // 这条 printf 被拆成了两行写，意思不变。
    printf(
        "提示：strlen 统计的是字节数，不一定等于中文字符数\n");

    // --------------------------------------------------------------------
    // 第四部分：用 strcpy 复制字符串
    // --------------------------------------------------------------------
    // strcpy(目的地, 来源)：把来源字符串（连同结尾的 '\0'）复制到目的地。
    // 方向要记牢：第一个参数是"复制到哪里"，第二个才是"从哪里复制"，和 a = b 的方向一样。
    // 注意：目的地必须足够大，否则会写出数组外面（越界）。这里 copied 和 str 一样大，所以是安全的。
    strcpy(copied, str);

    printf("\n-----strcpy 复制后的结果-----\n");
    printf("原字符串：%s\n", str);
    printf("复制后的内容是：%s\n", copied);

    // strlen 也可以直接放在 printf 里使用。复制之后，copied 的长度应该和 str 一样。
    printf("复制后的字符串长度是：%zu\n", strlen(copied));
    printf("复制后的数组长度是：%zu\n", sizeof(copied));

    // --------------------------------------------------------------------
    // 第五部分：用 strncmp 比较两个字符串
    // --------------------------------------------------------------------
    printf("\n请输入第二行文字用于演示 strncmp：");

    // 和上面一样，读第二行文字，读失败就提前结束。（这个 if 的条件被拆成了两行写。）
    if (fgets(other, sizeof(other), stdin) ==
        NULL) {
        printf("输入错误\n");
        return 1;
    }

    // 求第二行的长度，为了下面判断末尾是不是换行符。
    len = strlen(other);

    // 同样去掉末尾的换行符，这样比较时就不会因为换行符而出现差异。
    if (len > 0 && other[len - 1] == '\n') {
        other[len - 1] = '\0';
    }

    // strncmp(a, b, n)：比较两个字符串的前 n 个字节。
    //   比较规则：从第一个字符开始，一个一个比较字符的编码，遇到第一个不同的字符就决定大小。
    //   返回值：0 表示相同；负数表示 a 比 b 小；正数表示 a 比 b 大。
    //   具体的数字是几，不同系统可能不一样，所以只能看"是负数、0 还是正数"，不要依赖具体数字。
    // 这里 n 取 sizeof(other)，也就是 100，比任何一行输入都长，所以相当于比较整个字符串。
    // 例："Hi 你好" 和 "Hip"：前两个字符 H、i 相同；第三个字符分别是空格（编码 32）和 p（编码 112），
    // 32 比 112 小，所以第一个字符串更小，结果是负数。
    compare_result =
        strncmp(str, other, sizeof(other));

    // --------------------------------------------------------------------
    // 第六部分：输出比较结果
    // --------------------------------------------------------------------
    printf("\n-----strncmp 比较后的结果-----\n");
    printf("第一行文字：%s\n", str);
    printf("第二行文字：%s\n", other);

    // %d 输出 int 类型的比较结果。
    printf("比较结果是：%d\n", compare_result);

    // 根据返回值分三种情况：等于 0 是相同；小于 0 是第一个更小；其余（大于 0）是第一个更大。
    if (compare_result == 0) {
        printf("两个字符串相同\n");
    } else if (compare_result < 0) {
        printf("第一个字符串小于第二个字符串\n");

    // 走到这里，说明比较结果大于 0。
    } else {
        printf("第一个字符串大于第二个字符串\n");
    }

    // return 0：结束 main，把 0 交给系统，表示"程序正常结束"。
    return 0;
}

