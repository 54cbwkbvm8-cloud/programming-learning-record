// --------------------------------------------------------------------
// 第一部分：引入"工具箱"
// --------------------------------------------------------------------
// <stdio.h> 是"标准输入输出"工具箱，printf（把内容显示在屏幕上）就放在里面。
#include <stdio.h>


// --------------------------------------------------------------------
// 第二部分：main 函数 —— 程序从这里开始
// --------------------------------------------------------------------
// 程序从 main 开始，从上往下一行一行执行。
// int 表示 main 结束时返回一个整数给系统，(void) 表示不接收参数。
int main(void) {

    // 声明变量的同时给它一个初始值：int a = 7 就是"造一个整数格子 a，同时把 7 放进去"。
    // 变量 = 内存里一个有名字的小格子，int 表示格子里只能放整数。
    int a = 7;
    int b = 2;

    // --------------------------------------------------------------------
    // 第一条：整数除法
    // --------------------------------------------------------------------
    // 每组输出都拆成三条 printf：第一条打印提示文字，第二条打印结果，第三条打印 \n 换行。
    // \n 表示"换行"，相当于按一下回车。
    printf("第一条输出：");

    // 整数除以整数，结果还是整数，小数部分直接丢掉（不是四舍五入）：7 / 2 是 3，不是 3.5。
    // %d 是整数的占位符，会被后面的值 a / b 替换，所以这里输出 3。
    printf("%d", a / b);
    printf("\n");

    // --------------------------------------------------------------------
    // 第二条：强制类型转换，得到真正的小数结果
    // --------------------------------------------------------------------
    printf("第二条输出：");

    // (double)a 叫"强制类型转换"：临时把 a 当成 double（双精度小数）来用，得到 7.0。
    // a 本身没有变，仍然是整数 7，只是这一次运算里把它当小数用。
    // 现在是"小数 / 整数"，C 会自动把 b 也当成小数，算出 7.0 / 2.0 = 3.5。
    // 注意：转换只作用在紧跟着的 a 上。如果写成 (double)(a / b)，会先算 7 / 2 得 3，再转成 3.0，结果就错了。
    // %f 按小数显示，默认保留 6 位小数，所以输出 3.500000。
    printf("%f", (double)a / b);
    printf("\n");

    // --------------------------------------------------------------------
    // 第三条：输出百分号
    // --------------------------------------------------------------------
    printf("第三条输出：");

    // 在 printf 里，% 是"格式符的开头"，有特殊含义。想真正显示一个百分号，要连写两个 %%。
    // 所以 "%d%%" 会先放入整数 80，再显示一个 %，最终输出 80%。
    printf("%d%%", 80);
    printf("\n");

    // --------------------------------------------------------------------
    // 补充练习 1：保留两位小数
    // --------------------------------------------------------------------
    printf("补充练习 1（保留两位小数）:");

    // %.2f 里的 .2 表示"小数点后保留 2 位"，3.5 显示成 3.50（不足的位数补 0）。
    printf("%.2f", (double)a / b);
    printf("\n");

    // --------------------------------------------------------------------
    // 补充练习 2：宽度和补零
    // --------------------------------------------------------------------
    printf("补充练习 2（宽度为两个空格，不足补零）：");

    // %02d 拆开看：2 是"最少占 2 个字符的宽度"，前面的 0 表示"不够宽时用 0 来补"。
    // 7 只有一位，所以补成 07。常用在显示时间，比如 07:05。
    printf("%02d", 7);
    printf("\n");

    // --------------------------------------------------------------------
    // 补充练习 3：宽度和左对齐
    // --------------------------------------------------------------------
    printf("补充练习 3（宽度为五个空格，左对齐）：");

    // %-5d 拆开看：5 是最少占 5 个字符的宽度，- 表示"左对齐"（内容靠左，不够的位置在右边补空格）。
    // 7 占 1 格，右边补 4 个空格，所以输出是 7 后面跟 4 个空格，再接 END,。
    // 后面故意接一个 END,，是为了能看出前面到底补了几个空格。
    printf("%-5dEND,", 7);
    printf("\n");

    // return 0：结束 main，把 0 交给系统，约定 0 表示"程序正常结束"。
    return 0;
}

